"""Generate the pigment metabolome-transfer build query (Track A of CGT-Metabolism).

Emits ``fig6_pigment_transfer.cql`` -- the UNION ALL of EXACTLY THREE datasets, the
minimum needed for the designed positive/negative control pair:

* ``BetaxanthinCachera2023Dataset``  (``metabolism``) -- betaxanthin, whose direct
  precursor TYROSINE is one of Mulleder's 19 amino acids, and whose cassette carries the
  feedback-resistant ARO4-K229L / ARO7-G141S alleles that exist to push tyrosine flux.
* ``CarotenoidOzaydin2013Dataset``   (``global``)     -- beta-carotene, whose precursors
  (acetyl-CoA, GGPP) are measured NOWHERE genome-wide. The negative control.
* ``AminoAcidMulleder2016Dataset``   (``metabolism``) -- the 19-AA metabolome, the
  candidate auxiliary task.

Deliberately EXCLUDED (vs ``generate_fig6_cql.py``, which unions seven datasets): the
isobutanol screen + validated subset, Zelezniak, and da Silveira. They are not part of
the tyrosine contrast, and every extra block adds rows the split has to carry.

DELETION-in-gene_set filter, NOT all-in-gene_set -- carried over unchanged from
``generate_fig6_cql.py`` and load-bearing here. The pigment strains carry heterologous
biosynthesis cassettes as ``gene_addition`` perturbations (beta-carotene 3 genes;
betaxanthin 2 heterologous genes + 2 feedback-resistant S288C alleles), and the
heterologous names are NOT in the S288C ``gene_set``. Requiring ALL perturbations in
``gene_set`` -- the Fig-3 clause -- would drop every pigment record. Each block instead
requires only that every DELETION perturbation's gene is in ``gene_set`` (so the deleted
locus is a real graph node the ``Perturbation`` processor can index) and that at least
one deletion exists (so no strain is all-cassette / effectively WT).

That filter is what lets the cassette survive the query; ``DeletionKeyedGenotypeAggregator``
is what lets it stop blocking co-location downstream (see query_fig6_pigment_transfer.py).

media / temperature are MATCHed but NOT filtered -- SC (Cachera), SC-URA (Ozaydin) and
SM (Mulleder), all at 30 C.
"""

from __future__ import annotations

import os.path as osp

# (dataset_id, graph_level) -- graph_level verified against the live DB.
BLOCKS: list[tuple[str, str]] = [
    ("BetaxanthinCachera2023Dataset", "metabolism"),  # MetabolitePhenotype, 1 key
    ("CarotenoidOzaydin2013Dataset", "global"),  # VisualScorePhenotype, ordinal
    ("AminoAcidMulleder2016Dataset", "metabolism"),  # MetabolitePhenotype, 19 keys
]


def _block(dataset_id: str, graph_level: str) -> str:
    """Return one dataset ``MATCH ... RETURN e, ref`` block (deletion-in-gene_set)."""
    return f"""// {dataset_id} (graph_level '{graph_level}')
MATCH (dataset:Dataset)<-[:ExperimentMemberOf]-(e:Experiment)
WHERE dataset.id = '{dataset_id}'
MATCH (e)<-[:GenotypeMemberOf]-(g:Genotype)
MATCH (g)<-[:PerturbationMemberOf]-(p:Perturbation)
MATCH (e)<-[:ExperimentReferenceOf]-(ref:ExperimentReference)
MATCH (e)<-[:PhenotypeMemberOf]-(phen:PhenotypicFeature)
MATCH (e)<-[:EnvironmentMemberOf]-(env:Environment)
MATCH (env)<-[:MediaMemberOf]-(m:Media)
MATCH (env)<-[:TemperatureMemberOf]-(t:Temperature)
WHERE phen.graph_level = '{graph_level}'
 AND ALL(dp IN [(g)<-[:PerturbationMemberOf]-(pert) | pert]
 WHERE (NOT dp.perturbation_type ENDS WITH 'deletion')
 OR dp.systematic_gene_name IN $gene_set)
 AND SIZE([(g)<-[:PerturbationMemberOf]-(pert)
 WHERE pert.perturbation_type ENDS WITH 'deletion' | pert]) > 0
WITH DISTINCT e, ref
 ORDER BY e.id
RETURN e, ref"""


def main() -> None:
    """Write ``queries/fig6_pigment_transfer.cql``."""
    here = osp.dirname(osp.abspath(__file__))
    qdir = osp.abspath(osp.join(here, "..", "queries"))
    header = (
        "// Pigment metabolome-transfer build (CGT-Metabolism Track A): betaxanthin\n"
        "// (Cachera 2023) + beta-carotene visual score (Ozaydin 2013) + the 19-AA\n"
        "// metabolome (Mulleder 2016). deletion-in-gene_set filter keeps the\n"
        "// heterologous cassette additions; >=1 deletion required.\n"
        "// Generated by\n"
        "// experiments/019-simb-multimodal/scripts/generate_fig6_pigment_transfer_cql.py"
    )
    body = "\n\nUNION ALL\n\n".join(_block(*b) for b in BLOCKS)
    out = osp.join(qdir, "fig6_pigment_transfer.cql")
    with open(out, "w") as f:
        f.write(f"{header}\n\n{body}\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
