def sha256(path: str) -> str:
    """sha256 of a file."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def f3(x: float) -> str:
    """Three decimals, a real minus sign."""
    s = f"{x:.3f}"
    return s.replace("-", "$-$") if s.startswith("-") else s


def signed3(x: float) -> str:
    """Three decimals with an explicit sign."""
    return ("$+$" if x >= 0 else "$-$") + f"{abs(x):.3f}"


def intc(n: int) -> str:
    """Integer with a LaTeX thousands separator."""
    return f"{n:,}".replace(",", "{,}")


def compositions(total: int, parts: int) -> Iterator[tuple[int, ...]]:
    """Every tuple of ``parts`` non-negative integers summing to ``total``."""
    if parts == 1:
        yield (total,)
        return
    for first in range(total + 1):
        for rest in compositions(total - first, parts - 1):
            yield (first, *rest)


def expected_weights(
    counts: list[int], batch: int
) -> tuple[list[float], list[float], list[float], list[float]]:
    """Exact expectations over one batch for the records and the balanced sampler.

    Returns ``(p_present, w_equal, w_records, w_balanced_equal)`` per dataset:
    the probability that the dataset has a record in a records-sampler batch, the
    expected weight of its mean loss under equal weighting (1 / datasets present) and
    under record weighting (its records / batch), and the expected equal weight under the
    balanced sampler (each slot a dataset uniformly).
    """
    n = sum(counts)
    k = len(counts)
    denom = comb(n, batch)
    p_present = [0.0] * k
    w_equal = [0.0] * k
    w_records = [0.0] * k
    w_bal = [0.0] * k
    for comp in compositions(batch, k):
        num = 1
        for c, m in zip(counts, comp, strict=True):
            num *= comb(c, m)
        p_hyp = num / denom
        coef = factorial(batch)
        for m in comp:
            coef //= factorial(m)
        p_mult = coef / k**batch
        present = [m > 0 for m in comp]
        n_present = sum(present)
        for s in range(k):
            if present[s]:
                p_present[s] += p_hyp
                w_equal[s] += p_hyp / n_present
                w_bal[s] += p_mult / n_present
            w_records[s] += p_hyp * comp[s] / batch
    return p_present, w_equal, w_records, w_bal


def measured_table(win: dict, lin: dict) -> tuple[str, dict[str, str]]:
    """t1: window means of the four complete runs against the linear bars."""
    runs = win["runs"]
    parts = lin["parts"]

    def mean(run: str, key: str) -> float | None:
        m = runs[run]["means"].get(key)
        return None if m is None else float(m["mean"])

    def fold(part: str, panel: str, model: str, f: str) -> float:
        return float(
            parts[part]["panels"][panel]["folds"][f]["models"][model][
                "median_gene_pearson"
            ]
        )

    vai = parts["vaishnav"]["models"]["kmer_1_6_ridge"]["folds"]
    dbl = parts["doubles"]["rungs"]
    rows = [
        (
            "Kemmeren 2014, median per-gene Pearson $r$ over 140 held-out deletion strains",
            "val/kemmeren/pearson_per_gene_median",
            f3(fold("deletion_kemmeren", "kemmeren", "ridge_composite", "1")),
            f3(fold("deletion_kemmeren", "kemmeren", "ridge_composite", "0")),
            "ridge, composite token of the deleted gene",
        ),
        (
            "Sameith 2015 doubles, median over 72 doubles of the centered per-double "
            "Pearson $r$ (6{,}127 genes)",
            "val/doubles/pearson_per_strain_centered_median",
            f3(dbl["additive_Mx_plus_My"]["all_median_unit_centered_pearson"])
            + " / "
            + f3(dbl["fitted_a_Mx_b_My_c_loo"]["all_median_unit_centered_pearson"]),
            "same set (split B)",
            "additive measured / fitted, leave one out",
        ),
        (
            "Messner 2023, median per-gene Pearson $r$ over 441 held-out deletion genes",
            "val/messner/pearson_per_gene_median",
            f3(fold("deletion_messner", "messner", "ridge_composite", "1")),
            f3(fold("deletion_messner", "messner", "ridge_composite", "0")),
            "ridge, composite token of the deleted gene",
        ),
        (
            "Caudal 2024, median per-gene Pearson $r$ over 189 held-out isolates",
            "val/caudal/pearson_per_gene_median",
            f3(fold("isolates", "caudal", "gblup_kinship", "1")),
            f3(fold("isolates", "caudal", "gblup_kinship", "0")),
            "GBLUP, kinship from gene-level calls",
        ),
        (
            "Muenzner 2024 protein, median per-gene Pearson $r$ over 159 held-out isolates",
            "val/muenzner/pearson_per_gene_median",
            f3(fold("isolates", "muenzner", "gblup_kinship", "1")),
            f3(fold("isolates", "muenzner", "gblup_kinship", "0")),
            "GBLUP, kinship from gene-level calls",
        ),
        (
            "Vaishnav 2022, Pearson $r$ over held-out promoters (runs: 2{,}000 of 14{,}232; "
            "ladder: all)",
            "val/vaishnav/pearson",
            f3(float(vai["1"]["pearson"])),
            f3(float(vai["0"]["pearson"])),
            "ridge, k-mer counts ($k$ 1 to 6)",
        ),
    ]
    lines = []
    for label, key, bar1, bar0, model in rows:
        vals = [mean(run, key) for run, _ in ARM_ORDER]
        best = max(v for v in vals if v is not None)
        cells = []
        for v in vals:
            if v is None:
                cells.append("--")
            elif v == best:
                cells.append(r"\textbf{" + f3(v) + "}")
            else:
                cells.append(f3(v))
        lines.append(" & ".join([label, *cells, bar1, bar0, model]) + r" \\")
    tr = win["transfer_kemmeren"]
    lines.append(r"\midrule")
    lines.append(
        " & ".join(
            [
                "Transfer on Kemmeren 2014, joint minus alone at 317{,}300 optimizer steps",
                "0 (reference)",
                signed3(tr["joint_9_hlgauss_equal"]),
                signed3(tr["joint_9_balanced_hlgauss_equal"]),
                signed3(tr["joint_9_pinball_equal"]),
                "--",
                "--",
                "rule: mean gain $\\geq 0.02$, 5 of 6 seeds up",
            ]
        )
        + r" \\"
    )
    macros = {
        "TransferRecords": signed3(tr["joint_9_hlgauss_equal"]),
        "TransferBalanced": signed3(tr["joint_9_balanced_hlgauss_equal"]),
        "TransferPinball": signed3(tr["joint_9_pinball_equal"]),
    }
    return "\n".join(lines) + "\n", macros


def share_table(meta: dict, val_cap: int) -> tuple[str, dict[str, str]]:
    """t2: training records and expected loss weights per dataset."""
    counts = [int(meta["counts"][s]["train"]) for s, _, _ in DATASETS]
    vals = [int(meta["counts"][s]["val"]) for s, _, _ in DATASETS]
    n = sum(counts)
    p_present, w_eq, w_rec, w_bal = expected_weights(counts, BATCH)
    lines = []
    for i, (_short, name, level) in enumerate(DATASETS):
        scored = min(vals[i], val_cap)
        lines.append(
            " & ".join(
                [
                    name,
                    level,
                    intc(counts[i]),
                    intc(scored)
                    + ("" if scored == vals[i] else f" of {intc(vals[i])}"),
                    f"{100 * counts[i] / n:.1f}",
                    f"{p_present[i]:.3f}",
                    f"{w_eq[i]:.3f}",
                    f"{w_rec[i]:.3f}",
                    f"{w_bal[i]:.3f}",
                ]
            )
            + r" \\"
        )
    lines.append(r"\midrule")
    lines.append(
        " & ".join(
            [
                "All nine",
                "",
                intc(n),
                intc(sum(min(v, val_cap) for v in vals)),
                "100.0",
                "",
                f"{sum(w_eq):.3f}",
                f"{sum(w_rec):.3f}",
                f"{sum(w_bal):.3f}",
            ]
        )
        + r" \\"
    )
    vi = [s for s, _, _ in DATASETS].index("vaishnav")
    gene_frac = 1 - counts[vi] / n
    macros = {
        "NTrain": intc(n),
        "NVaishnavTrain": intc(counts[vi]),
        "VaishnavPct": f"{100 * counts[vi] / n:.1f}",
        "GeneRecordsPerBatch": f"{BATCH * gene_frac:.2f}",
        "VaishnavWeightEqual": f"{w_eq[vi]:.3f}",
        "VaishnavWeightRecords": f"{w_rec[vi]:.3f}",
        "KemmerenWeightEqual": f"{w_eq[0]:.3f}",
        "KemmerenPresent": f"{p_present[0]:.3f}",
        "BalancedWeight": f"{w_bal[0]:.3f}",
        "StepsPerEpochJoint": intc(-(-n // BATCH)),
        "StepsPerEpochKemmeren": intc(-(-counts[0] // BATCH)),
    }
    return "\n".join(lines) + "\n", macros


def runs_table(win: dict) -> str:
    """t3: one row per overnight run with its W&B link."""
    lines = []
    for run, info in win["runs"].items():
        w0, w1 = info["window"]
        n_eval = (
            max(m["n_evaluations"] for m in info["means"].values())
            if info["means"]
            else 0
        )
        lines.append(
            " & ".join(
                [
                    JOB_OF_RUN[run],
                    r"\href{" + f"{WANDB}/{run}" + r"}{\texttt{" + run + "}}",
                    r"\texttt{" + info["arm_label"].replace("_", r"\_") + "}",
                    f"{intc(info['epochs_reached'])} of {intc(info['n_epochs'])}",
                    f"{intc(w0)} to {intc(w1)}",
                    str(n_eval) if info["complete"] else "window not reached",
                ]
            )
            + r" \\"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write every table, the macros and the provenance record."""
    load_dotenv()
    results = osp.join(EXP_DIR, "results")
    win_path = osp.join(results, "overnight_2026_10_22_window_means.json")
    lin_path = osp.join(results, "linear_evals_043.json")
    meta_path = osp.join(
        os.environ["DATA_ROOT"],
        "data/torchcell/experiments",
        EXPERIMENT,
        "train_043_prep/prep_v1_routeA/meta.json",
    )
    conf_path = osp.join(EXP_DIR, "conf", "train_043_default.yaml")
    with open(win_path) as f:
        win = json.load(f)
    with open(lin_path) as f:
        lin = json.load(f)
    with open(meta_path) as f:
        meta = json.load(f)
    with open(conf_path) as f:
        val_cap = int(yaml.safe_load(f)["data"]["val_max_records_per_dataset"])

    os.makedirs(OUT, exist_ok=True)
    t1, m1 = measured_table(win, lin)
    t2, m2 = share_table(meta, val_cap)
    t3 = runs_table(win)
    src1 = (
        "results/overnight_2026_10_22_window_means.json, results/linear_evals_043.json"
    )
    src2 = "train_043_prep/prep_v1_routeA/meta.json (job 6134), conf/train_043_default.yaml"
    for name, body, src in [
        ("t1-measured-rows.tex", t1, src1),
        ("t2-batch-share-rows.tex", t2, src2),
        ("t3-runs-rows.tex", t3, "results/overnight_2026_10_22_window_means.json"),
    ]:
        with open(osp.join(OUT, name), "w") as f:
            # the closing rule lives in the generated file: \input is not expandable,
            # so a \bottomrule after it in the tabular is a misplaced \noalign
            f.write(HEADER.format(src=src) + body + "\\bottomrule\n")
    with open(osp.join(OUT, "macros.tex"), "w") as f:
        f.write(HEADER.format(src=f"{src1}, {src2}"))
        for k, v in {**m1, **m2}.items():
            f.write(f"\\newcommand{{\\td{k}}}{{{v}}}\n")
    prov = {
        "generated_by": "experiments/043-expression-proteome-morphology/scripts/"
        "training_design_043_tables.py",
        "inputs": {p: sha256(p) for p in (win_path, lin_path, meta_path, conf_path)},
        "batch_size": BATCH,
    }
    with open(osp.join(OUT, "provenance.json"), "w") as f:
        json.dump(prov, f, indent=1)
        f.write("\n")
    print(f"wrote {OUT}")
    for k, v in {**m1, **m2}.items():
        print(f"  {k} = {v}")


if __name__ == "__main__":
    main()
