def _scores(scores: pd.DataFrame, subset: str = "all") -> pd.DataFrame:
    s = scores[scores["subset"] == subset].copy()
    s["order"] = s["rule"].map({r: i for i, r in enumerate(RULE_ORDER)})
    return s.sort_values(["call", "order"], ascending=[False, True])


def t6_growth(scores: pd.DataFrame) -> None:
    rows = []
    for call in ("served", "software"):
        s = _scores(scores)
        s = s[s["call"] == call]
        acc = mark_best(list(s["accuracy"]), [f3(v) for v in s["accuracy"]])
        auc = mark_best(list(s["auroc"]), [f3(v) for v in s["auroc"]])
        for i, (_, r) in enumerate(s.iterrows()):
            rows.append(
                [
                    RULE_LABEL[r["rule"]],
                    call,
                    f3(r["tau"]),
                    str(int(r["tp"])),
                    str(int(r["fp"])),
                    str(int(r["tn"])),
                    str(int(r["fn"])),
                    acc[i],
                    auc[i],
                ]
            )
    write_table(
        "t6-growth-scores.tex",
        tabular(
            "llrrrrrrr",
            [
                [
                    "Reference rule",
                    "Growth",
                    r"$\tau$",
                    "TP",
                    "FP",
                    "TN",
                    "FN",
                    "Accuracy",
                    "AUROC",
                ],
                ["", "call", "(fitness)", "(n)", "(n)", "(n)", "(n)", "(fraction)", ""],
            ],
            rows,
        ),
    )


