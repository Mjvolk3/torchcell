"""Index every W&B run behind the 027 decision, and emit the hyperlinked table for notes-tex.

Reads the 72 per-worker result files that ``analyze_bxfx.py`` reads, so the table and the
decision are built from the same records. Writes ``results/wandb_run_index.json`` and the
LaTeX table ``notes-tex/027-metabolic-flux-module/tables/wandb_runs_027.tex`` (seed rows,
arm columns, each cell the run id linked to its W&B page).

Run from the repository root:

    python experiments/027-betaxanthin-metabolic/scripts/wandb_run_index.py
"""

from __future__ import annotations

import json
from pathlib import Path

from pydantic import BaseModel

REPO_ROOT = Path(__file__).resolve().parents[3]
RESULTS = REPO_ROOT / "experiments" / "027-betaxanthin-metabolic" / "results"
TABLE_OUT = (
    REPO_ROOT / "notes-tex" / "027-metabolic-flux-module" / "tables" / "wandb_runs_027.tex"
)
INDEX_OUT = RESULTS / "wandb_run_index.json"

ARM_ORDER = ["pooled", "flux_off", "flux_free", "flux_anchored", "null_pooled", "null_anchored"]


class RunRecord(BaseModel):
    arm: str
    seed: int
    worker: int
    wandb_run_id: str
    wandb_url: str
    test_spearman_pinned: float
    select_epoch: int


class RunIndex(BaseModel):
    project_url: str
    n_runs: int
    runs: list[RunRecord]


def tex_escape(s: str) -> str:
    return s.replace("_", "\\_")


def load_runs() -> list[RunRecord]:
    runs: list[RunRecord] = []
    for path in sorted(RESULTS.glob("bxfx_w*.json")):
        payload = json.loads(path.read_text())
        for run in payload["runs"]:
            runs.append(
                RunRecord(
                    arm=run["cell"]["arm"],
                    seed=int(run["cell"]["seed"]),
                    worker=int(payload["worker"]),
                    wandb_run_id=run["wandb_run_id"],
                    wandb_url=run["wandb_url"],
                    test_spearman_pinned=float(run["test"]["pinned"]["spearman"]),
                    select_epoch=int(run["select_epoch"]),
                )
            )
    return sorted(runs, key=lambda r: (r.seed, ARM_ORDER.index(r.arm)))


def project_url(runs: list[RunRecord]) -> str:
    urls = {r.wandb_url.rsplit("/runs/", 1)[0] for r in runs}
    if len(urls) != 1:
        raise ValueError(f"runs span more than one W&B project: {sorted(urls)}")
    return urls.pop()


def write_table(index: RunIndex) -> None:
    by_cell = {(r.seed, r.arm): r for r in index.runs}
    seeds = sorted({r.seed for r in index.runs})
    arms = [a for a in ARM_ORDER if any(r.arm == a for r in index.runs)]
    for seed in seeds:
        for arm in arms:
            if (seed, arm) not in by_cell:
                raise ValueError(f"grid is not balanced: seed {seed} has no {arm} run")

    lines = [
        "%% GENERATED by experiments/027-betaxanthin-metabolic/scripts/wandb_run_index.py",
        "%% from results/bxfx_w*.json. Do not edit by hand; rerun the script.",
        "%% SOURCE: experiments/027-betaxanthin-metabolic/results/bxfx_w*.json"
        " (wandb_run_id, wandb_url per run), the same files analyze_bxfx.py reads.",
        "\\begin{table}[H]",
        "  \\centering",
        "  \\footnotesize",
        "  \\caption[W\\&B runs behind the 027 decision]{Every training run behind"
        f" Tables~\\ref{{tab:armresults}} and \\ref{{tab:decision}}, {index.n_runs} in all,"
        " one per seed and arm. Each cell is the W\\&B run id, linked to the run page in"
        f" project \\href{{{index.project_url}}}{{\\texttt{{{tex_escape(index.project_url.split('/')[-1])}}}}}"
        " (entity \\texttt{zhao-group}), which holds the per-epoch training loss,"
        " validation loss, validation Pearson and the selected epoch.}",
        "  \\label{tab:wandb-runs-027}",
        "  \\begin{tabular}{@{}r" + "l" * len(arms) + "@{}}",
        "    \\hline",
        "    Seed & " + " & ".join(f"\\texttt{{{tex_escape(a)}}}" for a in arms) + " \\\\",
        "    \\hline",
    ]
    for seed in seeds:
        cells = [
            f"\\href{{{by_cell[(seed, a)].wandb_url}}}{{\\texttt{{{by_cell[(seed, a)].wandb_run_id}}}}}"
            for a in arms
        ]
        lines.append(f"    {seed} & " + " & ".join(cells) + " \\\\")
    lines += ["    \\hline", "  \\end{tabular}", "\\end{table}", ""]
    TABLE_OUT.parent.mkdir(parents=True, exist_ok=True)
    TABLE_OUT.write_text("\n".join(lines))


def main() -> None:
    runs = load_runs()
    index = RunIndex(project_url=project_url(runs), n_runs=len(runs), runs=runs)
    INDEX_OUT.write_text(index.model_dump_json(indent=2))
    write_table(index)
    print(f"{index.n_runs} runs in {index.project_url}")
    print(f"wrote {INDEX_OUT}")
    print(f"wrote {TABLE_OUT}")


if __name__ == "__main__":
    main()
