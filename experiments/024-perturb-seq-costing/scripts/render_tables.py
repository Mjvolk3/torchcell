def t6_barcode() -> str:
    out = [
        "## Table 6. Barcode collision rate",
        "",
        "Gaisser's formula $100(1-((B-1)/B)^{C-1})$, $B = 96^R \\times S$. "
        "**The sublibrary index $S$ is a real barcode dimension** -- cells split "
        "into sublibraries after the last in-cell ligation.",
        "",
        "| Rounds | Sublibraries | Barcode space | @ 45k cells | @ 480k cells | @ 3M cells | @ 12M cells |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for rounds in (3, 4):
        for sub in (1, 24, 96):
            B = MD.barcode_space(rounds=rounds, sublibraries=sub)
            cells = [45_000, 480_000, 3_000_000, 12_000_000]
            rates = " | ".join(
                f"{100 * MD.collision_rate(c, B):.2f}%" for c in cells
            )
            bold = "**" if (rounds == 4 and sub == 24) else ""
            out.append(
                f"| {bold}{rounds}{bold} | {bold}{sub}{bold} | {bold}{B:,}{bold} | {rates} |"
            )
    out += [
        "",
        "> A genome-scale screen barcodes ~12M cells. Three rounds cannot reach "
        "1% at that scale even across 96 sublibraries; four rounds reach 0.59% "
        "with 24. The 4th plate costs ~$2,566 once.",
        "",
    ]
    return "\n".join(out)


def t7_cells_per_perturbation() -> str:
    target = CM.PSEUDOBULK_TIERS["standard (Brettner's own 500-cell heuristic)"]
    depths = [
        ("SPLiT-seq as published", 410),
        ("SPLiT-seq + rRNA depletion", 861),
        ("10x v2 (Jariani)", 894),
        ("10x v3 (Jackson)", 2000),
        ("10x v3 (Boocock)", 4036),
    ]
    out = [
        "## Table 7. Cells per perturbation",
        "",
        "Two independent constraints: a biological floor of "
        f"**{CM.CELLS_FLOOR} cells** (field standard, stated by Brandner) and a "
        f"pseudobulk depth target of **{target:,.0f} mRNA UMIs**. The larger binds.",
        "",
        "| Method | mRNA UMIs/cell | Cells/perturbation | Binding constraint | Cells for 6,000 genes |",
        "| --- | ---: | ---: | --- | ---: |",
    ]
    for name, d in depths:
        n = CM.cells_per_perturbation(d, target)
        binding = "biological floor" if n == CM.CELLS_FLOOR else "sequencing depth"
        out.append(f"| {name} | {d:,} | **{n}** | {binding} | {n * 6000:,} |")
    out += [
        "",
        "**Detection ladder** -- what a pseudobulk budget reaches, given ~16 UMIs "
        "of a gene are needed to call a 2-fold change at 80% power:",
        "",
        "| Tier | Pseudobulk UMIs / perturbation | Lowest detectable gene, 2-fold | ... at 1.5-fold |",
        "| --- | ---: | ---: | ---: |",
    ]
    for tier, t in CM.PSEUDOBULK_TIERS.items():
        import math

        out.append(
            f"| {tier} | {t:,.0f} | "
            f"{CM.min_copies_per_cell_detectable(t, log2_fc=1.0):.1f} copies/cell | "
            f"{CM.min_copies_per_cell_detectable(t, log2_fc=math.log2(1.5)):.1f} copies/cell |"
        )
    out.append("")
    return "\n".join(out)


