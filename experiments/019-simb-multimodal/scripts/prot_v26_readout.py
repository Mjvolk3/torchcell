"""Readout of the proteome alignment round v26 (project torchcell_019_prot_v26).

The knockout proteome (Messner 2023, the full fig3_proteome store) from the genotype
alone on the v21 small trunk at batch 128, 600 epochs, the S_prot arm as the reference
against the latent alignment term (torchcell/losses/latent_align.py) at lambda 0.1 and 1
on z_S. A CELL is the arm plus its recipe tags (ref, align<lambda>, src<source>); the
runs of a cell differ by split seed.

  window   the registered window, the mean of val/proteome/pearson_per_feature over
           epochs 500 to 599 (declared 2026-10-12 with the launch, before any run was
           read); a run short of epoch 599 is PARTIAL and reports the mean over its last
           100 epochs under `partial_window`, never under `window`;
  paired   the per-split difference of each alignment cell against the reference.

Writes results/prot_v26_readout.json and notes-tex/figure-3-gate/tables/prot_v26.tex.

    python experiments/019-simb-multimodal/scripts/prot_v26_readout.py
"""

from __future__ import annotations

import json
import os.path as osp
import re
import statistics as st
from concurrent.futures import ThreadPoolExecutor
from typing import Any

import wandb

ENTITY = "zhao-group"
PROJECT = "torchcell_019_prot_v26"
VAL = "val/proteome/pearson_per_feature"
TRAIN = "traineval/proteome/pearson_per_feature"
ALIGN = "val/latent_align/loss"
WINDOW = (500, 599)
ARM = "S_prot"
SPLIT_RE = re.compile(r"split(\d+)")
VARIANT_RE = re.compile(r"ref|align[0-9e.-]+|src[a-z_]+")
REPO = osp.abspath(osp.join(osp.dirname(__file__), "..", "..", ".."))
RESULTS = osp.join(osp.dirname(osp.dirname(osp.abspath(__file__))), "results")
TABLES = osp.join(REPO, "notes-tex", "figure-3-gate", "tables")


def series(run: Any, key: str) -> list[tuple[int, float]]:
    return [
        (int(x["epoch"]), float(x[key]))
        for x in run.history(keys=["epoch", key], pandas=False, samples=100000)
        if x.get(key) is not None
    ]


def read_run(run: Any) -> dict[str, Any] | None:
    if ARM not in run.tags:
        return None
    sm = next((SPLIT_RE.fullmatch(t) for t in run.tags if SPLIT_RE.fullmatch(t)), None)
    if sm is None:
        return None
    variants = sorted(t for t in run.tags if VARIANT_RE.fullmatch(t))
    val = series(run, VAL)
    train = series(run, TRAIN)
    align = series(run, ALIGN)
    last = max((e for e, _ in val), default=-1)
    if last < 0:
        return None
    finished = last >= WINDOW[1]
    in_window = [v for e, v in val if WINDOW[0] <= e <= WINDOW[1]]
    tail = [v for e, v in val if e > last - 100]
    return {
        "id": run.id,
        "url": run.url,
        "cell": "_".join([ARM, *variants]),
        "variants": variants,
        "split": int(sm.group(1)),
        "last_epoch": last,
        "finished": finished,
        "window": st.mean(in_window) if finished and in_window else None,
        "partial_window": None if finished else (st.mean(tail) if tail else None),
        "roll_max": max(v for _, v in val),
        "train_last": train[-1][1] if train else None,
        "align_last": align[-1][1] if align else None,
        "ladder": {str(k): st.mean([v for e, v in val if k - 10 < e <= k + 10]) for k in (100, 200, 300, 400, 500, 599) if any(k - 10 < e <= k + 10 for e, _ in val)},
    }


def summarize(runs: list[dict[str, Any]], ref: dict[int, float]) -> dict[str, Any]:
    fin = [r for r in runs if r["finished"]]
    w = [r["window"] for r in fin]
    pairs = [(r["window"] - ref[r["split"]]) for r in fin if r["split"] in ref]
    return {
        "n": len(runs),
        "n_finished": len(fin),
        "window_mean": st.mean(w) if w else None,
        "window_sd": st.stdev(w) if len(w) > 1 else None,
        "paired_delta_mean": st.mean(pairs) if pairs else None,
        "paired_n_up": sum(p > 0 for p in pairs),
        "paired_n": len(pairs),
        "train_last_mean": st.mean(tl) if (tl := [r["train_last"] for r in runs if r["train_last"] is not None]) else None,
        "align_last_mean": st.mean(al) if (al := [r["align_last"] for r in runs if r["align_last"] is not None]) else None,
        "partial_window_mean": st.mean(pw) if (pw := [r["partial_window"] for r in runs if r["partial_window"] is not None]) else None,
    }


def table(cells: dict[str, dict[str, Any]]) -> str:
    rows = sorted(cells.items(), key=lambda kv: -(kv[1]["window_mean"] if kv[1]["window_mean"] is not None else -1))
    best = max((c["window_mean"] for c in cells.values() if c["window_mean"] is not None), default=None)
    out = [
        "%% GENERATED by experiments/019-simb-multimodal/scripts/prot_v26_readout.py. Do not edit by hand.",
        "%% SOURCE: experiments/019-simb-multimodal/results/prot_v26_readout.json",
        "\\begin{table}[htbp]",
        "  \\centering",
        "  \\footnotesize",
        "  \\caption[Round v26, proteome alignment]{Round v26 on the knockout proteome (Messner 2023, every "
        "proteome genotype), genotype only, v21 small trunk at batch 128, 600 epochs. The window is the "
        "mean validation Pearson per feature over epochs 500 to 599 of finished runs; the paired "
        "difference is against the reference on the same split seed; the training fit is the eval-mode "
        "training Pearson at the last logged epoch. Bold, the best window mean. "
        "\\src{experiments/019-simb-multimodal/scripts/prot_v26_readout.py}}",
        "  \\label{tab:prot-v26}",
        "  \\begin{tabular}{@{}lrrrrr@{}}",
        "    \\toprule",
        "    cell & runs (n) & finished (n) & window mean val Pearson per feature (s.d.) & paired difference vs reference, mean (splits up) & train Pearson per feature, last epoch (mean) \\\\",
        "    \\midrule",
    ]
    for name, c in rows:
        w = "partial" if c["window_mean"] is None else f"{c['window_mean']:.3f}" + (f" ({c['window_sd']:.3f})" if c["window_sd"] is not None else "")
        if best is not None and c["window_mean"] == best:
            w = f"\\textbf{{{w}}}"
        d = "" if c["paired_delta_mean"] is None else f"{c['paired_delta_mean']:+.3f} ({c['paired_n_up']} of {c['paired_n']})"
        tr = "" if c["train_last_mean"] is None else f"{c['train_last_mean']:.2f}"
        out.append(f"    \\texttt{{{name.replace('_', chr(92) + '_')}}} & {c['n']} & {c['n_finished']} & {w} & {d} & {tr} \\\\")
    out += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    return "\n".join(out)


def main() -> None:
    api = wandb.Api(timeout=120)
    runs = list(api.runs(f"{ENTITY}/{PROJECT}", per_page=500))
    with ThreadPoolExecutor(8) as pool:
        rows = [r for r in pool.map(read_run, runs) if r is not None]
    cells: dict[str, list[dict[str, Any]]] = {}
    for r in rows:
        cells.setdefault(r["cell"], []).append(r)
    ref = {r["split"]: r["window"] for r in cells.get(f"{ARM}_ref", []) if r["window"] is not None}
    summary = {name: summarize(rs, ref) for name, rs in cells.items()}
    for name in sorted(summary, key=lambda n: -(summary[n]["window_mean"] or -1)):
        c = summary[name]
        w = "partial" if c["window_mean"] is None else f"{c['window_mean']:.3f} +/- {c['window_sd'] if c['window_sd'] is not None else 0:.3f}"
        d = "" if c["paired_delta_mean"] is None else f"paired {c['paired_delta_mean']:+.3f} ({c['paired_n_up']}/{c['paired_n']} up)"
        print(f"{name:28s} n {c['n']:2d} fin {c['n_finished']:2d} window {w:18s} {d:26s} train {None if c['train_last_mean'] is None else round(c['train_last_mean'], 3)} align {None if c['align_last_mean'] is None else round(c['align_last_mean'], 3)}")
    out = {"generated_by": "experiments/019-simb-multimodal/scripts/prot_v26_readout.py", "project": PROJECT, "window": WINDOW, "cells": summary, "runs": rows}
    with open(osp.join(RESULTS, "prot_v26_readout.json"), "w") as f:
        json.dump(out, f, indent=1)
    with open(osp.join(TABLES, "prot_v26.tex"), "w") as f:
        f.write(table(summary))


if __name__ == "__main__":
    main()
