"""Turn the processing script into an executed notebook and its documentation page.

``ecoli_benchmark_processing.py`` is written in cells: a ``# %%`` line starts a code
cell and ``# %% [markdown]`` a text cell whose lines are comments. This script builds
the notebook, runs it in a Jupyter kernel from the repository root, drops what the
kernel wrote to standard error, and writes

- ``experiments/050-ecoli-benchmark/notebooks/ecoli_benchmark_processing.ipynb``
- ``docs/source/benchmark/ecoli/processing.md``

    python experiments/050-ecoli-benchmark/scripts/notebook_page.py \
        --jupyter-execute <jupyter-execute of an env with nbclient, ipykernel, torchcell>
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

SOURCE = Path("experiments/050-ecoli-benchmark/scripts/ecoli_benchmark_processing.py")
NOTEBOOK = Path(
    "experiments/050-ecoli-benchmark/notebooks/ecoli_benchmark_processing.ipynb"
)
PAGE = Path("docs/source/benchmark/ecoli/processing.md")
GITHUB = "https://github.com/Mjvolk3/torchcell/blob/main"


def cells(text: str) -> list[dict[str, Any]]:
    """The cells of a ``# %%`` script; the header before the first marker is dropped."""
    out: list[dict[str, Any]] = []
    for number, chunk in enumerate(text.split("\n# %%")[1:]):
        head, _, body = chunk.partition("\n")
        if head.strip() == "[markdown]":
            lines = [
                line[2:] if line.startswith("# ") else ""
                for line in body.strip("\n").split("\n")
            ]
            cell: dict[str, Any] = {"cell_type": "markdown", "source": "\n".join(lines)}
        else:
            cell = {
                "cell_type": "code",
                "source": body.strip("\n"),
                "outputs": [],
                "execution_count": None,
            }
        cell["metadata"] = {}
        cell["id"] = f"cell-{number:02d}"
        out.append(cell)
    return out


def text_of(value: str | list[str]) -> str:
    """A notebook field that is a string or a list of lines, as one string."""
    return value if isinstance(value, str) else "".join(value)


def main() -> None:
    """Build, execute and render the processing notebook."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--jupyter-execute", default="jupyter-execute")
    args = parser.parse_args()
    notebook: dict[str, Any] = {
        "cells": cells(SOURCE.read_text(encoding="utf-8")),
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    NOTEBOOK.parent.mkdir(parents=True, exist_ok=True)
    work = Path(".") / (NOTEBOOK.stem + ".run.ipynb")
    work.write_text(json.dumps(notebook, indent=1) + "\n", encoding="utf-8")
    env = dict(os.environ, PYTHONPATH=str(Path(".").resolve()))
    subprocess.run(
        [args.jupyter_execute, "--inplace", "--timeout=1800", work.name],
        env=env,
        check=True,
    )
    executed: dict[str, Any] = json.loads(work.read_text(encoding="utf-8"))
    work.unlink()
    for cell in executed["cells"]:
        cell["metadata"].pop("execution", None)
        if cell["cell_type"] != "code":
            continue
        merged: list[dict[str, Any]] = []
        for output in cell["outputs"]:
            if output["output_type"] != "stream" or output["name"] == "stderr":
                continue
            if merged:
                merged[-1]["text"] = text_of(merged[-1]["text"]) + text_of(
                    output["text"]
                )
            else:
                merged.append(output)
        cell["outputs"] = merged
    executed["metadata"] = notebook["metadata"]
    NOTEBOOK.write_text(json.dumps(executed, indent=1) + "\n", encoding="utf-8")

    stamp = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    parts = [
        f"<!-- Generated by {Path(__file__).as_posix().split('torchcell/')[-1]} "
        f"(run {stamp}). Do not edit by hand. -->",
        "",
        "```{note}",
        f"This page is the notebook [`{NOTEBOOK.name}`]({GITHUB}/{NOTEBOOK.as_posix()}) "
        f"with the outputs of one run. Its source is the script "
        f"[`{SOURCE.name}`]({GITHUB}/{SOURCE.as_posix()}).",
        "```",
        "",
    ]
    for cell in executed["cells"]:
        source = text_of(cell["source"])
        if cell["cell_type"] == "markdown":
            parts += [source, ""]
            continue
        parts += ["```python", source, "```", ""]
        for output in cell["outputs"]:
            parts += ["```text", text_of(output["text"]).rstrip("\n"), "```", ""]
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {NOTEBOOK} and {PAGE}")


if __name__ == "__main__":
    main()
