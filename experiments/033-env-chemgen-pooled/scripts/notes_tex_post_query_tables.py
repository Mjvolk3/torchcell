TABLES_DIR = osp.join(
    osp.dirname(EXPERIMENT_ROOT.rstrip("/")),
    "notes-tex",
    "033-post-query-analysis",
    "tables",
)
SCRIPT = "experiments/033-env-chemgen-pooled/scripts/notes_tex_post_query_tables.py"

#: Values the 031 documents state in prose, with where each is stated. Everything else
