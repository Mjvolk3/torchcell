def t1_runs(wells: pd.DataFrame) -> None:
    design = {
        "ex21": "single-agent titration, six inhibitors",
        "ex23": "combinations of one to six inhibitors",
        "ex26": "isobole grid, furfural x acetic acid",
        "ex27": "isobole grid, formic acid x acetic acid",
        "ex28": "isobole grid, 5-HMF x acetic acid",
    }
    dose_cols = [c for c in wells.columns if c.startswith("dose_g_per_l_")]
    rows = []
    for run, g in wells.groupby("run"):
        inhib = [c.split("_")[-1] for c in dose_cols if (g[c] > 0).any()]
        rows.append(
            [
                run,
                design[run],
                f1(g["duration_h"].max()),
                str(len(g)),
                str(int(g["grew"].sum())),
                str(len(inhib)),
                str(g["biological_replicate_id"].dropna().nunique()),
            ]
        )
    rows.append(
        ["all", "", "", str(len(wells)), str(int(wells["grew"].sum())), "6", ""]
    )
    write_table(
        "t1-runs.tex",
        tabular(
            "llrrrrr",
            [
                [
                    "Run",
                    "Design",
                    "Length",
                    "Wells",
                    "Grew",
                    "Inhibitors",
                    "Replicates",
                ],
                ["", "", "(h)", "(n)", "(n)", "(n)", "(n)"],
            ],
            rows,
        ),
    )


def t2_growth_call(comb: pd.DataFrame) -> None:
    rows = []
    groups = [("1", [1]), ("2", [2]), ("3", [3]), ("4 to 6", [4, 5, 6])]
    for label, ns in groups:
        served = comb[(comb["call"] == "served") & comb["n_compounds"].isin(ns)]
        soft = comb[(comb["call"] == "software") & comb["n_compounds"].isin(ns)]
        g_s = served[served["grew"]]
        g_w = soft[soft["grew"]]
        rows.append(
            [
                label,
                str(len(served)),
                str(len(g_s)),
                str(len(g_w)),
                f3(g_s["observed_grown_mean"].mean()) if len(g_s) else "",
                f3(g_w["observed_grown_mean"].mean()) if len(g_w) else "",
            ]
        )
    served = comb[comb["call"] == "served"]
    soft = comb[comb["call"] == "software"]
    rows.append(
        [
            "all",
            str(len(served)),
            str(int(served["grew"].sum())),
            str(int(soft["grew"].sum())),
            "",
            "",
        ]
    )
    write_table(
        "t2-growth-call.tex",
        tabular(
            "lrrrrr",
            [
                [
                    "Inhibitors",
                    "Combinations",
                    "Grew,",
                    "Grew,",
                    "Mean fitness of",
                    "Mean fitness of",
                ],
                [
                    "(n)",
                    "(n)",
                    "served (n)",
                    "software (n)",
                    "grown, served",
                    "grown, software",
                ],
            ],
            rows,
        ),
    )


def t3_coverage(wells: pd.DataFrame, matrix: dict) -> None:
    prov = read_json("wetlab_provenance.json")
    mw = prov["molar_mass_g_per_mol"]
    ex23 = wells[(wells["run"] == "ex23") & (wells["n_compounds"] == 1)]
    best = {
        c["abbreviation"]: c
        for c in matrix["choices"]
        if c["version"] == "best_available"
    }
    source_label = {
        "measured_vanacloig_b002": "measured, build 002",
        "measured_hoepfner_hop": "measured, Hoepfner",
        "predicted_ridge_loco": "predicted, held out",
        "predicted_ridge_all32": "predicted, on 32",
    }
    rows = []
    for info in matrix["inhibitors"]:
        ab, name = info["abbreviation"], info["name"]
        dose = ex23[f"dose_g_per_l_{ab}"]
        dose = dose[dose > 0]
        d_gl = dose.iloc[0] if len(dose) else float("nan")
        van = info["vanacloig_name"]
        van_txt = (
            "none"
            if van is None
            else f"{SHORT.get(van, van)}, b{info['vanacloig_build']}"
        )
        ch = best[ab]
        rel = ch["measured_reliability"]
        rows.append(
            [
                SHORT[name],
                ab,
                f2(mw[ab]),
                f2(d_gl),
                f1(1000.0 * d_gl / mw[ab]),
                van_txt,
                "" if rel is None else f3(rel),
                source_label[ch["source"]],
            ]
        )
    write_table(
        "t3-coverage.tex",
        tabular(
            "llrrrlrl",
            [
                [
                    "Inhibitor",
                    "Short",
                    "$M$",
                    "ex23 dose",
                    "ex23 dose",
                    "Vanacloig",
                    "Replicate",
                    "Profile",
                ],
                [
                    "",
                    "",
                    r"(g mol$^{-1}$)",
                    r"(g L$^{-1}$)",
                    "(mM)",
                    "store",
                    "reliability",
                    "used",
                ],
                ["", "", "", "", "", "", "(Spearman)", ""],
            ],
            rows,
        ),
    )


