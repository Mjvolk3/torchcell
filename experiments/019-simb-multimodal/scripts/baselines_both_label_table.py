"""The twelve-seed sequence baselines on the both-label store, as one table.

Reads the per-seed files `expression_baselines_split.py` wrote for the fig3_proteome store
restricted to the strains carrying both labels (IGB job 2423302): the bilinear ridge (B2)
and the nearest-neighbor average (B3), ProtT5 and the model's composite stack, the cells
selected on validation, on validation and on test. These are the strains the v21 and v22
rounds train on (1,103 train, 125 validation, 121 test on split seed 0).

    python experiments/019-simb-multimodal/scripts/baselines_both_label_table.py

Writes results/baselines_both_label.json and notes-tex/figure-3-gate/tables/baselines_both_label.tex.
"""

from __future__ import annotations

import glob
import json
import os.path as osp
import statistics as st

REPO = osp.abspath(osp.join(osp.dirname(__file__), "..", "..", ".."))
RESULTS = osp.join(osp.dirname(osp.dirname(osp.abspath(__file__))), "results")
TABLES = osp.join(REPO, "notes-tex", "figure-3-gate", "tables")
DIRS = {
    "expression": "baselines_split_fig3_proteome_both_expression_log2_ratio_full",
    "proteome": "baselines_split_fig3_proteome_both_protein_abundance_full",
}
BASELINES = {"B2_bilinear": "bilinear ridge", "B3_neighbor_average": "neighbor average"}
EMBEDDINGS = {"prot_T5_all": "ProtT5", "model_stack": "composite stack", "random_1024": "random 1024"}


def main() -> None:
    out: dict = {"generated_by": "experiments/019-simb-multimodal/scripts/baselines_both_label_table.py", "rows": []}
    for head, d in DIRS.items():
        files = sorted(glob.glob(osp.join(RESULTS, d, "seed*.json")))
        J = [json.load(open(f)) for f in files]
        split = J[0]["split"]
        for B, bname in BASELINES.items():
            for emb, ename in EMBEDDINGS.items():
                val = [j[B]["by_embedding"][emb]["selected_on_val"]["val_pearson_per_feature"] for j in J]
                test = [j[B]["by_embedding"][emb]["selected_on_val"]["test_pearson_per_feature"] for j in J]
                out["rows"].append(
                    {
                        "head": head,
                        "baseline": bname,
                        "embedding": ename,
                        "n_seeds": len(J),
                        "val_mean": st.mean(val),
                        "val_sd": st.stdev(val),
                        "test_mean": st.mean(test),
                        "test_sd": st.stdev(test),
                        "n_train": split["n_train"],
                        "n_val": split["n_val"],
                        "n_test": split["n_test"],
                        "n_gene": split["n_gene"],
                    }
                )
    with open(osp.join(RESULTS, "baselines_both_label.json"), "w") as f:
        json.dump(out, f, indent=1)
    for r in out["rows"]:
        print(f"{r['head']:<11}{r['baseline']:<18}{r['embedding']:<16} val {r['val_mean']:.3f} ± {r['val_sd']:.3f}  test {r['test_mean']:.3f} ± {r['test_sd']:.3f}  (n={r['n_seeds']})")
    best = {}
    for r in out["rows"]:
        best.setdefault(r["head"], max((x for x in out["rows"] if x["head"] == r["head"]), key=lambda x: x["val_mean"]))
    lines = [
        "%% GENERATED by experiments/019-simb-multimodal/scripts/baselines_both_label_table.py. Do not edit by hand.",
        "%% SOURCE: results/baselines_split_fig3_proteome_both_expression_log2_ratio_full/seed*.json and",
        "%% results/baselines_split_fig3_proteome_both_protein_abundance_full/seed*.json (expression_baselines_split.py, IGB job 2423302)",
        "\\begin{table}[htbp]",
        "  \\centering",
        "  \\footnotesize",
        "  \\caption[Baselines on the both-label store]{Sequence baselines on the strains carrying both"
        " labels, the store v21 and v22 train on (1{,}103 train, 125 validation and 121 test strains on"
        " split seed 0; 6{,}169 expression and 1{,}850 proteome features). Pearson per feature across"
        " held-out strains, mean $\\pm$ sd over 12 split seeds, with the ridge strength, gene rank and"
        " neighbor count selected on validation. The best validation mean per head is bold."
        " \\src{experiments/019-simb-multimodal/scripts/baselines_both_label_table.py}}",
        "  \\label{tab:baselines-both-label}",
        "  \\begin{tabular}{@{}lllrr@{}}",
        "    \\toprule",
        "    head & baseline & embedding & validation Pearson & test Pearson \\\\",
        "    \\midrule",
    ]
    for r in out["rows"]:
        b = r is best[r["head"]]
        v = f"{r['val_mean']:.3f} $\\pm$ {r['val_sd']:.3f}"
        t = f"{r['test_mean']:.3f} $\\pm$ {r['test_sd']:.3f}"
        if b:
            v, t = f"\\textbf{{{v}}}", f"\\textbf{{{t}}}"
        lines.append(f"    {r['head']} & {r['baseline']} & {r['embedding']} & {v} & {t} \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    with open(osp.join(TABLES, "baselines_both_label.tex"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
