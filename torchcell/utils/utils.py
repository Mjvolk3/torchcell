def apply_paper_style() -> None:
    """Set every rcParam the repo figure standard fixes, explicitly.

    Setting ``font.size`` alone is not enough, and the reason is a trap worth
    knowing. Importing :mod:`torchcell.graph` runs ``plt.style.use`` at module
    import time, and that style file sets ``axes.labelsize`` 16,
    ``xtick.labelsize`` 14 and ``savefig.bbox`` ``tight`` as absolute values.
    Absolute sizes do not scale with ``font.size``, so a later
    ``rcParams["font.size"] = 6`` leaves axis labels and ticks at 14 to 16 point
    while titles set with an explicit ``fontsize`` come out correct. The result
    is a figure with mismatched type whose canvas has silently been recropped
    wider than its declared panel width.

    Call this after every import, and it holds regardless of what an imported
    module did to the global state.
    """
    import matplotlib.pyplot as plt

    plt.rcParams.update(PAPER_RC)


PANEL_LABEL_PT = 8.0  # Nature: panel letters only, the one size above figure text
PANEL_LABEL_PAD_PT = 1.5
# Vertical raise of the letter above the axes top edge. A 6 pt title at pad 3 occupies
# 3 to 9 pt above the spine and the topmost tick label reaches ~3 pt above it, so a letter
# whose bottom is 12 pt up clears both by at least one letter width -- the white-cross
# rule ([[paper.nature-biotech.style-guide]]): a cross the width of the letter box laid
# over the letter meets no title, spine, or tick label.
PANEL_LABEL_RAISE_PT = 12.0


def panel_label(
    ax: "Axes",
    letter: str,
    x: float | None = None,
    y: float = 1.0,
    pad_pt: float = PANEL_LABEL_PAD_PT,
    raise_pt: float = PANEL_LABEL_RAISE_PT,
    fontsize: float = PANEL_LABEL_PT,
) -> "Text":
    """Draw a panel letter at the panel's top-left corner, in the repo standard.

    Nature's band for figure text is 5 to 7 pt, with 8 pt bold lowercase reserved for
    panel letters. The letter sits OUTSIDE the axes box, at the top-left of the PANEL --
    its left edge flush with the outermost y-axis decoration (the y label, or the tick
    labels when there is no y label) -- and carries an opaque white patch, so the letter
    survives being cropped out of a composed figure with whatever sits behind it.

    Placement follows the white-cross rule ([[paper.nature-biotech.style-guide]]): a cross
    the width of the letter box laid over the letter meets no title, spine, tick label, or
    axis label. The letter is raised ``raise_pt`` points above the axes top edge (one text
    line above the title band, clear of the topmost tick label) and pushed left to the
    panel's outer edge, which is measured from the axes' tight bounding box, so call this
    AFTER the y label and tick formatting are set. ``x`` (axes fraction) overrides the
    measured left edge; ``pad_pt`` is then the offset left of that anchor.
    """
    from matplotlib.transforms import ScaledTranslation

    # An Axes always belongs to a figure by the time it can be drawn on, but the
    # accessor is typed as optional, so fail loudly rather than on an attribute.
    fig = ax.get_figure()
    if fig is None:
        raise ValueError("panel_label: the axes is not attached to a figure")
    if x is None:
        # Outer left edge of the panel: axes box minus everything hanging off its left
        # (tick labels, y label), measured in points so it survives tight_layout.
        # No renderer argument: matplotlib >= 3.6 resolves the figure's own renderer,
        # which keeps this independent of the backend the script happens to run on.
        tight = ax.get_tightbbox()
        if tight is None:
            raise ValueError(
                "panel_label: the axes has no tight bounding box to measure"
            )
        left_pt = (ax.bbox.x0 - tight.x0) / fig.dpi * 72.0
        offset = ScaledTranslation(
            -left_pt / 72.0, raise_pt / 72.0, fig.dpi_scale_trans
        )
        ha = "left"
        x = 0.0
    else:
        offset = ScaledTranslation(-pad_pt / 72.0, raise_pt / 72.0, fig.dpi_scale_trans)
        ha = "right"
    return ax.text(
        x,
        y,
        letter.lower(),
        transform=ax.transAxes + offset,
        fontsize=fontsize,
        fontweight="bold",
        fontfamily="Arial",
        ha=ha,
        va="bottom",
        bbox={"facecolor": "white", "edgecolor": "none", "pad": 1.0},
    )


def savefig_true_size_svg(
    fig: "Figure",
    path: str,
    src_dpi: int = 72,
    drawio_dpi: int = 100,
    **savefig_kwargs: Any,
) -> None:
    """Save a matplotlib figure as an SVG that imports at TRUE physical size in draw.io.

    matplotlib writes SVG coordinates in PostScript points (72 per inch) and tags the
    root ``width``/``height`` with the ``pt`` unit. draw.io does not honor the CSS
    definition of ``pt``; it reads the numeric ``width``/``height``/``viewBox`` in its
    own native unit of 100 per inch. A figure authored at W inches therefore imports at
    ``W * 72/100`` inches -- 72% of intended, fonts included (the source of the
    57.7 mm-file / 41.4 mm-in-draw.io discrepancy).

    This saves the SVG, then rewrites the root so the coordinate numbers correspond to
    ``drawio_dpi`` (100) per inch and wraps the drawn content in a matching ``scale()``
    group. The rendered result is visually identical; only the declared coordinate
    system changes, so draw.io lands on the true mm/pt sizes and 6 pt text stays 6 pt.

    For a fixed-figsize WYSIWYG canvas, do NOT pass ``bbox_inches="tight"`` -- it
    recrops the canvas and defeats the intended size; author the figure at its final
    ``figsize`` instead. It IS appropriate for a standalone figure whose goal is a
    tight crop (e.g. a legend-only image); the rescale still yields a correct
    physical size for whatever tight box matplotlib emits.
    """
    # Byte-stable output, so an SVG can be hash-checked the way a result CSV is.
    # matplotlib leaves ``svg.hashsalt`` unset, in which case it seeds the clip-path and
    # glyph element ids from a fresh random salt on every process, and it stamps a
    # ``<dc:date>`` with the wall-clock save time. Two identical runs then produce files
    # with identical vector content but different hashes. Salting with the output
    # basename makes the ids a pure function of the figure while keeping distinct
    # figures distinct, and ``metadata={"Date": None}`` omits the date stamp. A caller
    # that passes its own ``metadata`` keeps it.
    savefig_kwargs.setdefault("metadata", {"Date": None})
    with matplotlib.rc_context({"svg.hashsalt": osp.basename(path)}):
        fig.savefig(path, **savefig_kwargs)
    with open(path, encoding="utf-8") as f:
        svg = f.read()
    # matplotlib always emits an <svg> root tagged with width/height in pt. If any of
    # these is missing the file is not a matplotlib SVG and the rescale is meaningless,
    # so fail loudly rather than silently writing a wrongly-sized figure.
    m_tag = re.search(r"<svg\b[^>]*>", svg)
    if m_tag is None:
        raise ValueError(f"{path}: no <svg> root tag; not a matplotlib SVG")
    open_tag = m_tag.group(0)
    m_w = re.search(r'width="([\d.]+)pt"', open_tag)
    m_h = re.search(r'height="([\d.]+)pt"', open_tag)
    if m_w is None or m_h is None:
        raise ValueError(f"{path}: <svg> root has no pt width/height to rescale")
    w = float(m_w.group(1))
    h = float(m_h.group(1))
    k = drawio_dpi / src_dpi
    new_w, new_h = w * k, h * k
    new_tag = re.sub(r'width="[\d.]+pt"', f'width="{new_w:.4f}"', open_tag)
    new_tag = re.sub(r'height="[\d.]+pt"', f'height="{new_h:.4f}"', new_tag)
    new_tag = re.sub(
        r'viewBox="[^"]*"', f'viewBox="0 0 {new_w:.4f} {new_h:.4f}"', new_tag
    )
    svg = svg.replace(open_tag, new_tag + f'<g transform="scale({k:.10f})">', 1)
    svg = svg.replace("</svg>", "</g></svg>", 1)
    with open(path, "w", encoding="utf-8") as f:
        f.write(svg)


# --- Chemical structures at the ACS 1996 standard --------------------------------
#
# The publication standard for a drawn structure is ChemDraw's "ACS Document 1996"
# template, which Nature and the ACS journals accept as submitted: a fixed bond length
# of 0.381 cm, double-bond spacing at 18 percent of the bond length, a 0.021 cm line,
# Arial labels with implicit hydrogens shown on heteroatoms (HO, OH, NH) and none on
# the carbon skeleton. RDKit implements the same template (``SetACS1996Mode``: bond
# 14.4 pt, line 0.6 pt, offset 0.18, monochrome, 10 pt labels); here the bond is
# rescaled to the ACS length in points and the label to Nature's figure-text size, so
# a structure drawn into a panel at ``fontsize=6`` matches the panel's own type.
ACS_BOND_PT = 10.8  # 0.381 cm, the ACS 1996 fixed bond length
ACS_LINE_PT = 0.6  # 0.021 cm, the ACS 1996 line width
ACS_FONT_PT = 6.0  # atom labels, Nature's figure-text default (band 5 to 7 pt)

_SVG_NUMBER = re.compile(r"[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?")
_SVG_COMMAND = re.compile(r"([MLQCZ])([^MLQCZ]*)")


def _svg_path(d: str) -> Any:
    """An absolute SVG path (M, L, Q, C, Z) as a matplotlib :class:`Path`.

    RDKit writes nothing else: bonds are ``M x,y L x,y`` lines and FreeType glyph
    outlines are ``M``, ``L``, ``Q`` and ``Z`` runs. A relative command is a
    malformed input here and raises.
    """
    from matplotlib.path import Path

    verts: list[tuple[float, float]] = []
    codes: list[Any] = []
    for cmd, body in _SVG_COMMAND.findall(d):
        nums = [float(x) for x in _SVG_NUMBER.findall(body)]
        if cmd == "M":
            verts.append((nums[0], nums[1]))
            codes.append(Path.MOVETO)
            for p in zip(nums[2::2], nums[3::2], strict=True):
                verts.append(p)
                codes.append(Path.LINETO)
        elif cmd == "L":
            for p in zip(nums[0::2], nums[1::2], strict=True):
                verts.append(p)
                codes.append(Path.LINETO)
        elif cmd == "Q":
            for i in range(0, len(nums), 4):
                verts.extend([(nums[i], nums[i + 1]), (nums[i + 2], nums[i + 3])])
                codes.extend([Path.CURVE3, Path.CURVE3])
        elif cmd == "C":
            for i in range(0, len(nums), 6):
                verts.extend(
                    [
                        (nums[i], nums[i + 1]),
                        (nums[i + 2], nums[i + 3]),
                        (nums[i + 4], nums[i + 5]),
                    ]
                )
                codes.extend([Path.CURVE4] * 3)
        else:
            verts.append(verts[-1])
            codes.append(Path.CLOSEPOLY)
    return Path(verts, codes)


def acs_structure_svg(
    smiles: str,
    bond_pt: float = ACS_BOND_PT,
    font_pt: float = ACS_FONT_PT,
    line_pt: float = ACS_LINE_PT,
) -> tuple[str, float, float]:
    """RDKit's ACS 1996 drawing of ``smiles`` as SVG text, with its width and height.

    The canvas is flexible (RDKit sizes it to the molecule), one SVG pixel is one
    point, the bond is ``bond_pt`` long, the labels are set in Arial at ``font_pt``
    as glyph outlines (so the drawing needs no font at render time), and the line is
    ``line_pt`` wide. Returns ``(svg, width_pt, height_pt)``.
    """
    from matplotlib import font_manager
    from rdkit import Chem
    from rdkit.Chem import rdDepictor
    from rdkit.Chem.Draw import rdMolDraw2D

    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        raise ValueError(f"acs_structure_svg: RDKit cannot parse {smiles!r}")
    rdDepictor.Compute2DCoords(mol)
    drawer = rdMolDraw2D.MolDraw2DSVG(-1, -1)
    # RDKit's stub types every attribute of the options object as the object itself,
    # so the assignments below are typed through Any
    opts: Any = drawer.drawOptions()
    mean_bond = rdMolDraw2D.MeanBondLength(mol)
    rdMolDraw2D.SetACS1996Mode(opts, mean_bond)
    opts.scalingFactor = bond_pt / mean_bond
    opts.fixedFontSize = int(round(font_pt))
    opts.bondLineWidth = line_pt
    opts.fontFile = font_manager.findfont("Arial")
    opts.padding = 0.02
    drawer.DrawMolecule(mol)
    drawer.FinishDrawing()
    svg = drawer.GetDrawingText()
    m = re.search(r"width='([\d.]+)px' height='([\d.]+)px'", svg)
    if m is None:
        raise ValueError("acs_structure_svg: RDKit wrote no pixel size")
    return svg, float(m.group(1)), float(m.group(2))


def acs_structure_box(smiles: str, **kwargs: Any) -> Any:
    """The ACS 1996 structure as a :class:`DrawingArea` in points, black on nothing.

    Every RDKit path becomes a matplotlib patch: a stroked path for a bond (its
    ``stroke-width`` kept, butt caps, miter joins, as RDKit draws it) and a filled
    path for a glyph outline. The area has no background, so it sits on a panel's
    own fill. ``kwargs`` go to :func:`acs_structure_svg`.
    """
    from matplotlib.offsetbox import DrawingArea
    from matplotlib.patches import PathPatch
    from matplotlib.transforms import Affine2D

    svg, w, h = acs_structure_svg(smiles, **kwargs)
    area = DrawingArea(w, h, 0, 0)
    flip = Affine2D().scale(1, -1).translate(0, h)  # SVG y runs down
    for m in re.finditer(r"<path([^>]*)/>", svg):
        attrs = m.group(1)
        m_d = re.search(r"d='([^']*)'", attrs)
        if m_d is None:
            continue
        path = _svg_path(m_d.group(1)).transformed(flip)
        m_style = re.search(r"style='([^']*)'", attrs)
        style = m_style.group(1) if m_style else ""
        if "fill:none" in style:
            m_lw = re.search(r"stroke-width:([\d.]+)px", style)
            lw = float(m_lw.group(1)) if m_lw else ACS_LINE_PT
            area.add_artist(
                PathPatch(
                    path,
                    facecolor="none",
                    edgecolor="black",
                    linewidth=lw,
                    capstyle="butt",
                    joinstyle="miter",
                )
            )
        else:
            area.add_artist(
                PathPatch(path, facecolor="black", edgecolor="none", linewidth=0)
            )
    return area


def acs_structure(
    ax: "Axes",
    smiles: str,
    xy: tuple[float, float],
    xycoords: str = "data",
    box_alignment: tuple[float, float] = (0.5, 0.5),
    **kwargs: Any,
) -> tuple[Any, float, float]:
    """Draw ``smiles`` at the ACS 1996 standard, anchored at ``xy`` on ``ax``.

    The structure keeps its physical size whatever the axes' data scale, because the
    drawing area is in points, so two structures on one sheet have the same bond
    length, which is what the standard fixes. ``box_alignment`` is the point of the
    structure's box that sits on ``xy`` (``(0.5, 0.5)`` its center). Returns the
    :class:`AnnotationBbox` and the structure's width and height in points, so the
    caller can place a name under it. ``kwargs`` go to :func:`acs_structure_svg`.
    """
    from matplotlib.offsetbox import AnnotationBbox

    area = acs_structure_box(smiles, **kwargs)
    box = AnnotationBbox(
        area, xy, xycoords=xycoords, frameon=False, pad=0.0, box_alignment=box_alignment
    )
    ax.add_artist(box)
    return box, float(area.width), float(area.height)


def format_scientific_notation(num: float) -> str:
    """Format a number into scientific notation, preserving all significant digits.

    Examples:
        10000 -> "1e04"
        10007 -> "1.0007e04"
        1234567 -> "1.234567e06"
        100 -> "1e02"
    """
    if num == 0:
        return "0"

    # Handle negative numbers
    sign = ""
    if num < 0:
        sign = "-"
        num = abs(num)

    # Get exponent (power of 10)
    exponent = int(math.floor(math.log10(num)))
    mantissa = num / (10**exponent)

    # Find minimum precision needed to preserve the exact value
    mantissa_str = f"{mantissa:.0f}"  # Default for Pylance
    for precision in range(15):
        mantissa_str = f"{mantissa:.{precision}f}"
        reconstructed = float(mantissa_str) * (10**exponent)
        if round(reconstructed) == round(num):
            break

    # Clean up: remove trailing zeros and unnecessary decimal point
    mantissa_str = mantissa_str.rstrip("0").rstrip(".")

    return f"{sign}{mantissa_str}e{exponent:02d}"


