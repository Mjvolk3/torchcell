# --- emitters ---------------------------------------------------------------
def write_table(name: str, body: str) -> None:
    os.makedirs(TABLES, exist_ok=True)
    path = osp.join(TABLES, name)
    with open(path, "w") as f:
        f.write(
            f"%% GENERATED by {SCRIPT_REL}\n"
            "%% SOURCE: the result files named in that script's docstring. "
            "Do not edit by hand.\n"
        )
        f.write(body if body.endswith("\n") else body + "\n")
    print(f"wrote {path}")


def tabular(colspec: str, header: list[list[str]], rows: list[list[str]]) -> str:
    """A booktabs tabular whose header may be stacked over several lines.

    Every column header has to name its metric and its unit, and a one-line
    header that does both runs a ten-column table past the 182 mm text block --
    the overfull hbox `make check` fails on. Stacking the unit under the name
    is what keeps both the information and the width.
    """
    out = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule"]
    out += [" & ".join(h) + r" \\" for h in header]
    out += ["\\midrule"]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out)


def bold(s: str) -> str:
    return rf"\textbf{{{s}}}"


def f2(v) -> str:
    return "" if pd.isna(v) else f"{v:.2f}"


def f3(v) -> str:
    return "" if pd.isna(v) else f"{v:.3f}"


def f1(v) -> str:
    return "" if pd.isna(v) else f"{v:.1f}"


def sgn3(v) -> str:
    return "" if pd.isna(v) else f"{v:+.3f}"


def ci(lo, hi, fmt=f3) -> str:
    if pd.isna(lo) or pd.isna(hi):
        return ""
    return f"[{fmt(lo)}, {fmt(hi)}]"


def mark_best(vals: list[float], strs: list[str], want_max: bool = True) -> list[str]:
    """Bold the best entry of a column, skipping missing values."""
    live = [(i, v) for i, v in enumerate(vals) if v is not None and not pd.isna(v)]
    if not live:
        return strs
    best = (max if want_max else min)(live, key=lambda t: t[1])[0]
    return [bold(s) if i == best else s for i, s in enumerate(strs)]


def read_csv(name: str) -> pd.DataFrame:
    return pd.read_csv(osp.join(RESULTS, name))


def read_json(name: str) -> dict:
    with open(osp.join(RESULTS, name)) as f:
        return json.load(f)


