"""Tables and the figure of the linear-probe results page, from the committed runs.

Reads every ``results/probes/<task>.<feature>.csv`` written by ``linear_probes.py`` and
``results/splits_summary.csv``, and writes

- ``results/linear_probes.csv``: every run, one row per task, split, representation
  and pair combination.
- ``docs/source/benchmark/ecoli/_generated/``: one table per task (test Pearson, mean
  and sample standard deviation over the seeds of a split family), the split-size
  table, the task table and ``linear_probes.svg`` / ``.png``.

The statistic in every table cell is the mean over targets of the per-target Pearson
correlation on the test part, at the ridge penalty chosen on validation.

    python experiments/050-ecoli-benchmark/scripts/results_page.py
"""

from __future__ import annotations

import glob
import os
import os.path as osp
from datetime import UTC, datetime

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from matplotlib.ticker import MaxNLocator, MultipleLocator  # noqa: E402

from torchcell.tasks.ecoli import ECOLI_TASKS  # noqa: E402
from torchcell.utils import PANEL_WIDTHS_MM, PLOT_PALETTE, mm_to_in  # noqa: E402

RESULTS = "experiments/050-ecoli-benchmark/results"
OUT = "docs/source/benchmark/ecoli/_generated"
FEATURES = ("random", "one_hot", "esm2", "prot_t5", "calm")
FEATURE_LABELS = {
    "random": "Random",
    "one_hot": "One-hot",
    "esm2": "ESM-2 650M",
    "prot_t5": "ProtT5-XL",
    "calm": "CaLM",
}
FAMILY_LABELS = {
    "random": "Random",
    "seqid30": "Sequence identity 30 %",
    "seqid50": "Sequence identity 50 %",
    "position": "Chromosome position",
    "gene_holdout": "Gene holdout, random",
    "seqid30_gene_holdout": "Gene holdout, identity 30 %",
    "seqid50_gene_holdout": "Gene holdout, identity 50 %",
    "position_gene_holdout": "Gene holdout, position",
}
PANEL_TITLES = {
    "ecoli-growth-rate-campos2018": "Growth rate (Campos 2018)",
    "ecoli-morphology-campos2018": "Cell shape and cell cycle (Campos 2018)",
    "ecoli-metabolome-fuhrer2017": "Metabolome (Fuhrer 2017)",
    "ecoli-gene-interaction-babu2014": "Genetic interactions (Babu 2014)",
}
SHORT = {
    "random": "Random",
    "seqid30": "Identity 30 %",
    "seqid50": "Identity 50 %",
    "position": "Position",
    "gene_holdout": "Genes, random",
    "seqid30_gene_holdout": "Genes, id. 30 %",
    "seqid50_gene_holdout": "Genes, id. 50 %",
    "position_gene_holdout": "Genes, position",
}


def header() -> str:
    """The generated-file comment."""
    stamp = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    return (
        "<!-- Generated by experiments/050-ecoli-benchmark/scripts/results_page.py "
        f"(run {stamp}). Do not edit by hand. -->\n\n"
    )


def table(head: list[str], rows: list[list[str]]) -> str:
    """A markdown table, first column left-aligned and the rest right-aligned."""
    lines = ["| " + " | ".join(head) + " |"]
    lines.append("| --- | " + " | ".join("---:" for _ in head[1:]) + " |")
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def cell(values: pd.Series) -> str:
    """Mean and sample standard deviation over seeds, or why there is no number."""
    finite = values.dropna()
    if len(values) == 0:
        return "not run"
    if len(finite) == 0:
        return "undefined"
    if len(finite) == 1:
        return f"{finite.iloc[0]:.3f}"
    return f"{finite.mean():.3f} ± {finite.std(ddof=1):.3f}"


def write(name: str, text: str) -> None:
    """Write one generated fragment."""
    with open(osp.join(OUT, name), "w", encoding="utf-8") as handle:
        handle.write(header() + text)


def main() -> None:
    """Write the combined run table, the fragments and the figure."""
    os.makedirs(OUT, exist_ok=True)
    runs = pd.concat(
        [
            pd.read_csv(p)
            for p in sorted(glob.glob(osp.join(RESULTS, "probes", "*.csv")))
        ],
        ignore_index=True,
    )
    runs.to_csv(osp.join(RESULTS, "linear_probes.csv"), index=False)
    features = [f for f in FEATURES if f in set(runs["feature"])]

    write(
        "tasks.md",
        table(
            ["Task", "Dataset class", "Genome", "Unit", "Label"],
            [
                [
                    f"`{s.name}`",
                    f"`{s.dataset_class}`",
                    f"`{s.assembly_set}`",
                    "gene" if s.kind == "single_gene" else "gene pair",
                    s.n_targets_note,
                ]
                for s in ECOLI_TASKS.values()
            ],
        ),
    )
    sizes = pd.read_csv(osp.join(RESULTS, "splits_summary.csv"))
    sizes["family"] = sizes["split"].str.replace(r"_s\d+$", "", regex=True)
    rows = []
    for (task, family), group in sizes.groupby(["task", "family"], sort=False):
        rows.append(
            [
                f"`{task}`",
                f"`{family}_s0` to `{family}_s{len(group) - 1}`",
                str(len(group)),
                f"{int(group['samples'].iloc[0]):,}",
                f"{int(group['train'].min()):,} to {int(group['train'].max()):,}",
                f"{int(group['val'].min()):,} to {int(group['val'].max()):,}",
                f"{int(group['test'].min()):,} to {int(group['test'].max()):,}",
            ]
        )
    write(
        "splits.md",
        table(
            ["Task", "Splits", "Seeds", "Samples", "Train", "Validation", "Test"], rows
        ),
    )

    for task, group in runs.groupby("task", sort=False):
        text = ""
        for combine, sub in group.groupby("combine", sort=False):
            if combine != "single":
                text += f"\nPair representation: `{combine}`.\n\n"
            rows = []
            for family in sub["family"].drop_duplicates():
                part = sub[sub["family"] == family]
                rows.append(
                    [FAMILY_LABELS[family]]
                    + [
                        cell(part.loc[part["feature"] == f, "test_pearson"])
                        for f in features
                    ]
                )
            text += table(
                ["Split family"] + [FEATURE_LABELS[f] for f in features], rows
            )
        write(f"probes_{task}.md", text)
        if (
            "test_pearson_one_new" in group
            and group["test_pearson_one_new"].notna().any()
        ):
            text = ""
            holdout = group[group["family"].str.contains("gene_holdout")]
            for combine, sub in holdout.groupby("combine", sort=False):
                text += f"\nPair representation: `{combine}`.\n\n"
                rows = []
                for family in sub["family"].drop_duplicates():
                    part = sub[sub["family"] == family]
                    for label, column in (
                        ("one gene new", "test_pearson_one_new"),
                        ("both genes new", "test_pearson_both_new"),
                    ):
                        rows.append(
                            [f"{FAMILY_LABELS[family]}, {label}"]
                            + [
                                cell(part.loc[part["feature"] == f, column])
                                for f in features
                            ]
                        )
                text += table(
                    ["Test pairs"] + [FEATURE_LABELS[f] for f in features], rows
                )
            write(f"probes_{task}_novelty.md", text)

    plt.rcParams.update(
        {
            "font.family": "Arial",
            "font.size": 6,
            "axes.labelsize": 6,
            "axes.titlesize": 6,
            "xtick.labelsize": 6,
            "ytick.labelsize": 6,
            "legend.fontsize": 6,
            "svg.fonttype": "none",
            "axes.linewidth": 0.5,
        }
    )
    single = [n for n, s in ECOLI_TASKS.items() if s.kind == "single_gene"]
    pair = [n for n, s in ECOLI_TASKS.items() if s.kind == "gene_pair"]
    figure = plt.figure(figsize=(mm_to_in(PANEL_WIDTHS_MM["full"]), mm_to_in(105)))
    grid = figure.add_gridspec(2, len(single), hspace=0.6, wspace=0.3)
    axes = [figure.add_subplot(grid[0, i]) for i in range(len(single))]
    axes.append(figure.add_subplot(grid[1, :]))
    for axis, task in zip(axes, single + pair):
        group = runs[runs["task"] == task]
        combines = list(group["combine"].drop_duplicates())
        if not combines:
            continue
        families = list(group["family"].drop_duplicates())
        width = 0.8 / (len(features) * len(combines))
        for i, feature in enumerate(features):
            for j, combine in enumerate(combines):
                sub = group[
                    (group["feature"] == feature) & (group["combine"] == combine)
                ]
                stats = sub.groupby("family")["test_pearson"].agg(["mean", "std"])
                stats = stats.reindex(families)
                x = (
                    np.arange(len(families))
                    + (i * len(combines) + j + 0.5) * width
                    - 0.4
                )
                axis.bar(
                    x,
                    stats["mean"],
                    width,
                    yerr=stats["std"].fillna(0),
                    color=PLOT_PALETTE[i],
                    edgecolor="black",
                    linewidth=0.3,
                    hatch="////" if combine == "sum" else None,
                    error_kw={"elinewidth": 0.4, "capsize": 1, "capthick": 0.4},
                    label=FEATURE_LABELS[feature] if j == 0 else None,
                )
        axis.axhline(0, color="black", linewidth=0.5)
        axis.set_xticks(np.arange(len(families)))
        axis.set_xticklabels([SHORT[f] for f in families], rotation=30, ha="right")
        axis.set_ylabel("Test Pearson r")
        axis.set_title(PANEL_TITLES[task], pad=3)
        axis.yaxis.set_major_locator(
            MultipleLocator(0.1)
            if ECOLI_TASKS[task].kind == "gene_pair"
            else MaxNLocator(nbins=5)
        )
        axis.yaxis.grid(True, linewidth=0.3, color="#cccccc")
        axis.set_axisbelow(True)
        for spine in axis.spines.values():
            spine.set_visible(True)
            spine.set_linewidth(0.5)
            spine.set_color("black")
        axis.tick_params(width=0.5, length=2)
    handles, labels = axes[0].get_legend_handles_labels()
    figure.legend(
        handles,
        labels,
        loc="upper center",
        ncol=len(features),
        frameon=False,
        bbox_to_anchor=(0.5, 0.99),
    )
    figure.subplots_adjust(left=0.07, right=0.99, top=0.91, bottom=0.13)
    figure.savefig(osp.join(OUT, "linear_probes.svg"))
    figure.savefig(osp.join(OUT, "linear_probes.png"), dpi=300)
    print(f"{len(runs)} runs, features {features}; wrote fragments to {OUT}")


if __name__ == "__main__":
    main()
