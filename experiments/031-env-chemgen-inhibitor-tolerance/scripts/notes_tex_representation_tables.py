def t13_per_dataset_baselines() -> None:
    """Best ridge and kNN per dataset on the centered target, against the null."""
    path = osp.join(RESULTS, "per_dataset_baselines_summary.csv")
    s = pd.read_csv(path)
    s = s[(s["target"] == "centered") & s["spearman_median"].notna()]
    rows = []
    for name in ORDER:
        d = s[s["dataset"] == name]
        if d.empty:
            continue
        ridge = d[d["model"] == "ridge"]
        knn = d[d["model"].str.startswith("knn")]
        null = d[d["model"] == "random_neighbor"]
        # the ceiling fraction follows the BEST model of either class, not ridge alone:
        # neighbor transfer wins on three of the five datasets
        feat = d[d["features"] != "none"]
        best = feat.loc[feat["spearman_median"].idxmax()]
        cap = float(best["ceiling_median"])
        rows.append(
            {
                "dataset": LABEL[name],
                "scheme": "LOCO"
                if "leave_one" in str(best["scheme"])
                else str(best["scheme"]).split("_")[0],
                "folds": int(best["folds"]),
                "null": f"{null['spearman_median'].median():.3f}"
                if not null.empty
                else "",
                "best ridge": f"{ridge['spearman_median'].max():.3f}"
                if not ridge.empty
                else "",
                "best kNN": f"{knn['spearman_median'].max():.3f}"
                if not knn.empty
                else "",
                "best overall": f"{best['spearman_median']:.3f}",
                "model, encoder": f"{best['model']}, "
                f"{str(best['features']).replace('_', ' ')}",
                "ceiling": f"{cap:.2f}" if np.isfinite(cap) else "none served",
                "of ceiling": f"{best['spearman_median'] / cap:.2f}"
                if np.isfinite(cap)
                else "",
            }
        )
    write(
        "t13-per-dataset-baselines",
        tex_table(pd.DataFrame(rows), align="llrrrrrlrr"),
        "per_dataset_baselines_summary.csv from per_dataset_baselines.py",
    )


def t14_hoepfner_ceiling() -> None:
    """Hoepfner's ceiling recovered from cross-screen repeats, per arm."""
    audit = pd.read_csv(osp.join(RESULTS, "hoepfner_column_audit.csv"))
    pairs = pd.read_csv(osp.join(RESULTS, "hoepfner_cross_screen_reliability.csv"))
    base = pd.read_csv(osp.join(RESULTS, "per_dataset_baselines_summary.csv"))
    best = base[
        (base["dataset"] == "hoepfner2014")
        & (base["target"] == "centered")
        & (base["features"] != "none")
    ]["spearman_median"].max()
    rows = []
    for arm, g in pairs.groupby("arm"):
        col = audit[audit["file"].str.startswith(arm)].iloc[0]
        cap = float(g["ceiling_r_truth"].median())
        rows.append(
            {
                "arm": arm,
                "experiments deposited": f"{int(col['distinct_experiment_ids']):,}",
                "repeated columns": int(col["experiment_ids_appearing_twice"]),
                "condition pairs": len(g),
                "compounds": int(g["inchikey"].nunique()),
                "reliability": f"{g['reliability_single'].median():.3f}",
                "ceiling": f"{cap:.3f}",
                "of ceiling": f"{best / cap:.2f}",
            }
        )
    allcap = float(pairs["ceiling_r_truth"].median())
    rows.append(
        {
            "arm": "both",
            "experiments deposited": f"{int(audit['distinct_experiment_ids'].sum()):,}",
            "repeated columns": int(audit["experiment_ids_appearing_twice"].sum()),
            "condition pairs": len(pairs),
            "compounds": int(pairs["inchikey"].nunique()),
            "reliability": f"{pairs['reliability_single'].median():.3f}",
            "ceiling": f"{allcap:.3f}",
            "of ceiling": f"{best / allcap:.2f}",
        }
    )
    write(
        "t14-hoepfner-ceiling",
        tex_table(pd.DataFrame(rows), align="lrrrrrrr"),
        "hoepfner_column_audit.csv and hoepfner_cross_screen_reliability.csv from "
        "hoepfner_replicate_ceiling.py",
    )


