"""Render the tables of ``notes-tex/033-post-query-analysis`` from the result CSVs.

Every table in that document is generated here from a file ``store_against_plan.py``
wrote, so no number is hand-authored. The scorecard (``t0``) is built the same way: each
row names a claim of the 031 plan, the value the plan stated, the value the built store
gives, and a reading that is computed from the two by a stated rule. The plan values are
read from the 031 result files through the columns ``store_against_plan.py`` carried
over, or, for the four that are prose statements in the 031 documents, from
``PLAN_STATED`` below with the section they come from.

Reads ``experiments/033-env-chemgen-pooled/results/*.csv`` and writes
``notes-tex/033-post-query-analysis/tables/*.tex``.
"""

