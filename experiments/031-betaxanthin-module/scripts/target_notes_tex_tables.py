r"""Generate the tables of notes-tex/031-betaxanthin-module and notes-tex/032-amino-acid-module.

One script serves both target documents, as the readout scripts do: each table is
written once per target from that study's results tree, into that document's tables/
directory. The column fitting is the essentiality generator's. Run from the repo root::

    PYTHONPATH=$PWD ~/miniconda3/envs/torchcell/bin/python \
        experiments/031-betaxanthin-module/scripts/target_notes_tex_tables.py
"""

