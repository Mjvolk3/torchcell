class PseudocountBackSolve(BaseModel):
    """The evidence that the release's values are log2(TPM + 1)."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    pseudocount: float
    n_genes: int
    n_samples: int
    median_total_tpm: float
    min_total_tpm: float
    max_total_tpm: float
    n_samples_within_tolerance: int
    sample_tolerance_tpm: float
    prefilter_equals_released_values: bool


def back_solve_pseudocount(
    released: pd.DataFrame, prefilter: pd.DataFrame
) -> PseudocountBackSolve:
    """Check that ``2**x - 1`` sums to 1e6 per sample over the pre-filter genes.

    A TPM sums to 1e6 over the genes it was computed on. The release's pre-filter matrix
    (4,355 genes) is that gene set; the released matrix must equal it exactly on every
    shared cell. The median per-sample total must be 1e6 within
    ``BACK_SOLVE_MEDIAN_TOLERANCE_TPM`` or the build stops.
    """
    shared = prefilter.loc[released.index, released.columns]
    equal = bool(np.array_equal(shared.to_numpy(), released.to_numpy()))
    if not equal:
        raise RuntimeError(
            "the released log-TPM values differ from the pre-filter matrix on shared "
            "cells; the pseudocount back-solve does not apply"
        )
    totals = (np.exp2(prefilter[released.columns].to_numpy()) - PSEUDOCOUNT).sum(axis=0)
    median = float(np.median(totals))
    if abs(median - TPM_TOTAL) > BACK_SOLVE_MEDIAN_TOLERANCE_TPM:
        raise RuntimeError(
            f"median per-sample sum of 2**x - {PSEUDOCOUNT} is {median}, not {TPM_TOTAL}"
        )
    return PseudocountBackSolve(
        pseudocount=PSEUDOCOUNT,
        n_genes=int(prefilter.shape[0]),
        n_samples=int(totals.size),
        median_total_tpm=median,
        min_total_tpm=float(totals.min()),
        max_total_tpm=float(totals.max()),
        n_samples_within_tolerance=int(
            (np.abs(totals - TPM_TOTAL) <= BACK_SOLVE_SAMPLE_TOLERANCE_TPM).sum()
        ),
        sample_tolerance_tpm=BACK_SOLVE_SAMPLE_TOLERANCE_TPM,
        prefilter_equals_released_values=equal,
    )


def to_tpm(log_tpm: np.ndarray[Any, np.dtype[np.float64]]) -> list[float]:
    """Invert the release's ``log2(TPM + 1)``."""
    return [float(v) for v in np.exp2(log_tpm) - PSEUDOCOUNT]


def rnaseq_phenotype(
    genes: list[str],
    log_tpm: np.ndarray[Any, np.dtype[np.float64]],
    counts: np.ndarray[Any, np.dtype[np.int64]],
) -> RNASeqExpressionPhenotype:
    """One library's absolute TPM and featureCounts count over the stored genes."""
    return RNASeqExpressionPhenotype(
        expression_tpm=dict(zip(genes, to_tpm(log_tpm), strict=True)),
        expression_count={g: int(c) for g, c in zip(genes, counts, strict=True)},
        measurement_type=MEASUREMENT_TYPE,
        provenance_gaps=[MAPPED_READS_GAP],
    )


