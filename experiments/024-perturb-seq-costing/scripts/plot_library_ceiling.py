"""What a yeast transformation can actually cover, against panel size and plex.

Sec. 4.7 states the genome-scale conclusion as a single arithmetic line: a
dual-guide library over 6,000 genes needs 5.4e8 clones at 30-fold redundancy,
which is 54 to 540 times beyond what yeast transformation delivers. A reviewer
asked to see the whole surface rather than the one point, and the request is
right -- the interesting content is WHERE the ceiling is crossed, not that it is
crossed at the genome.

Two distinctions the panels are built to keep separate, because conflating them
is what makes this confusing:

* **Cloned combinations** (route A of Sec. 7.1) need one clone per COMBINATION,
  so the requirement grows as C(T, k) and explodes. This is the wall.
* **Co-transformed singles** (route B) need one clone per GUIDE, so the
  requirement is T and does not grow with k at all. Combinations are then
  generated by Poisson uptake rather than by cloning, which is exactly why that
  route is worth the trouble.

Panel (c) is the answer to the literal question asked: for each plex, the
largest panel that fits inside one transformation.

Run:  python experiments/024-perturb-seq-costing/scripts/plot_library_ceiling.py
"""

from __future__ import annotations

import math
import os
import os.path as osp

import matplotlib.pyplot as plt
import numpy as np
from dotenv import load_dotenv

from design_equation import box, place_panel_letters, style
from torchcell.utils import PANEL_WIDTHS_MM, mm_to_in, savefig_true_size_svg

load_dotenv()
ASSET_IMAGES_DIR = os.environ["ASSET_IMAGES_DIR"]
OUT_DIR = osp.join(ASSET_IMAGES_DIR, "024-perturb-seq-costing")

# Lian et al., our own library's paper: transformation efficiency 1e6-1e7, and
# their stated construction standard is >1e6 clones at >=30-fold redundancy.
TRANSFORMATION_LOW = 1e6
TRANSFORMATION_HIGH = 1e7
REDUNDANCY = 30

PANELS = np.unique(np.concatenate([
    np.logspace(math.log10(20), math.log10(6000), 160), [200.0, 6000.0]]))
PLEXES = [1, 2, 3, 4]

# Palette slots 1..4, the document's order: orange, red, purple, yellow.
PLEX_COLOR = {1: "#D79B00", 2: "#B85450", 3: "#9673A6", 4: "#D6B656"}


def clones_needed(n_targets: float, k: int, redundancy: int = REDUNDANCY) -> float:
    """Independent clones to cover every k-combination of n_targets, cloned.

    C(T, k) combinations, each needing `redundancy` independent clones. k = 1 is
    the ordinary single-guide library and is the floor of this family.
    """
    if k == 1:
        return redundancy * n_targets
    return redundancy * math.comb(int(round(n_targets)), k)


def max_panel_for(k: int, capacity: float, redundancy: int = REDUNDANCY) -> float:
    """Largest panel whose k-combinations fit in `capacity` clones."""
    lo, hi = 2, 6000
    if clones_needed(lo, k, redundancy) > capacity:
        return float("nan")
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if clones_needed(mid, k, redundancy) <= capacity:
            lo = mid
        else:
            hi = mid - 1
    return float(lo)


def panel_a(ax) -> None:
    """Clones needed against panel size, one curve per plex, cloned pairs."""
    for k in PLEXES:
        y = [clones_needed(t, k) for t in PANELS]
        ax.plot(PANELS, y, color=PLEX_COLOR[k], lw=1.0, label=f"$k={k}$")
    ax.axhspan(TRANSFORMATION_LOW, TRANSFORMATION_HIGH, color="#666666",
               alpha=0.13, lw=0)
    ax.axhline(TRANSFORMATION_HIGH, color="#666666", lw=0.6, ls="--")
    ax.text(22, TRANSFORMATION_HIGH * 1.6, "one yeast transformation",
            fontsize=5, color="#666666")
    for t, lab in ((200, "200-gene\npanel"), (6000, "genome")):
        ax.axvline(t, color="#CCCCCC", lw=0.5, zorder=0)
        ax.text(t * 0.92, 3e12, lab, fontsize=4.5, color="#666666",
                ha="right", va="top")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Genes in the panel, $T$")
    ax.set_ylabel("Independent clones needed")
    ax.set_ylim(1e2, 1e13)
    ax.set_title("Cloning every combination", loc="left", fontsize=6)
    ax.legend(frameon=False, fontsize=4.5, loc="lower right", handlelength=1.6,
              labelspacing=0.25, borderaxespad=0.2)
    box(ax)


def panel_b(ax) -> None:
    """The same question for co-transformed singles: it does not grow with k."""
    y = [clones_needed(t, 1) for t in PANELS]
    ax.plot(PANELS, y, color="#666666", lw=1.2,
            label="co-transformed singles,\nany $k$")
    ax.plot(PANELS, [clones_needed(t, 2) for t in PANELS],
            color=PLEX_COLOR[2], lw=1.0, ls=":", label="cloned pairs, $k=2$")
    ax.axhspan(TRANSFORMATION_LOW, TRANSFORMATION_HIGH, color="#666666",
               alpha=0.13, lw=0)
    ax.axhline(TRANSFORMATION_HIGH, color="#666666", lw=0.6, ls="--")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Genes in the panel, $T$")
    ax.set_ylabel("Independent clones needed")
    ax.set_ylim(1e2, 1e13)
    ax.set_title("Co-transforming singles instead", loc="left", fontsize=6)
    ax.legend(frameon=False, fontsize=4.5, loc="upper left", handlelength=1.6,
              labelspacing=0.35, borderaxespad=0.2)
    box(ax)


def panel_c(ax) -> None:
    """The direct answer: largest constructible panel, per plex."""
    lo = [max_panel_for(k, TRANSFORMATION_LOW) for k in PLEXES]
    hi = [max_panel_for(k, TRANSFORMATION_HIGH) for k in PLEXES]
    xs = np.arange(len(PLEXES))
    ax.bar(xs, hi, width=0.62, color=[PLEX_COLOR[k] for k in PLEXES],
           edgecolor="black", lw=0.5, zorder=2)
    ax.bar(xs, lo, width=0.62, color="white", edgecolor="black", lw=0.5,
           hatch="////", zorder=3)
    for x, l, h in zip(xs, lo, hi):
        ax.text(x, h * 1.25, f"{h:,.0f}", ha="center", fontsize=4.5, zorder=4)
    ax.axhline(6000, color="#666666", lw=0.6, ls="--", zorder=1)
    ax.text(len(PLEXES) - 0.5, 6600, "genome", fontsize=4.5, color="#666666",
            ha="right")
    ax.set_yscale("log")
    ax.set_xticks(xs)
    ax.set_xticklabels([f"$k={k}$" for k in PLEXES])
    ax.set_xlabel("Guides per cell, cloned as combinations")
    ax.set_ylabel("Largest panel that fits")
    ax.set_ylim(1, 4e4)
    ax.set_title("What one transformation buys", loc="left", fontsize=6)
    box(ax)


def main() -> None:
    style()
    os.makedirs(OUT_DIR, exist_ok=True)
    w = PANEL_WIDTHS_MM["full"]
    fig, axes = plt.subplots(1, 3, figsize=(mm_to_in(w), mm_to_in(52)))
    panel_a(axes[0])
    panel_b(axes[1])
    panel_c(axes[2])
    fig.subplots_adjust(left=0.062, right=0.995, top=0.90, bottom=0.19,
                        wspace=0.42)
    place_panel_letters(fig, axes, "abc")
    savefig_true_size_svg(fig, osp.join(OUT_DIR, "library_ceiling.svg"))
    fig.savefig(osp.join(OUT_DIR, "library_ceiling.png"), dpi=300)
    plt.close(fig)

    print("largest constructible panel, cloned combinations")
    for k in PLEXES:
        print(f"  k={k}: {max_panel_for(k, TRANSFORMATION_LOW):>6,.0f} genes at "
              f"1e6 clones, {max_panel_for(k, TRANSFORMATION_HIGH):>6,.0f} at 1e7")
    print(f"\nco-transformed singles need {REDUNDANCY} x T clones at any k: "
          f"{clones_needed(6000, 1):,.0f} for the whole genome")
    print(f"wrote {OUT_DIR}/library_ceiling.svg")


if __name__ == "__main__":
    main()
