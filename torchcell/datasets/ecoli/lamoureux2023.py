"""PRECISE-1K (Lamoureux 2023): the E. coli K-12 MG1655 RNA-seq compendium.

Lamoureux et al. 2023 (Nucleic Acids Res., doi:10.1093/nar/gkad750) assembled 1,035
high-quality RNA-seq profiles, all generated by one lab under one protocol, aligned to
the MG1655 chromosome (NC_000913.3) and released as log2(TPM + 1) over 4,257 genes with a
per-sample metadata table (strain, genotype, medium, carbon and nitrogen source,
supplement, temperature, pH, culture type, evolution status, replicate id). Each record
here is ONE sample: one biological-replicate RNA-seq library, written against the MG1655
assembly set (``ecoli_K12_MG1655_ASM584v2``).

SOURCE. The paper's Data Availability points at Zenodo 10.5281/zenodo.8284223, the
GitHub release ``SBRG/precise1k`` v1.0 (archive root ``SBRG-precise1k-71e1157``). Four
members of that archive are consumed, each retrieved by the versioned
``torchcell.literature.retrieve.zip_member`` retriever with the archive's sha256 pinned
and each member's own sha256 pinned below (``RAW_FILES``). Measured 2026-10-07: Zenodo
answers HTTP 403 to ``retrieve._UA`` (a browser User-Agent) and serves a non-browser one,
so the recorded retrieval re-runs once that string changes; the deposited bytes are the
authority either way:

- ``data/precise1k/log_tpm_qc.csv``: PRECISE-1K itself, 4,257 genes x 1,035 samples.
- ``data/precise1k/counts.csv``: the raw featureCounts read counts (4,355 x 1,055).
- ``data/precise1k/metadata_qc.csv``: the post-QC sample metadata (1,035 rows).
- ``data/precise1k/log_tpm_qc_w_short_low_fpkm.csv``: the same values before the short and
  low-expression genes were removed (4,355 genes), read only to back-solve the pseudocount.

PHENOTYPE (``RNASeqExpressionPhenotype``, ``measurement_type="rnaseq_tpm"``). The schema
field is TPM, so the stored value is ``2**x - 1`` of the release's ``x = log2(TPM + 1)``.
The pseudocount 1 is not printed in the paper (it says "log2[TPM]"); it is BACK-SOLVED from
the release: over the 4,355-gene pre-filter matrix, ``sum(2**x - 1)`` must be 1e6 per sample
for a TPM, and it is, to within 1 TPM, for most samples (the build records the count and
the median in ``preprocess/pseudocount_back_solve.json`` and refuses a median that is not
1e6). The 4,257 stored genes therefore sum to slightly less than 1e6 per sample, because
the removed genes keep their share. ``expression_count`` is the same gene's featureCounts
count. Gene keys go through ``reconcile_locus_tags`` against MG1655 (retain-all).

REPLICATE STRUCTURE. A record is one library; the replicates of a condition are the
records sharing the metadata's ``full_name`` (``project:condition``), and the paper's QC
required "Minimum Pearson correlation with biological replicates (if any) 0.95". The
phenotype class has no ``n_samples`` slot, so no record claims more than its own library;
``preprocess/replicate_groups.json`` lists every condition's records, and
``preprocess/record_samples.json`` maps each LMDB index to its sample id.

REFERENCE. One reference for every record: the release centers its ICA input on the
compendium's control condition ("After centering the Public K-12 dataset to the PRECISE-1K
control condition"), the two ``control:wt_glc`` samples (MG1655, M9 + 2 g/L glucose). The
reference phenotype is that centering vector, ``2**mean(x) - 1`` over the two controls,
with their mean count rounded half to even; its environment is theirs.

GENOTYPE SETTLING (first matching rule, counted in ``preprocess/dropped_records.json``):
an adaptive-laboratory-evolution isolate (``Evolved Sample`` Endpoint/Midpoint) is dropped
because its acquired mutations are not in the release; a strain other than MG1655 is
dropped (BW25113 is another assembly set and writing it against MG1655 would be the
cross-strain inference plan D9 refuses; W3110 has no set in the tier; DGF-298 is a
genome-reduced strain whose deletion set is not in the release; GMOS is a label the
release does not define); a plasmid-borne heterologous or orthologous protein (``pColi``
study) is dropped because the construct, its source organism and its sequence are not
in the release; an activating-region deletion inside ``crp`` is a partial-gene edit with no
coordinates; an ``rpoB`` amino-acid substitution has no bacterial allele leaf. What is
left is wild-type MG1655 (no perturbation) or MG1655 with whole-gene deletions, each a
``BacterialDeletionPerturbation`` on the b-number the deleted gene's symbol resolves to.

ENVIRONMENT (per sample, from the metadata row; the paper prints no recipe). The medium
is a loader-local ``Media`` derived from the library ``M9`` or ``LB`` key the metadata
names, whose base composition is ``composition_deferred`` (the paper and the release state
none); a stated trace-element mixture is a deferred component and a stated selection
antibiotic a ``selection_agent`` component. The carbon and nitrogen sources vary across the
compendium, so each is an ``EnvironmentPhysicalPerturbation``; pH is one too; a supplement
is a ``SmallMoleculePerturbation`` per named compound. Dropped, because the record could
not say what the sample saw: a base medium with no ``MEDIA_LIBRARY`` key (a free-text
medium joins nothing, and no mirrored source states those recipes), a non-batch culture
(``Environment`` has no culture-type slot, so a chemostat would merge with a batch record),
an unstated oxygen regime, and the one supplement label that names two compounds with one
dose (``Acetoacetate/LiCl(10mM)``).
"""

