"""Write every table of ``notes-tex/031-inhibitor-tolerance-data/tables/`` from ``results/``.

Each table is a booktabs ``tabular`` fragment with a GENERATED + SOURCE header, read from
the CSV files the other 031 scripts write. Nothing in ``tables/`` is edited by hand.

Inputs (all under ``experiments/031-env-chemgen-inhibitor-tolerance/results/``):
``axes_table.csv``, ``gene_overlap.csv``, ``compound_overlap.csv``,
``shared_compounds.csv``, ``shared_compounds_{hom,het}.csv``, ``structure_{hom,het}.csv``,
``noise_summary.csv``, ``condition_noise_vanacloig2022.csv``, ``top_matches_hom.csv``,
and, when present, ``embedding_coverage.csv`` and ``chemical_similarity_summary.csv``.
"""

from __future__ import annotations

import os
import os.path as osp

import pandas as pd
from dotenv import load_dotenv

load_dotenv()
EXPERIMENT_ROOT = os.environ["EXPERIMENT_ROOT"]
REPO = osp.dirname(EXPERIMENT_ROOT)
RESULTS = osp.join(EXPERIMENT_ROOT, "031-env-chemgen-inhibitor-tolerance", "results")
TABLES = osp.join(REPO, "notes-tex", "031-inhibitor-tolerance-data", "tables")
SELF = "experiments/031-env-chemgen-inhibitor-tolerance/scripts/notes_tex_tables.py"
LABELS = {
    "vanacloig2022": "Vanacloig 2022",
    "hillenmeyer2008_hom": "Hillenmeyer HOM",
    "hillenmeyer2008_het": "Hillenmeyer HET",
}


def esc(s: object) -> str:
    """Escape the LaTeX specials that appear in compound names and labels."""
    t = str(s)
    for a, b in (("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"), ("|", ", ")):
        t = t.replace(a, b)
    return t


def write(
    name: str,
    source: str,
    colspec: str,
    header: list[str],
    rows: list[list[str]],
    midrules: list[int] | None = None,
) -> None:
    lines = [
        f"%% GENERATED by {SELF}",
        f"%% SOURCE: {source}. Do not edit by hand.",
        f"\\begin{{tabular}}{{{colspec}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
    ]
    for i, r in enumerate(rows):
        if midrules and i in midrules:
            lines.append("\\midrule")
        lines.append(" & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    os.makedirs(TABLES, exist_ok=True)
    with open(osp.join(TABLES, name), "w") as f:
        f.write("\n".join(lines))
    print("wrote", name, f"({len(rows)} rows)")


def n(x: float, d: int = 3) -> str:
    return "" if pd.isna(x) else f"{x:.{d}f}"


def big(x: object) -> str:
    return f"{int(x):,}".replace(",", "{,}")


def t1_axes() -> None:
    a = pd.read_csv(osp.join(RESULTS, "axes_table.csv")).set_index("axis")
    keep = [
        ("records", "records"),
        ("distinct queried genes", "queried genes"),
        ("genes per genotype", "genes per genotype"),
        ("ploidy", "ploidy"),
        ("distinct compounds (InChIKey)", "compounds"),
        ("distinct conditions (compound / physical / temperature)", "conditions"),
        (
            "distinct environments (compound + dose + physical + T + duration + screen)",
            "environments",
        ),
        ("medium base", "medium base"),
        ("aerobicity", "oxygen"),
        ("temperature (C)", "temperature (C)"),
        ("duration (generations)", "duration (generations)"),
        ("dose basis", "dose basis"),
        ("measurement type", "statistic"),
        ("n_samples", "replicates per record"),
    ]

    def short(v: str) -> str:
        parts = [p.strip() for p in str(v).split(";")]
        parts = [p for p in parts if not p.startswith("...")][:3]
        out = "; ".join(parts)
        return esc(out if len(out) <= 52 else out[:49] + "...")

    axes_cols = {
        "vanacloig2022": "Vanacloig 2022",
        "hillenmeyer2008_hom": "Hillenmeyer 2008 HOM",
        "hillenmeyer2008_het": "Hillenmeyer 2008 HET",
    }
    rows = [
        [esc(lbl)] + [short(a.loc[ax, axes_cols[d]]) for d in LABELS]
        for ax, lbl in keep
    ]
    write(
        "t1-axes.tex",
        "results/axes_table.csv from dataset_axes_comparison.py",
        "p{3.2cm}p{3.6cm}p{4.4cm}p{4.4cm}",
        ["axis"] + [LABELS[d] for d in LABELS],
        rows,
    )


def t2_overlap() -> None:
    g = pd.read_csv(osp.join(RESULTS, "gene_overlap.csv"))
    c = pd.read_csv(osp.join(RESULTS, "compound_overlap.csv"))
    rows = []
    for df in (g, c):
        for _, r in df.iterrows():
            pair = (
                f"{r['a']} and {r['b']}"
                if isinstance(r["b"], str) and r["b"]
                else r["a"]
            )
            jac = (
                n(float(r["jaccard"]), 2)
                if r["jaccard"] != "" and not pd.isna(r["jaccard"])
                else ""
            )
            rows.append(
                [
                    esc(r["what"]),
                    esc(pair),
                    big(r["n_a"]) if r["n_a"] != "" and not pd.isna(r["n_a"]) else "",
                    big(r["n_b"]) if r["n_b"] != "" and not pd.isna(r["n_b"]) else "",
                    big(r["shared"]),
                    jac,
                ]
            )
    write(
        "t2-overlap.tex",
        "results/gene_overlap.csv and compound_overlap.csv from dataset_axes_comparison.py",
        "llrrrr",
        ["set", "pair", "$n_a$", "$n_b$", "shared", "Jaccard"],
        rows,
        midrules=[len(g)],
    )


def t3_shared() -> None:
    doses = pd.read_csv(osp.join(RESULTS, "shared_compounds.csv"))
    rows = []
    for arm in ("hom", "het"):
        s = pd.read_csv(osp.join(RESULTS, f"shared_compounds_{arm}.csv"))
        for _, r in s.iterrows():
            d = doses[
                (doses["compound"] == r["hillenmeyer"])
                & (doses["b"].str.contains(arm.upper()))
            ]
            h_dose = esc(d["b_doses"].iloc[0]) if len(d) else "IC30 vs acid"
            v_dose = esc(d["a_doses"].iloc[0]) if len(d) else "IC30"
            dose = (
                f"{v_dose} / {h_dose}".replace("percent\\_v/v", "\\% v/v")
                .replace("ug/mL", "$\\mu$g/mL")
                .replace("uM", "$\\mu$M")
            )
            pair = (
                esc(r["vanacloig"])
                if r["vanacloig"] == r["hillenmeyer"]
                else f"{esc(r['vanacloig'])} / {esc(r['hillenmeyer'])}"
            )
            rows.append(
                [
                    pair,
                    arm.upper(),
                    dose,
                    big(r["n_genes"]),
                    n(r["spearman"]),
                    f"{int(r['rank_of_true_match'])} of {int(r['n_partner_conditions'])}",
                    f"{int(r['hit_overlap'])} ({r['hit_overlap_expected']:.1f})",
                    f"{r['fisher_p']:.1e}",
                ]
            )
    write(
        "t3-shared.tex",
        "results/shared_compounds_{hom,het}.csv and shared_compounds.csv from cross_dataset_similarity.py and dataset_axes_comparison.py",
        "llp{3.6cm}rrrrr",
        [
            "compound (V / H)",
            "arm",
            "dose V / H",
            "genes",
            r"$\rho$",
            "rank",
            "hits (exp.)",
            "Fisher $p$",
        ],
        rows,
    )


def t4_noise() -> None:
    s = pd.read_csv(osp.join(RESULTS, "noise_summary.csv")).set_index("dataset")
    items = [
        ("records", lambda r: big(r["records"])),
        ("records with one replicate", lambda r: f"{100 * r['n_samples_1']:.0f}\\%"),
        ("records with a served SE", lambda r: f"{100 * r['frac_with_se']:.0f}\\%"),
        ("SE median", lambda r: n(r["se_median"])),
        ("response SD", lambda r: n(r["response_sd"])),
        ("conditions", lambda r: big(r["conditions"])),
        ("reliability index, median", lambda r: n(r["reliability_median"])),
        ("reliability index, 25th pct", lambda r: n(r["reliability_q25"])),
        ("ceiling on $r$ vs truth, median", lambda r: n(r["ceiling_r_truth_median"])),
        ("conditions with no signal", lambda r: big(r["conditions_no_signal"])),
        (
            "raw conditions with replicates",
            lambda r: big(r["raw_conditions_with_replicates"]),
        ),
        ("replicate Spearman, median", lambda r: n(r["replicate_rho_median"])),
        ("bottom-5\\% hit Jaccard, median", lambda r: n(r["hit_jaccard_median"])),
        (
            "index vs replicate Spearman (rank)",
            lambda r: n(r["index_vs_replicate_rho"], 2),
        ),
    ]
    rows = [[lbl] + [fn(s.loc[d]) for d in LABELS] for lbl, fn in items]
    write(
        "t4-noise.tex",
        "results/noise_summary.csv from replicate_noise_and_ceilings.py",
        "lrrr",
        [""] + [LABELS[d] for d in LABELS],
        rows,
    )


