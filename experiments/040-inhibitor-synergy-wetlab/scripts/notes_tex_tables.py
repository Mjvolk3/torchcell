def t15_nominations(nom: pd.DataFrame) -> None:
    cats = [
        ("core", "Core, sensitive in at least four of six singles"),
        ("specific", "Compound specific, sensitive in exactly one member"),
        ("conflict", "Conflict, sensitive in one member and resistant in another"),
        ("composed_top", "Composed top 100"),
    ]
    sub = nom[nom["rule"] == "sum"]
    rows = []
    for key, label in cats:
        row = [label]
        for version in ("best_available", "all_predicted"):
            s = sub[(sub["version"] == version) & (sub["category"] == key)]
            if not len(s):
                row += ["", ""]
                continue
            row += [
                str(int(s["n_genes"].median())),
                f"{int(s['n_genes'].min())} to {int(s['n_genes'].max())}",
            ]
        rows.append(row)
    n_comb = sub["combination"].nunique()
    write_table(
        "t15-nominations.tex",
        tabular(
            "p{62mm}rlrl",
            [
                ["Category", "Median genes,", "Range,", "Median genes,", "Range,"],
                [
                    "",
                    "best available (n)",
                    "best available (n)",
                    "all predicted (n)",
                    "all predicted (n)",
                ],
            ],
            rows,
        )
        + f"\n%% over {n_comb} combinations, rule sum\n",
    )


