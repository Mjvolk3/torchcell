    if not osp.exists(p):
        print("skip t8: no chemical_similarity_summary.csv yet")
        return
    s = pd.read_csv(p)
    rows = [
        [
            esc(r["encoder"]),
            esc(r["partner"]),
            n(r["nn_similarity_median"], 2),
            big(r["n_vanacloig_with_neighbor_above_0.5"]),
            n(r["chem_vs_response_spearman"], 3),
            f"{r['chem_vs_response_p']:.1e}",
            n(r["top_decile_response_rho"], 3),
            n(r["rest_response_rho"], 3),
        ]
        for _, r in s.iterrows()
    ]
    write(
        "t8-chemsim.tex",
        "results/chemical_similarity_summary.csv from chemical_similarity.py",
        "llrrrrrr",
        [
            "encoder",
            "partner",
            "NN sim. median",
            "V with NN $>0.5$",
            "chem vs response $\\rho$",
            "$p$",
            "top-decile $\\rho$",
            "rest $\\rho$",
        ],
        rows,
    )


