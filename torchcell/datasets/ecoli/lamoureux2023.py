class RnaseqLamoureux2023Dataset(ExperimentDataset):
    """PRECISE-1K: one record per MG1655 RNA-seq library (wild type or deletions)."""

    REFERENCE_STRAIN: ClassVar[EcoliK12StrainName] = REFERENCE_STRAIN_NAME

    def __init__(
        self,
        root: str = "data/torchcell/rnaseq_lamoureux2023",
        io_workers: int = 0,
        ecoli_genome: EcoliK12Genome | None = None,
        transform: Callable[..., Any] | None = None,
        pre_transform: Callable[..., Any] | None = None,
        **kwargs: Any,
    ) -> None:
        """Initialize; the MG1655 genome is injected by the build or opened in process."""
        self.ecoli_genome = ecoli_genome
        super().__init__(root, io_workers, transform, pre_transform, **kwargs)

    @property
    def experiment_class(self) -> type[Experiment]:
        """Experiment schema class produced by this dataset."""
        return BacterialRNASeqExpressionExperiment

    @property
    def reference_class(self) -> type[ExperimentReference]:
        """Experiment-reference schema class produced by this dataset."""
        return BacterialRNASeqExpressionExperimentReference

    @property
    def raw_file_names(self) -> list[str]:
        """The four release members required before processing."""
        return [raw.name for raw in RAW_FILES]

    def download(self) -> None:
        """Link each mirror file into ``raw/`` after verifying it against its pin.

        The mirror + the pins are canonical; the Zenodo URL is retrieval metadata that
        ``deposit_raw_mirror`` re-runs, never a live build dependency. The manifest must
        carry each pin, else ``ManifestPinMismatchError`` names both digests.
        """
        data_root = _data_root()
        manifest = load_manifest(data_root)
        os.makedirs(self.raw_dir, exist_ok=True)
        for raw in RAW_FILES:
            check_manifest_pin(
                raw.relpath, manifest_sha256(manifest, raw.relpath), raw.sha256
            )
            src = raw_mirror_dir(data_root) / raw.relpath
            if not src.exists():
                raise RuntimeError(f"required raw artifact missing from mirror: {src}")
            link_verified(src, osp.join(self.raw_dir, raw.name), raw.sha256)
        log.info(
            "PRECISE-1K raw members linked into %s (sha256 verified)", self.raw_dir
        )

    def _genome(self) -> EcoliK12Genome:
        """The injected MG1655 genome, or the default cache opened read-only."""
        if self.ecoli_genome is None:
            self.ecoli_genome = bacterial_genome("ecoli", self.REFERENCE_STRAIN)
        return self.ecoli_genome

    def _write_json(self, name: str, payload: Any) -> None:
        with open(osp.join(self.preprocess_dir, name), "w") as handle:
            json.dump(payload, handle, indent=2, default=str)

    def _deletion_tags(
        self, genome: EcoliK12Genome, symbols: list[str]
    ) -> tuple[dict[str, tuple[str, str]], LocusTagReconciliation]:
        """Each deleted gene symbol -> (b-number, the genome's own symbol for it).

        Every symbol must resolve to one MG1655 locus (a deletion cannot be written
        against a name the genome does not carry), and the genome's symbol must resolve
        back to the same locus, so one gene has one spelling across datasets.
        """
        names = pd.Series(sorted(set(symbols)))
        stored, report = reconcile_locus_tags(
            genome, names, label=f"{self.name} deleted genes"
        )
        report.require_resolved(1.0)
        if report.outside_namespace:
            raise RuntimeError(
                f"deleted-gene symbols not stored as b-numbers: {report.outside_namespace}"
            )
        mapping: dict[str, tuple[str, str]] = {}
        for symbol, tag in zip(names, stored, strict=True):
            canonical = genome.genbank.loci[tag].symbol or symbol
            if genome.resolve_gene_name(canonical).systematic_name != tag:
                raise RuntimeError(
                    f"{canonical!r}, the genome's symbol of {tag}, does not resolve back"
                )
            mapping[symbol] = (tag, canonical)
        return mapping, report

    def _genotype(
        self, verdict: GenotypeVerdict, tags: Mapping[str, tuple[str, str]]
    ) -> Genotype:
        return Genotype(
            perturbations=[
                BacterialDeletionPerturbation(
                    systematic_gene_name=tags[symbol][0],
                    perturbed_gene_name=tags[symbol][1],
                    gene_namespace=GENE_NAMESPACE,
                )
                for symbol in verdict.deleted_symbols
            ]
        )

    @post_process
    def process(self) -> None:
        """Settle every sample's genotype and environment, then write the LMDB."""
        verify_raw_files(self.raw_dir, {raw.name: raw.sha256 for raw in RAW_FILES})
        genome = self._genome()
        os.makedirs(self.preprocess_dir, exist_ok=True)
        os.makedirs(self.processed_dir, exist_ok=True)

        metadata = read_metadata(osp.join(self.raw_dir, METADATA.name))
        released = pd.read_csv(osp.join(self.raw_dir, LOG_TPM.name), index_col=0)
        prefilter = pd.read_csv(
            osp.join(self.raw_dir, LOG_TPM_PREFILTER.name), index_col=0
        )
        counts = pd.read_csv(osp.join(self.raw_dir, COUNTS.name), index_col=0)
        if sorted(released.columns) != sorted(metadata.index):
            raise RuntimeError("expression samples and metadata rows differ")
        if not set(released.columns) <= set(counts.columns):
            raise RuntimeError("counts.csv lacks samples of the released matrix")
        if not set(released.index) <= set(counts.index):
            raise RuntimeError("counts.csv lacks genes of the released matrix")

        back_solve = back_solve_pseudocount(released, prefilter)
        self._write_json("pseudocount_back_solve.json", back_solve.model_dump())
        del prefilter

        source_genes = list(released.index)
        stored_genes, gene_report = reconcile_locus_tags(
            genome, pd.Series(source_genes), label=f"{self.name} expression genes"
        )
        gene_report.require_resolved(EXPRESSION_MIN_RESOLVED)
        genes = list(stored_genes)

        samples = sorted(str(sample) for sample in metadata.index)
        rows = {sample: metadata_row(metadata, sample) for sample in samples}
        genotype_verdicts: dict[str, GenotypeVerdict] = {}
        environment_verdicts: dict[str, EnvironmentVerdict] = {}
        dropped: dict[str, list[str]] = {}
        stage_of: dict[str, Literal["genotype", "environment"]] = {}
        kept: list[str] = []
        for sample in samples:
            row = rows[sample]
            g_verdict = settle_genotype(row)
            genotype_verdicts[sample] = g_verdict
            if not g_verdict.kept:
                dropped.setdefault(g_verdict.rule.value, []).append(sample)
                stage_of[g_verdict.rule.value] = "genotype"
                continue
            e_verdict = settle_environment(row)
            environment_verdicts[sample] = e_verdict
            if e_verdict.rule is not None:
                dropped.setdefault(e_verdict.rule.value, []).append(sample)
                stage_of[e_verdict.rule.value] = "environment"
                continue
            kept.append(sample)

        controls = sorted(s for s in samples if rows[s][COL_PROJECT] == CONTROL_PROJECT)
        for control in controls:
            if rows[control][COL_PROJECT_REFERENCE].split(";") != controls:
                raise RuntimeError(
                    f"control sample {control} names reference "
                    f"{rows[control][COL_PROJECT_REFERENCE]!r}, not {controls}"
                )
            if control not in kept:
                raise RuntimeError(f"control sample {control} was not kept")
        control_specs = {environment_verdicts[c].spec for c in controls}
        if len(control_specs) != 1:
            raise RuntimeError("the control samples do not share one environment")

        deleted = [
            symbol for s in kept for symbol in genotype_verdicts[s].deleted_symbols
        ]
        tags, deletion_report = self._deletion_tags(genome, deleted)
        self._write_json(
            "locus_tag_reconciliation.json",
            {
                "expression_genes": gene_report.model_dump(mode="json"),
                "deleted_genes": deletion_report.model_dump(mode="json"),
                "deleted_symbol_to_locus": {
                    s: list(v) for s, v in sorted(tags.items())
                },
            },
        )

        log_values = released[samples].to_numpy(dtype=np.float64)
        count_values = counts.loc[source_genes, samples].to_numpy(dtype=np.int64)
        column = {sample: i for i, sample in enumerate(samples)}
        control_columns = [column[c] for c in controls]
        reference_phenotype = RNASeqExpressionPhenotype(
            expression_tpm=dict(
                zip(
                    genes,
                    to_tpm(log_values[:, control_columns].mean(axis=1)),
                    strict=True,
                )
            ),
            expression_count={
                g: int(round(float(c)))
                for g, c in zip(
                    genes, count_values[:, control_columns].mean(axis=1), strict=True
                )
            },
            measurement_type=MEASUREMENT_TYPE,
            provenance_gaps=[MAPPED_READS_GAP],
        )
        environments: dict[ConditionSpec, Environment] = {}

        def environment_of(sample: str) -> Environment:
            spec = environment_verdicts[sample].spec
            if spec is None:
                raise RuntimeError(f"kept sample {sample} has no parsed condition")
            if spec not in environments:
                environments[spec] = build_environment(spec)
            return environments[spec]

        reference = BacterialRNASeqExpressionExperimentReference(
            dataset_name=self.name,
            genome_reference=assembly_reference(self.REFERENCE_STRAIN),
            environment_reference=environment_of(controls[0]),
            phenotype_reference=reference_phenotype,
        )
        publication = Publication(doi=PAPER_DOI, doi_url=f"https://doi.org/{PAPER_DOI}")

        env, interned_env = self._open_write_lmdb(osp.join(self.processed_dir, "lmdb"))
        groups: dict[str, ReplicateGroup] = {}
        with env.begin(write=True) as txn, interned_env.begin(write=True) as itxn:
            for idx, sample in enumerate(kept):
                experiment = BacterialRNASeqExpressionExperiment(
                    dataset_name=self.name,
                    genotype=self._genotype(genotype_verdicts[sample], tags),
                    environment=environment_of(sample),
                    phenotype=rnaseq_phenotype(
                        genes,
                        log_values[:, column[sample]],
                        count_values[:, column[sample]],
                    ),
                )
                txn.put(
                    f"{idx}".encode(),
                    self._intern_record(experiment, reference, publication, itxn),
                )
                full_name = rows[sample][COL_FULL_NAME]
                cells = {c: rows[sample][c] for c in CONDITION_COLUMNS}
                group = groups.setdefault(
                    full_name,
                    ReplicateGroup(
                        full_name=full_name,
                        condition_cells=cells,
                        samples=[],
                        record_indices=[],
                        metadata_biological_replicates=[],
                    ),
                )
                if group.condition_cells != cells:
                    raise RuntimeError(
                        f"replicates of {full_name} differ in their condition cells"
                    )
                group.samples.append(sample)
                group.record_indices.append(idx)
                group.metadata_biological_replicates.append(
                    rows[sample][COL_REPLICATES]
                )
        env.close()
        interned_env.close()

        rules = [
            DropRule(
                rule=rule,
                stage=stage_of[rule],
                description=(
                    GENOTYPE_RULE_REASONS[GenotypeRule(rule)]
                    if stage_of[rule] == "genotype"
                    else ENVIRONMENT_RULE_REASONS[EnvironmentRule(rule)]
                ),
                n_records=len(items),
                samples=items,
            )
            for rule, items in dropped.items()
        ]
        drop_log = DropLog(
            dataset=self.name,
            source_records=len(samples),
            kept_records=len(kept),
            dropped_records=len(samples) - len(kept),
            rules=sorted(rules, key=lambda r: (r.stage != "genotype", -r.n_records)),
            kept_by_genotype_class=dict(
                sorted(
                    Counter(genotype_class(genotype_verdicts[s]) for s in kept).items()
                )
            ),
            kept_by_base_media=dict(
                sorted(Counter(rows[s][COL_MEDIA] for s in kept).items())
            ),
        )
        if sum(r.n_records for r in drop_log.rules) != drop_log.dropped_records:
            raise RuntimeError("drop accounting mismatch")
        self._write_json("dropped_records.json", drop_log.model_dump())
        self._write_json(
            "replicate_groups.json",
            [
                g.model_dump()
                for g in sorted(groups.values(), key=lambda g: g.full_name)
            ],
        )
        self._write_json("record_samples.json", kept)
        log.info(
            "Wrote %d PRECISE-1K records (%d dropped) over %d conditions",
            len(kept),
            drop_log.dropped_records,
            len(groups),
        )

    def preprocess_raw(
        self, df: pd.DataFrame, preprocess: dict[str, Any] | None = None
    ) -> pd.DataFrame:
        """Preprocessing is handled inside process() for this dataset."""
        return df

    def create_experiment(self) -> None:
        """Experiment construction is handled inline in process() for this dataset."""
        raise NotImplementedError


def main() -> None:
    """Build/load the dataset for interactive debugging."""
    from dotenv import load_dotenv

    load_dotenv()
    data_root = os.environ["DATA_ROOT"]
    root = osp.join(data_root, "data/torchcell/rnaseq_lamoureux2023")
    dataset = RnaseqLamoureux2023Dataset(root=root)
    print(f"len = {len(dataset)}")
    print(dataset[0]["experiment"]["genotype"])
    drop_log = json.loads(
        Path(osp.join(root, "preprocess/dropped_records.json")).read_text()
    )
    print(json.dumps({r["rule"]: r["n_records"] for r in drop_log["rules"]}, indent=2))


if __name__ == "__main__":
    main()
