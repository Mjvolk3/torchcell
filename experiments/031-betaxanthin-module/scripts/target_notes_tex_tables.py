def store_baselines(target: str) -> str | None:
    """The CPU ladder over the store representations of one target."""
    src = results(target, f"store_baselines_{target}.json")
    if not osp.isfile(src):
        return None
    with open(src) as fh:
        d = json.load(fh)
    rows = []
    for rep, o in d["representations"].items():
        cells = []
        for model in ("ridge", "knn", "forest"):
            tp = o[model]["selected_on_val"]["test_pinned"]
            cell = f"{tp['mean_spearman']:+.3f}"
            if tp.get("top50_enrichment") is not None:
                cell += f" / {tp['top50_enrichment']:.2f}"
            cells.append(cell)
        rows.append(
            f"    {STORE_LABELS.get(rep, rep)} & {o['dim']} & "
            + " & ".join(cells)
            + " \\\\"
        )
    cell_note = {
        "betaxanthin": "the cell is the pinned-test Spearman and, after the slash, the top-50 enrichment",
        "amino_acids": "the cell is the mean pinned-test Spearman over the 19 amino acids",
        "cooper": (
            "the target is Cooper 2010's 17 CE-LIF peaks (a linear ratio to the plate mean, "
            "the auxotroph on synthetic complete medium), read from the loader's table by the "
            f"record's deleted gene on the same pinned split ({d['n_pinned']['test']} pinned "
            "test genotypes carry a Cooper row), over the SM stores of the prototroph; the "
            "cell is the mean pinned-test Spearman over the 17 peaks"
        ),
    }[target]
    name = "store_baselines" if target != "cooper" else "store_baselines_cooper"
    label = (
        "tab:store-baselines" if target != "cooper" else "tab:store-baselines-cooper"
    )
    body = (
        "\\begin{table}[H]\n  \\centering\n  \\footnotesize\n"
        "  \\caption[CPU baselines over the store representations]{Each deleted gene "
        "represented by one row of a store ($\\log(1+|v|)$ of the flux columns, "
        "standardized on the training genes; a gene the store does not cover reads the "
        "wild-type row), fit by the 027 ladder's ridge (rank-swept bilinear for the amino "
        "acids) and cosine nearest neighbors, every training row tied at the $k$-th "
        "similarity averaged in, and by a 300-tree random forest, the Flux Cone Learning "
        "form on one point. Selected on validation per-feature Pearson rounded to "
        f"$10^{{-6}}$; {cell_note}. Written by "
        "\\texttt{target\\_notes\\_tex\\_tables.py} from "
        f"\\texttt{{results/store\\_baselines\\_{target.replace('_', '\\_')}.json}} "
        "(\\texttt{target\\_store\\_baselines.py}).}\n"
        f"  \\label{{{label}}}\n"
        "  \\begin{tabular}{@{}p{62mm}rrrr@{}}\n    \\hline\n"
        "    representation & columns & ridge & kNN & forest \\\\\n    \\hline\n"
        + "\n".join(rows)
        + "\n    \\hline\n  \\end{tabular}\n\\end{table}\n"
    )
    return write(target, name, body, f"results/store_baselines_{target}.json")


