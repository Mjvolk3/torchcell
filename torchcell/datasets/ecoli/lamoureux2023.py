class GenotypeVerdict(BaseModel):
    """The settled genotype of one sample, or the rule that dropped it."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    rule: GenotypeRule
    deleted_symbols: tuple[str, ...] = ()

    @property
    def kept(self) -> bool:
        """True for wild type or whole-gene deletions."""
        return self.rule in KEPT_GENOTYPE_RULES


def _description_tokens(description: str) -> list[str]:
    """The edit tokens after the strain words of a ``Strain Description`` cell."""
    for prefix in _DESCRIPTION_PREFIXES:
        if description.startswith(prefix):
            return description[len(prefix) :].split()
    raise ValueError(f"unrecognized Strain Description {description!r}")


def settle_genotype(row: Mapping[str, str]) -> GenotypeVerdict:
    """Settle one metadata row's genotype against MG1655 (first matching rule).

    ``row`` holds the verbatim cells (blank = ""). An unrecognized strain or an edit
    token of no known form raises rather than guessing.
    """
    if row[COL_EVOLVED] in EVOLVED_VALUES:
        return GenotypeVerdict(rule=GenotypeRule.evolved_isolate)
    if row[COL_EVOLVED] != "No":
        raise ValueError(f"unknown Evolved Sample cell {row[COL_EVOLVED]!r}")
    strain = row[COL_STRAIN]
    if strain != REFERENCE_STRAIN_NAME:
        if strain not in STRAIN_RULES:
            raise ValueError(f"unknown Strain cell {strain!r}")
        return GenotypeVerdict(rule=STRAIN_RULES[strain])
    if row[COL_STUDY] == HETEROLOGOUS_STUDY:
        return GenotypeVerdict(rule=GenotypeRule.heterologous_expression_construct)
    description = row[COL_DESCRIPTION]
    if description == WILD_TYPE_DESCRIPTION:
        return GenotypeVerdict(rule=GenotypeRule.wild_type)
    tokens = _description_tokens(description)
    if not tokens:
        raise ValueError(f"Strain Description {description!r} names no strain or edit")
    if any(_PARTIAL_EDIT_TOKEN.match(t) for t in tokens):
        return GenotypeVerdict(rule=GenotypeRule.partial_gene_edit)
    if any(_SUBSTITUTION_TOKEN.match(t) for t in tokens):
        return GenotypeVerdict(rule=GenotypeRule.point_mutation_allele)
    genes: list[str] = []
    for token in tokens:
        match = _DELETION_TOKEN.match(token)
        if match is None:
            raise ValueError(
                f"Strain Description {description!r}: edit token {token!r} is of no "
                "known form"
            )
        genes.append(match.group("gene"))
    if len(set(genes)) != len(genes):
        raise ValueError(f"Strain Description {description!r} repeats a deletion")
    return GenotypeVerdict(rule=GenotypeRule.deletion, deleted_symbols=tuple(genes))


