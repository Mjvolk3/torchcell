def left(cm: float) -> str:
    """A ragged-right column of fixed width, so a long header wraps."""
    return rf">{{\raggedright\arraybackslash}}p{{{cm}cm}}"


def right(cm: float) -> str:
    """A ragged-left column of fixed width, for numbers under a wrapping header."""
    return rf">{{\raggedleft\arraybackslash}}p{{{cm}cm}}"


def esc(text: object) -> str:
    """LaTeX-escape a cell."""
    s = str(text)
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"), ("&", r"\&")):
        s = s.replace(a, b)
    return s


def n(value: float) -> str:
    return f"{int(round(value)):,}"


def f(value: float, digits: int = 2) -> str:
    return "" if pd.isna(value) else f"{value:.{digits}f}"


def pct(value: float, digits: int = 1) -> str:
    return f"{100 * value:.{digits}f}"


def tex_table(df: pd.DataFrame, align: str) -> str:
    """A bare tabular, no caption: the document supplies the float and the caption."""
    # \hspace{0pt} lets TeX hyphenate the first word of a narrow header cell
    head = (
        " & ".join(rf"\textbf{{\hspace{{0pt}}{esc(c)}}}" for c in df.columns) + r" \\"
    )
    body = "\n".join(
        " & ".join(esc(v) for v in row) + r" \\" for row in df.itertuples(index=False)
    )
    return (
        f"\\begin{{tabular}}{{{align}}}\n\\toprule\n{head}\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n"
    )


def write(name: str, text: str, source: str) -> None:
    os.makedirs(TABLES_DIR, exist_ok=True)
    path = osp.join(TABLES_DIR, f"{name}.tex")
    with open(path, "w") as fh:
        fh.write(
            f"%% GENERATED by {SCRIPT}\n"
            f"%% SOURCE: experiments/033-env-chemgen-pooled/results/{source}\n"
            "%% Do not edit by hand.\n" + text
        )
    print(f"  wrote {path}")


def values_only(tally: str) -> str:
    """``value:count|value:count`` as the values alone, largest count first."""
    pairs = [item.rsplit(":", 1) for item in tally.split("|")]
    pairs.sort(key=lambda p: -int(p[1]))
    return ", ".join(v for v, _ in pairs)


def distinct(tally: str) -> int:
    """How many stated values a tally holds."""
    return sum(1 for item in tally.split("|") if not item.startswith("unstated:"))


def reading(plan: float, store: float, tolerance: float) -> str:
    """``holds`` when the store value is within ``tolerance`` of the plan's, relative."""
    return "holds" if abs(store - plan) <= tolerance * abs(plan) else "differs"


def t0_scorecard(results: str) -> None:
    axes = pd.read_csv(osp.join(results, "store_axes.csv")).set_index("dataset")
    units = pd.read_csv(osp.join(results, "unit_of_analysis.csv")).set_index("dataset")
    ploidy = pd.read_csv(osp.join(results, "ploidy_pairs.csv")).set_index("level")
    policy = pd.read_csv(osp.join(results, "label_policy.csv")).set_index("dataset")
    pairs = pd.read_csv(osp.join(results, "within_cell_pairs.csv"))
    folds = pd.read_csv(osp.join(results, "vanacloig_folds.csv"))
    target = pd.read_csv(osp.join(results, "standardized_target.csv")).set_index(
        "dataset"
    )
    embed = pd.read_csv(osp.join(results, "embedding_coverage_store.csv"))
    fcfp = embed[
        (embed["encoder"] == "fcfp4_count") & (embed["dataset"] == "All four")
    ].iloc[0]

    rows = []

    def add(claim: str, plan: str, store: str, verdict: str) -> None:
        rows.append(
            {"plan claim": claim, "plan": plan, "store": store, "reading": verdict}
        )

    records = int(axes["measurements"].sum())
    add(
        "records in the four kept datasets",
        n(PLAN_STATED["records"][0]),
        n(records),
        reading(PLAN_STATED["records"][0], records, 0.0),
    )
    share = axes.loc["Vanacloig 2022", "cells"] / axes["cells"].sum()
    add(
        "Vanacloig share of the pool, percent",
        pct(PLAN_STATED["vanacloig_share"][0]),
        pct(share),
        reading(PLAN_STATED["vanacloig_share"][0], share, 0.15),
    )
    plan_pairs = int(units["plan_pair_cells"].sum())
    add(
        "training rows, the plan's (gene, compound) pairs against store cells",
        n(plan_pairs),
        n(axes["cells"].sum()),
        reading(plan_pairs, axes["cells"].sum(), 0.05),
    )
    both = int(ploidy.loc["same compound", "cells_both"])
    add(
        "Hoepfner cells in both ploidy arms, same compound",
        n(PLAN_STATED["paired_ploidy_cells"][0]),
        n(both),
        reading(PLAN_STATED["paired_ploidy_cells"][0], both, 0.01),
    )
    same_env = int(ploidy.loc["same environment", "cells_both"])
    add(
        "Hoepfner cells in both ploidy arms, same environment",
        "not measured",
        n(same_env),
        "new",
    )
    plan_ratio = units["plan_pair_sd"].max() / units["plan_pair_sd"].min()
    store_ratio = units["store_sd"].max() / units["store_sd"].min()
    add(
        "widest over narrowest response sd",
        f(plan_ratio, 1),
        f(store_ratio, 1),
        reading(plan_ratio, store_ratio, 0.10),
    )
    flips = [SHORT[d] for d in target.index if target.loc[d, "orientation"] == -1]
    positive = [SHORT[d] for d in units.index if units.loc[d, "store_skew"] > 0]
    add(
        "sources whose sick tail is positive",
        ", ".join(flips),
        ", ".join(positive),
        "holds" if flips == positive else "differs",
    )
    ceiling = float(folds["ceiling_r_truth"].median())
    add(
        "Vanacloig median ceiling over 41 compounds",
        f(PLAN_STATED["vanacloig_ceiling_median"][0]),
        f(ceiling),
        reading(PLAN_STATED["vanacloig_ceiling_median"][0], ceiling, 0.02),
    )
    no_signal = int((folds["reliability"] <= 0).sum())
    add(
        "Vanacloig compounds with no signal",
        n(PLAN_STATED["vanacloig_no_signal"][0]),
        n(no_signal),
        reading(PLAN_STATED["vanacloig_no_signal"][0], no_signal, 0.0),
    )
    hoepfner = pairs[pairs["dataset"] == "Hoepfner 2014"]
    add(
        "Hoepfner repeated screen pairs",
        n(PLAN_STATED["hoepfner_screen_pairs"][0]),
        n(len(hoepfner)),
        reading(PLAN_STATED["hoepfner_screen_pairs"][0], len(hoepfner), 0.0),
    )
    add(
        "Hoepfner median reliability of one served value",
        f(PLAN_STATED["hoepfner_reliability_median"][0], 3),
        f(hoepfner["pearson"].median(), 3),
        reading(
            PLAN_STATED["hoepfner_reliability_median"][0],
            hoepfner["pearson"].median(),
            0.02,
        ),
    )
    repeated = int(policy["cells_repeated"].sum())
    add(
        "label of a repeated cell",
        "a read-time policy",
        f"the last measurement, {n(repeated)} cells",
        "new",
    )
    compounds = int(fcfp["compounds"])
    embedded = int(fcfp["compounds_embedded"])
    add(
        "dosed compounds with an FCFP4 vector",
        "all",
        f"{n(embedded)} of {n(compounds)}",
        "holds" if embedded == compounds else "differs",
    )
    no_vector = int(fcfp["cells"] - fcfp["cells_with_every_vector"])
    add("cells with no complete compound vector", "not measured", n(no_vector), "new")
    varying = [
        SHORT[d]
        for d in axes.index
        if any(distinct(axes.loc[d, field]) > 1 for field in PHYSICAL_FIELDS)
    ]
    add(
        "sources where a physical or medium field varies",
        "none",
        ", ".join(varying) if varying else "none",
        "holds" if not varying else "differs",
    )
    write(
        "t0-scorecard",
        tex_table(pd.DataFrame(rows), "p{7.4cm}p{2.6cm}p{4.2cm}l"),
        "store_axes.csv, unit_of_analysis.csv, ploidy_pairs.csv, label_policy.csv, "
        "within_cell_pairs.csv, vanacloig_folds.csv, standardized_target.csv and "
        "embedding_coverage_store.csv from store_against_plan.py",
    )


