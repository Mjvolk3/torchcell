"""Render the tables of ``notes-tex/031-unified-representation`` from the result CSVs.

Every table in that document is generated here from a file another script in this folder
wrote, so no number is hand-authored. Reads ``results/*.csv`` and writes
``notes-tex/031-unified-representation/tables/*.tex``.
"""

from __future__ import annotations

import os
import os.path as osp

import pandas as pd
from dotenv import load_dotenv

load_dotenv()
EXPERIMENT_ROOT = os.environ["EXPERIMENT_ROOT"]
RESULTS = osp.join(EXPERIMENT_ROOT, "031-env-chemgen-inhibitor-tolerance", "results")
REPO = osp.dirname(osp.dirname(osp.abspath(EXPERIMENT_ROOT.rstrip("/"))))
TABLES = osp.join(
    osp.dirname(EXPERIMENT_ROOT.rstrip("/")),
    "notes-tex",
    "031-unified-representation",
    "tables",
)
LABEL = {
    "vanacloig2022": "Vanacloig 2022",
    "hillenmeyer2008_hom": "Hillenmeyer HOM",
    "hillenmeyer2008_het": "Hillenmeyer HET",
    "hoepfner2014": "Hoepfner 2014",
    "wildenhain2015": "Wildenhain 2015",
}
ORDER = list(LABEL)


def esc(text: object) -> str:
    """LaTeX-escape a cell."""
    s = str(text)
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"), ("&", r"\&")):
        s = s.replace(a, b)
    return s


def tex_table(df: pd.DataFrame, align: str | None = None) -> str:
    """A bare tabular, no caption: the document supplies the float and the caption."""
    cols = align or ("l" + "r" * (len(df.columns) - 1))
    head = " & ".join(rf"\textbf{{{esc(c)}}}" for c in df.columns) + r" \\"
    body = "\n".join(
        " & ".join(esc(v) for v in row) + r" \\" for row in df.itertuples(index=False)
    )
    return (
        f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n{head}\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n"
    )


def write(name: str, text: str, source: str) -> None:
    """Write one tabular, naming the result file it came from so the gate can see it."""
    os.makedirs(TABLES, exist_ok=True)
    path = osp.join(TABLES, f"{name}.tex")
    with open(path, "w") as fh:
        fh.write(
            "%% GENERATED by experiments/031-env-chemgen-inhibitor-tolerance/scripts/"
            "notes_tex_representation_tables.py\n"
            f"%% SOURCE: experiments/031-env-chemgen-inhibitor-tolerance/results/{source}\n"
            "%% Do not edit by hand.\n" + text
        )
    print(f"  wrote {path}")


def t1_datasets() -> None:
    """The five datasets on the axes a shared representation has to absorb."""
    dose = pd.read_csv(osp.join(RESULTS, "dose_axis_summary.csv")).set_index("dataset")
    rows = []
    for name in ORDER:
        records = pd.read_parquet(
            osp.join(RESULTS, f"records_{name}.parquet"),
            columns=["gene", "ref_ploidy", "perturbation_type"],
        )
        d = dose.loc[name]
        rows.append(
            {
                "dataset": LABEL[name],
                "records": f"{len(records):,}",
                "genes": f"{records['gene'].nunique():,}",
                "compounds": f"{int(d['compounds']):,}",
                "ploidy": "|".join(sorted(set(records["ref_ploidy"].astype(str)))),
                "dose basis": d["dose_bases"].replace("|", ", ")
                if isinstance(d["dose_bases"], str)
                else "none",
                # the percent sign is escaped once, by esc(), not here
                "molar": f"{100 * float(d['frac_convertible_to_molar']):.0f}%",
            }
        )
    write(
        "t1-datasets",
        tex_table(pd.DataFrame(rows), align="lrrrllr"),
        "dose_axis_summary.csv and records_*.parquet",
    )


def t2_chemical_space() -> None:
    """How much of the Vanacloig panel each partner covers chemically."""
    df = pd.read_csv(osp.join(RESULTS, "chemical_space_thresholds.csv"))
    df = df.rename(
        columns={
            "source": "source",
            "n_exact_match": "exact",
            "nn_similarity_median": "median NN",
            "n_above_0.5": "above 0.5",
            "n_above_0.7": "above 0.7",
        }
    )
    df["source"] = df["source"].map(lambda s: LABEL.get(s, s.replace("_", " ")))
    df["median NN"] = df["median NN"].map(lambda v: f"{v:.3f}")
    out = df[["source", "exact", "median NN", "above 0.5", "above 0.7"]]
    write("t2-chemical-space", tex_table(out), "chemical_space_thresholds.csv")


def t3_yeast9() -> None:
    """Yeast9 structure coverage and the classes that have no structure."""
    cls = pd.read_csv(osp.join(RESULTS, "yeast9_failure_classes.csv"))
    col = "structure_class" if "structure_class" in cls.columns else cls.columns[0]
    keep = [c for c in cls.columns if c != col and cls[c].dtype.kind in "if"][:3]
    out = cls[[col, *keep]].head(11)
    write("t3-yeast9-classes", tex_table(out), "yeast9_failure_classes.csv")


def t4_encoder_yeast9() -> None:
    """Encoder coverage over the structure-bearing Yeast9 species."""
    df = pd.read_csv(osp.join(RESULTS, "yeast9_encoder_coverage.csv"))
    cols = [
        c
        for c in ("encoder", "dim", "n_attempted", "n_embedded", "n_failed")
        if c in df.columns
    ]
    write("t4-yeast9-encoders", tex_table(df[cols]), "yeast9_encoder_coverage.csv")


def main() -> None:
    t1_datasets()
    t2_chemical_space()
    t3_yeast9()
    t4_encoder_yeast9()


if __name__ == "__main__":
    main()
