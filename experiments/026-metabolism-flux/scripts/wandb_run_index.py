"""Index every W&B run of the 026 flux sweep, and emit the hyperlinked table for notes-tex.

Reads the four grid result files written by ``sweep_flux.py`` (``sweep_arms_a``,
``sweep_arms_b``, ``sweep_null``, ``sweep_reg_flux_anchored``), which are the files
``analyze_sweep.py`` scores. Writes ``results/wandb_run_index.json`` and the LaTeX table
``notes-tex/027-metabolic-flux-module/tables/wandb_runs_026.tex``: one row per grid cell,
with every seed's run id linked to its W&B page.

The 18 earlier ``flux_arms_gpu*.json`` runs predate W&B logging in ``train_flux.py`` and
have no run page, so they are not in the index.

Run from the repository root:

    python experiments/026-metabolism-flux/scripts/wandb_run_index.py
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from pydantic import BaseModel

REPO_ROOT = Path(__file__).resolve().parents[3]
RESULTS = REPO_ROOT / "experiments" / "026-metabolism-flux" / "results"
TABLE_OUT = (
    REPO_ROOT / "notes-tex" / "027-metabolic-flux-module" / "tables" / "wandb_runs_026.tex"
)
INDEX_OUT = RESULTS / "wandb_run_index.json"

GRID_FILES = {
    "arms": ["sweep_arms_a.json", "sweep_arms_b.json"],
    "null": ["sweep_null.json"],
    "reg": ["sweep_reg_flux_anchored.json"],
}
GRID_TITLE = {
    "arms": "five arms, ten seeds each",
    "null": "label-permutation null",
    "reg": "lr $\\times$ weight decay $\\times$ width, \\texttt{flux\\_anchored}",
}


class RunRecord(BaseModel):
    grid: str
    label: str
    arm: str
    seed: int
    wandb_run_id: str
    wandb_url: str
    peak_val_pearson: float


class RunIndex(BaseModel):
    project_url: str
    n_runs: int
    runs: list[RunRecord]


def tex_escape(s: str) -> str:
    return s.replace("_", "\\_")


def load_runs() -> list[RunRecord]:
    runs: list[RunRecord] = []
    for grid, files in GRID_FILES.items():
        for name in files:
            payload = json.loads((RESULTS / name).read_text())
            for run in payload["runs"]:
                runs.append(
                    RunRecord(
                        grid=grid,
                        label=run["cell"]["label"],
                        arm=run["arm"],
                        seed=int(run["seed"]),
                        wandb_run_id=run["wandb_run_id"],
                        wandb_url=run["wandb_url"],
                        peak_val_pearson=float(run["best"]["val_betaxanthin"]),
                    )
                )
    return runs


def project_url(runs: list[RunRecord]) -> str:
    urls = {r.wandb_url.rsplit("/runs/", 1)[0] for r in runs}
    if len(urls) != 1:
        raise ValueError(f"runs span more than one W&B project: {sorted(urls)}")
    return urls.pop()


def write_table(index: RunIndex) -> None:
    rows: dict[tuple[str, str], list[RunRecord]] = defaultdict(list)
    for r in index.runs:
        rows[(r.grid, r.label)].append(r)

    lines = [
        "%% GENERATED by experiments/026-metabolism-flux/scripts/wandb_run_index.py",
        "%% from results/sweep_*.json. Do not edit by hand; rerun the script.",
        "%% SOURCE: experiments/026-metabolism-flux/results/sweep_arms_a.json, sweep_arms_b.json,",
        "%% sweep_null.json, sweep_reg_flux_anchored.json (wandb_run_id, wandb_url per run).",
        "\\begin{table}[H]",
        "  \\centering",
        "  \\footnotesize",
        "  \\caption[W\\&B runs of the 026 sweep]{Every run of the 026 sweep behind"
        f" Table~\\ref{{tab:026}}, {index.n_runs} in all, in project"
        f" \\href{{{index.project_url}}}{{\\texttt{{{tex_escape(index.project_url.split('/')[-1])}}}}}"
        " (entity \\texttt{zhao-group}). One row per grid cell; each entry is a seed and"
        " its run id, linked to the run page. The 18 earlier runs in"
        " \\texttt{flux\\_arms\\_gpu*.json} predate W\\&B logging and have no page.}",
        "  \\label{tab:wandb-runs-026}",
        "  \\begin{tabular}{@{}llp{0.60\\textwidth}@{}}",
        "    \\hline",
        "    Grid & Cell & Seed: run \\\\",
        "    \\hline",
    ]
    for grid in GRID_FILES:
        cells = sorted(k for k in rows if k[0] == grid)
        for i, key in enumerate(cells):
            runs = sorted(rows[key], key=lambda r: r.seed)
            entries = " ".join(
                f"{r.seed}: \\href{{{r.wandb_url}}}{{\\texttt{{{r.wandb_run_id}}}}}" for r in runs
            )
            label = key[1]
            if label.startswith(f"{grid}-"):
                label = label[len(grid) + 1 :]
            if grid == "reg":
                # Every reg cell is flux_anchored (the caption says so); keep the row short.
                label = label.removeprefix("flux_anchored-")
            grid_cell = f"\\texttt{{{grid}}}" if i == 0 else ""
            lines.append(f"    {grid_cell} & \\texttt{{{tex_escape(label)}}} & {entries} \\\\")
        lines.append("    \\hline")
    lines += ["  \\end{tabular}", "\\end{table}", ""]
    TABLE_OUT.parent.mkdir(parents=True, exist_ok=True)
    TABLE_OUT.write_text("\n".join(lines))


def main() -> None:
    runs = load_runs()
    index = RunIndex(project_url=project_url(runs), n_runs=len(runs), runs=runs)
    INDEX_OUT.write_text(index.model_dump_json(indent=2))
    write_table(index)
    print(f"{index.n_runs} runs in {index.project_url}")
    print(f"wrote {INDEX_OUT}")
    print(f"wrote {TABLE_OUT}")


if __name__ == "__main__":
    main()
