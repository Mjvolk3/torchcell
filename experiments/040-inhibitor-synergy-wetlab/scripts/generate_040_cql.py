"""Generate the experiment 040 query: the four pooled screens and the private wells, KG 4.0.

Writes ``queries/env_chemgen_mixture_040.cql``, one ``UNION ALL`` block per dataset, in
the shape of the 033 query (``experiments/033-env-chemgen-pooled/queries/
001_env_chemgen_pooled.cql``): a dataset, every perturbed gene of the record in
``$gene_set``, the reference, the two ``serialized_data`` properties. No medium, dose or
compound filter; which records a training arm reads is a read-time selection
(``mixture_data.py``), as it was over the 033 cell table.

What changes against the 033 query, and why.

* The store is KG 4.0 (release ``2026.10.17-4295f7ca``, torchcell 1.8.3). Vanacloig 2022
  now serves its Table S1 IC30 doses (mM, uM, ug/mL, or the basis-free percent of #764),
  so the dev-store dose path of ``mixture_data.vanacloig_doses`` has no reason to exist
  and is gone.
* The private ``InhibitorBioscreenVolk2021Dataset`` (977 wells of the 2021 Bioscreen runs)
  is served in 4.0 and gets its own block. Its genotype is ``Genotype(perturbations=[])``
  (every well is the same strain), so the gene clause of the other blocks, which demands
  at least one perturbation, would drop every record; the block has no genotype clause.
  The trainer keeps reading the wells from ``results/wetlab_wells.csv``; the block is in
  the query so that the store holds every record the experiment stands on and the build
  can count them against the release.
* One ``{partition}`` marker per block (``PARTITION_MARKER`` of
  ``torchcell.data.neo4j_query_raw``) for the partitioned raw stage; a single session
  removes it.

Served counts per dataset are ``SERVED_COUNTS``, read from the release snapshot
``database/releases/2026.10.17-4295f7ca.json`` (``n_experiments``) and pinned here so the
build script can report returned against served without the snapshot on the machine.

Run from the repo root:
    python experiments/040-inhibitor-synergy-wetlab/scripts/generate_040_cql.py
"""

from __future__ import annotations

import os.path as osp
from typing import Literal

#: The release the query is written against and the counts it serves per dataset.
RELEASE = "2026.10.17-4295f7ca"
RELEASE_VERSION = "4.0"
RELEASE_TORCHCELL = "1.8.3"
SERVED_COUNTS: dict[str, int] = {
    "EnvChemgenVanacloig2022Dataset": 164_205,
    "EnvChemgenHoepfner2014Dataset": 3_127_814,
    "HetHillenmeyer2008Dataset": 2_963_683,
    "EnvChemgenWildenhain2015Dataset": 448_655,
    "InhibitorBioscreenVolk2021Dataset": 977,
}

GeneClause = Literal["all", "none"]

#: (dataset id, comment, gene clause); the order is the UNION order and the order of
#: ``mixture_data.SPECS`` plus the private wells last.
BLOCKS: list[tuple[str, str, GeneClause]] = [
    (
        "EnvChemgenVanacloig2022Dataset",
        "haploid, PDR1/PDR3/SNQ2 sensitized host, every compound at its Table S1 IC30, doses served",
        "all",
    ),
    (
        "EnvChemgenHoepfner2014Dataset",
        "both ploidy arms, every (compound, concentration) its own condition",
        "all",
    ),
    (
        "HetHillenmeyer2008Dataset",
        "heterozygous diploid, log2 fitness-defect ratio",
        "all",
    ),
    (
        "EnvChemgenWildenhain2015Dataset",
        "haploid deletions and conditional alleles, one screening concentration",
        "all",
    ),
    (
        "InhibitorBioscreenVolk2021Dataset",
        "PRIVATE, the 2021 Bioscreen wells, empty genotype, no gene clause",
        "none",
    ),
]

HEADER = f"""// experiments/040-inhibitor-synergy-wetlab/queries/env_chemgen_mixture_040.cql
// [[experiments.040-inhibitor-synergy-wetlab.queries.env_chemgen_mixture_040]]
//
// GENERATED by experiments/040-inhibitor-synergy-wetlab/scripts/generate_040_cql.py.
// Edit the generator, never this file.
//
// Every record of the four pooled chemogenomic screens the 040 mixture trainer reads
// (Vanacloig 2022, Hoepfner 2014, Hillenmeyer 2008 HET, Wildenhain 2015) plus the private
// 2021 Bioscreen wells, from KG 4.0 (release {RELEASE}, torchcell {RELEASE_TORCHCELL}).
//
// The query decides the record population and nothing else: a dataset, and every
// perturbed gene of the record in $gene_set. No medium, dose or compound filter; the
// trainer selects at read time. A Vanacloig genotype carries ONE perturbation in 4.0,
// the queried deletion; the sensitized host's PDR1, PDR3 and SNQ2 deletions sit on the
// reference strain (build 002 of 033 onward). The private wells carry an EMPTY genotype
// (one strain, BY4742-iAID6) and have no gene clause.
//
// Served counts, release {RELEASE}:
"""
HEADER += "".join(f"//   {name}: {n:,}\n" for name, n in SERVED_COUNTS.items())
HEADER += f"""//   total: {sum(SERVED_COUNTS.values()):,}
//
// The partition marker (PARTITION_MARKER of torchcell.data.neo4j_query_raw) after each
// dataset filter is where the partitioned raw stage (fetch_workers > 0) puts its e.id
// prefix filter; a single session removes it. The raw stage counts the marker per
// block, so this header must not spell it.
//
// Records are returned as the serialized_data properties, not as nodes: hydrated nodes
// are retained by the driver for the life of the result and project past machine
// memory at this scale (the 025 query's reason).
"""

GENE_CLAUSE_ALL = """MATCH (e)<-[:GenotypeMemberOf]-(g:Genotype)
MATCH (e)<-[:ExperimentReferenceOf]-(ref:ExperimentReference)
WHERE ALL(p IN [(g)<-[:PerturbationMemberOf]-(pert) | pert]
WHERE p.systematic_gene_name IN $gene_set)
 AND SIZE([(g)<-[:PerturbationMemberOf]-(pert) | pert]) > 0
"""
GENE_CLAUSE_NONE = """MATCH (e)<-[:ExperimentReferenceOf]-(ref:ExperimentReference)
"""


def block(dataset: str, comment: str, clause: GeneClause) -> str:
    """One UNION ALL block of the query."""
    clause_text = GENE_CLAUSE_ALL if clause == "all" else GENE_CLAUSE_NONE
    return (
        f"// {dataset} ({comment})\n"
        "MATCH (dataset:Dataset)<-[:ExperimentMemberOf]-(e:Experiment)\n"
        f"WHERE dataset.id = '{dataset}' {{partition}}\n"
        f"{clause_text}"
        "WITH DISTINCT e, ref\n"
        " ORDER BY e.id\n"
        "RETURN e.serialized_data AS e_serialized, "
        "ref.serialized_data AS ref_serialized\n"
    )


def count_query(dataset: str, clause: GeneClause) -> str:
    """The block's clause as one count: how many served records it admits.

    The build asserts the raw stage returned exactly this many, which is what proves the
    partitioned fetch lost nothing and that every record short of the served count was
    excluded by the clause (a perturbed gene outside ``$gene_set``), not by the build.
    """
    clause_text = GENE_CLAUSE_ALL if clause == "all" else GENE_CLAUSE_NONE
    return (
        "MATCH (dataset:Dataset)<-[:ExperimentMemberOf]-(e:Experiment)\n"
        f"WHERE dataset.id = '{dataset}'\n"
        f"{clause_text}"
        "RETURN count(DISTINCT e) AS n\n"
    )


def outside_gene_set_query(dataset: str) -> str:
    """Served records of ``dataset`` per perturbed gene outside ``$gene_set``."""
    return (
        "MATCH (dataset:Dataset)<-[:ExperimentMemberOf]-(e:Experiment)\n"
        f"WHERE dataset.id = '{dataset}'\n"
        "MATCH (e)<-[:GenotypeMemberOf]-(g:Genotype)<-[:PerturbationMemberOf]-(p)\n"
        "WHERE NOT p.systematic_gene_name IN $gene_set\n"
        "RETURN p.systematic_gene_name AS gene, count(DISTINCT e) AS n\n"
        " ORDER BY n DESC, gene\n"
    )


def empty_genotype_query(dataset: str) -> str:
    """Served records of ``dataset`` with a genotype of no perturbations.

    The screens' clause asks for at least one perturbation, so a released wild-type
    screen (Wildenhain's ``orf=NULL / wild type`` rows, the BY4741 background alone) is
    excluded by it; the private wells, all empty-genotype, have no such clause.
    """
    return (
        "MATCH (dataset:Dataset)<-[:ExperimentMemberOf]-(e:Experiment)\n"
        f"WHERE dataset.id = '{dataset}'\n"
        "MATCH (e)<-[:GenotypeMemberOf]-(g:Genotype)\n"
        "WHERE SIZE([(g)<-[:PerturbationMemberOf]-(p) | p]) = 0\n"
        "RETURN count(DISTINCT e) AS n\n"
    )


def query_text() -> str:
    """The whole query."""
    blocks = [block(*b) for b in BLOCKS]
    return HEADER + "\n" + "\nUNION ALL\n\n".join(blocks)


def query_path() -> str:
    """Where the query is written, beside this script's experiment folder."""
    here = osp.dirname(osp.abspath(__file__))
    return osp.abspath(osp.join(here, "..", "queries", "env_chemgen_mixture_040.cql"))


def main() -> None:
    """Write the query."""
    assert set(name for name, _, _ in BLOCKS) == set(SERVED_COUNTS)
    path = query_path()
    text = query_text()
    with open(path, "w") as f:
        f.write(text)
    print(f"wrote {path} ({text.count('UNION ALL') + 1} blocks)")


if __name__ == "__main__":
    main()
