def t13_profiles(prof: pd.DataFrame, matrix: dict) -> None:
    """One row per named comparison, keyed by the exact pair of profile columns.

    Keying on the compound alone is not enough: acetic acid appears in four
    comparisons (against the Hoepfner profile, against the sodium acetate
    prediction, against the build-001 profile) and they are different claims.
    """
    loco = prof[(prof["comparison"] == "loco_32") & (prof["target"] == "centered")]
    rows = [
        [
            "Leave-one-compound-out over 32 compounds, median",
            "32 compounds",
            f3(loco["spearman"].median()),
            f"[{f3(loco['spearman'].quantile(0.25))}, "
            f"{f3(loco['spearman'].quantile(0.75))}]",
            "",
            "",
        ]
    ]
    wanted = [
        (
            "furfural|predicted_loco",
            "furfural|measured_b002",
            "furfural, leave-one-out against build 002",
        ),
        (
            "5-(hydroxymethyl)furfural|predicted_loco",
            "5-(hydroxymethyl)furfural|measured_b002",
            "5-HMF, leave-one-out against build 002",
        ),
        (
            "acetic acid|predicted_all32",
            "sodium acetate|measured_hoepfner_hop",
            "acetic acid predicted against Hoepfner sodium acetate",
        ),
        (
            "acetic acid|predicted_all32",
            "sodium acetate|predicted_all32",
            "acetic acid prediction against sodium acetate prediction",
        ),
        (
            "levulinic acid|predicted_all32",
            "levulinic acid|measured_b001",
            "levulinic acid predicted against build 001",
        ),
        (
            "sodium acetate|measured_b001",
            "sodium acetate|measured_hoepfner_hop",
            "Vanacloig build 001 sodium acetate against Hoepfner sodium acetate",
        ),
        (
            "furfural|measured_b001",
            "furfural|measured_b002",
            "furfural, build 001 against build 002",
        ),
    ]
    for predicted, measured, label in wanted:
        sel = prof[(prof["predicted"] == predicted) & (prof["measured"] == measured)]
        cen = sel[sel["target"] == "centered"]
        raw = sel[sel["target"] == "raw"]
        if not len(cen):
            continue
        c = cen.iloc[0]
        rel = c["measured_reliability"]
        rows.append(
            [
                label,
                str(int(c["n_genes"])),
                f3(c["spearman"]),
                "",
                f3(raw.iloc[0]["spearman"]) if len(raw) else "",
                "" if pd.isna(rel) else f3(rel),
            ]
        )
    write_table(
        "t13-profiles.tex",
        tabular(
            "p{66mm}lrlrr",
            [
                ["Comparison", "Genes", "Centered", "IQR", "Raw", "Measured replicate"],
                [
                    "",
                    "(n)",
                    "Spearman",
                    "(Spearman)",
                    "Spearman",
                    "reliability (Spearman)",
                ],
            ],
            rows,
        ),
    )


