"""Measure whether the 027 grid's predictions carry any spread across genotypes.

Reads the per-cell test-prediction dumps that ``train_bx.py`` writes at the selected epoch
(``$DATA_ROOT/test-predictions-027/<arm>_s<seed>.json``, 905 records each: 629 pinned
Merzbacher test genes plus 276 further held-out genotypes), and for every cell computes the
standard deviation of the predictions against the standard deviation of the targets. A
model that has collapsed to a constant has a ratio near zero however its correlation
reads, because Pearson and Spearman are scale-free.

Writes ``results/prediction_collapse.json`` and the LaTeX table
``notes-tex/027-metabolic-flux-module/tables/prediction_collapse.tex``.

Run from the repository root:

    python experiments/027-betaxanthin-metabolic/scripts/audit_prediction_collapse.py
"""

from __future__ import annotations

import json
import os
from collections import defaultdict
from pathlib import Path

import numpy as np
from dotenv import load_dotenv
from pydantic import BaseModel

load_dotenv()

REPO_ROOT = Path(__file__).resolve().parents[3]
DUMPS = Path(os.environ["DATA_ROOT"]) / "test-predictions-027"
RESULTS = REPO_ROOT / "experiments" / "027-betaxanthin-metabolic" / "results"
INDEX_OUT = RESULTS / "prediction_collapse.json"
TABLE_OUT = (
    REPO_ROOT / "notes-tex" / "027-metabolic-flux-module" / "tables" / "prediction_collapse.tex"
)

ARM_ORDER = ["pooled", "flux_off", "flux_free", "flux_anchored", "null_pooled", "null_anchored"]


class CellSpread(BaseModel):
    arm: str
    seed: int
    n_records: int
    pred_sd: float
    target_sd: float
    sd_ratio: float
    pred_mean: float
    target_mean: float
    pred_range: float
    pearson_all: float


class ArmSpread(BaseModel):
    arm: str
    n_cells: int
    sd_ratio_max: float
    sd_ratio_median: float
    pred_mean_min: float
    pred_mean_max: float
    pred_range_max: float


class CollapseAudit(BaseModel):
    n_cells: int
    target_sd: float
    target_mean: float
    cells: list[CellSpread]
    arms: list[ArmSpread]


def tex_escape(s: str) -> str:
    return s.replace("_", "\\_")


def load_cells() -> list[CellSpread]:
    cells: list[CellSpread] = []
    for path in sorted(DUMPS.glob("*_s*.json")):
        payload = json.loads(path.read_text())
        recs = payload["predictions"]
        pred = np.array([r["pred"] for r in recs], dtype=float)
        target = np.array([r["target"] for r in recs], dtype=float)
        keep = np.isfinite(pred) & np.isfinite(target)
        pred, target = pred[keep], target[keep]
        cells.append(
            CellSpread(
                arm=payload["cell"]["arm"],
                seed=int(payload["cell"]["seed"]),
                n_records=int(keep.sum()),
                pred_sd=float(pred.std()),
                target_sd=float(target.std()),
                sd_ratio=float(pred.std() / target.std()),
                pred_mean=float(pred.mean()),
                target_mean=float(target.mean()),
                pred_range=float(np.ptp(pred)),
                pearson_all=float(np.corrcoef(pred, target)[0, 1]),
            )
        )
    if len(cells) != 144:
        raise ValueError(f"expected 144 cells, found {len(cells)} in {DUMPS}")
    return cells


def summarize(cells: list[CellSpread]) -> list[ArmSpread]:
    by_arm: dict[str, list[CellSpread]] = defaultdict(list)
    for c in cells:
        by_arm[c.arm].append(c)
    out = []
    for arm in ARM_ORDER:
        cs = by_arm[arm]
        ratios = np.array([c.sd_ratio for c in cs])
        out.append(
            ArmSpread(
                arm=arm,
                n_cells=len(cs),
                sd_ratio_max=float(ratios.max()),
                sd_ratio_median=float(np.median(ratios)),
                pred_mean_min=min(c.pred_mean for c in cs),
                pred_mean_max=max(c.pred_mean for c in cs),
                pred_range_max=max(c.pred_range for c in cs),
            )
        )
    return out


def write_table(audit: CollapseAudit) -> None:
    lines = [
        "%% GENERATED by experiments/027-betaxanthin-metabolic/scripts/audit_prediction_collapse.py",
        "%% from $DATA_ROOT/test-predictions-027/*.json. Do not edit by hand; rerun the script.",
        "%% SOURCE: experiments/027-betaxanthin-metabolic/results/prediction_collapse.json",
        "\\begin{table}[H]",
        "  \\centering",
        "  \\footnotesize",
        "  \\caption[Prediction spread at the selected epoch]{Spread of the predictions across"
        f" the {audit.cells[0].n_records} held-out genotypes at the selected epoch, per arm"
        f" over its {audit.arms[0].n_cells} seeds. The targets have standard deviation"
        f" {audit.target_sd:.3f} and mean {audit.target_mean:+.3f} in standardized units."
        " SD ratio is the prediction standard deviation over the target standard deviation;"
        " a value near zero is a constant predictor. Constant is the range, over seeds, of"
        " the value the model outputs for every genotype.}",
        "  \\label{tab:collapse}",
        "  \\begin{tabular}{@{}lrrrl@{}}",
        "    \\hline",
        "    Arm & Cells & SD ratio, max & SD ratio, median & Constant, over seeds \\\\",
        "    \\hline",
    ]
    for a in audit.arms:
        lines.append(
            f"    \\texttt{{{tex_escape(a.arm)}}} & {a.n_cells} & {a.sd_ratio_max:.1e} &"
            f" {a.sd_ratio_median:.1e} & ${a.pred_mean_min:+.2f}$ to ${a.pred_mean_max:+.2f}$ \\\\"
        )
    lines += ["    \\hline", "  \\end{tabular}", "\\end{table}", ""]
    TABLE_OUT.parent.mkdir(parents=True, exist_ok=True)
    TABLE_OUT.write_text("\n".join(lines).replace("e-0", "e-"))


def main() -> None:
    cells = load_cells()
    audit = CollapseAudit(
        n_cells=len(cells),
        target_sd=float(np.median([c.target_sd for c in cells])),
        target_mean=float(np.median([c.target_mean for c in cells])),
        cells=cells,
        arms=summarize(cells),
    )
    INDEX_OUT.write_text(audit.model_dump_json(indent=2))
    write_table(audit)
    print(f"{audit.n_cells} cells; target sd {audit.target_sd:.4f}")
    for a in audit.arms:
        print(
            f"{a.arm:15s} sd_ratio max {a.sd_ratio_max:.2e} median {a.sd_ratio_median:.2e}"
            f"  constant [{a.pred_mean_min:+.2f}, {a.pred_mean_max:+.2f}]"
        )
    print(f"wrote {INDEX_OUT}\nwrote {TABLE_OUT}")


if __name__ == "__main__":
    main()
