def esc(text: object) -> str:
    """LaTeX-escape a cell."""
    s = str(text)
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"), ("&", r"\&")):
        s = s.replace(a, b)
    return s


def tex_table(
    df: pd.DataFrame, align: str | None = None, raw_header: bool = False
) -> str:
    """A bare tabular, no caption: the document supplies the float and the caption.

    ``raw_header`` passes column names through unescaped so a header may carry math.
    """
    cols = align or ("l" + "r" * (len(df.columns) - 1))
    head_cells = [str(c) if raw_header else esc(c) for c in df.columns]
    head = " & ".join(rf"\textbf{{{c}}}" for c in head_cells) + r" \\"
    body = "\n".join(
        " & ".join(esc(v) for v in row) + r" \\" for row in df.itertuples(index=False)
    )
    return (
        f"\\begin{{tabular}}{{{cols}}}\n\\toprule\n{head}\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n"
    )


def write(name: str, text: str, source: str) -> None:
    """Write one tabular, naming the result file it came from so the gate can see it."""
    os.makedirs(TABLES, exist_ok=True)
    path = osp.join(TABLES, f"{name}.tex")
    with open(path, "w") as fh:
        fh.write(
            "%% GENERATED by experiments/031-env-chemgen-inhibitor-tolerance/scripts/"
            "notes_tex_representation_tables.py\n"
            f"%% SOURCE: experiments/031-env-chemgen-inhibitor-tolerance/results/{source}\n"
            "%% Do not edit by hand.\n" + text
        )
    print(f"  wrote {path}")


def t1_datasets() -> None:
    """The five datasets on the axes a shared representation has to absorb."""
    dose = pd.read_csv(osp.join(RESULTS, "dose_axis_summary.csv")).set_index("dataset")
    rows = []
    for name in ORDER:
        records = pd.read_parquet(
            osp.join(RESULTS, f"records_{name}.parquet"),
            columns=["gene", "ref_ploidy", "perturbation_type"],
        )
        d = dose.loc[name]
        rows.append(
            {
                "dataset": LABEL[name],
                "records": f"{len(records):,}",
                "genes": f"{records['gene'].nunique():,}",
                "compounds": f"{int(d['compounds']):,}",
                "ploidy": "|".join(sorted(set(records["ref_ploidy"].astype(str)))),
                "dose basis": d["dose_bases"].replace("|", ", ")
                if isinstance(d["dose_bases"], str)
                else "none",
                # the percent sign is escaped once, by esc(), not here
                "molar": f"{100 * float(d['frac_convertible_to_molar']):.0f}%",
            }
        )
    write(
        "t1-datasets",
        tex_table(pd.DataFrame(rows), align="lrrrllr"),
        "dose_axis_summary.csv and records_*.parquet",
    )


