def t10_embedding(results: str) -> None:
    embed = pd.read_csv(osp.join(results, "embedding_coverage_store.csv"))
    rows = []
    for encoder, g in embed.groupby("encoder", sort=True):
        pool = g[g["dataset"] == "All four"].iloc[0]
        row: dict[str, object] = {
            "encoder": encoder,
            "compounds": f"{n(pool['compounds_embedded'])} of {n(pool['compounds'])}",
            "cells without a vector": n(
                pool["cells"] - pool["cells_with_every_vector"]
            ),
        }
        for _, r in g[g["dataset"] != "All four"].iterrows():
            row[SHORT[r["dataset"]]] = pct(r["cells_with_every_vector"] / r["cells"], 2)
        rows.append(row)
    write(
        "t10-embedding",
        tex_table(
            pd.DataFrame(rows), left(3.0) + left(2.6) + right(1.8) + right(1.6) * 4
        ),
        "embedding_coverage_store.csv",
    )


