def amino_acid_concordance() -> str | None:
    """Mulleder 2016 against Cooper 2010, the matched pairs."""
    src = results("amino_acids", "amino_acid_dataset_concordance.json")
    if not osp.isfile(src):
        return None
    with open(src) as fh:
        d = json.load(fh)
    mul = d["mulleder_retest"]
    coo = {r["key"]: r for r in d["cooper_duplicate_retest"]}
    rows = []
    for s in d["matched"]:
        parts = s["mulleder"].split("+")
        mul_rt = sum(mul[p]["spearman_retest_log10"] for p in parts) / len(parts)
        coo_rt = coo[s["cooper_peak"]]["spearman"] if s["cooper_peak"] in coo else float("nan")
        rows.append(
            f"    {s['cooper_peak'].replace('_', ' ')} & {s['mulleder']} & {s['n']} & "
            f"${s['spearman']:+.3f}$ & ${s['pearson_log']:+.3f}$ & "
            f"{s['top5_overlap']} / {s['top5_expected']:.1f} & "
            f"{mul_rt:.2f} & {coo_rt:.2f} \\\\"
        )
    body = (
        "\\begin{table}[H]\n  \\centering\n  \\footnotesize\n"
        "  \\caption[M\\\"ulleder 2016 against Cooper 2010]{The two deletion-collection "
        "amino-acid screens on their "
        f"{d['n_shared_strains']:,} shared strains, matched on the collection's ORF name. "
        "Cooper's CE-LIF peaks (a linear ratio to the plate mean; composite peaks list "
        "their components) against M\\\"ulleder's LC-MS concentrations (mM): the "
        "Spearman over strains both measured, the Pearson of the two log-scaled "
        "quantities, the overlap of the top 5 percent of strains against the count "
        "expected by chance, and the two within-study replicate references, M\\\"ulleder's "
        "(194 strains measured twice, Spearman on log10) and Cooper's duplicated genes "
        "(two deletion strains of one gene in the released table). "
        "Written by \\texttt{target\\_notes\\_tex\\_tables.py} from "
        "\\texttt{results/amino\\_acid\\_dataset\\_concordance.json}.}\n"
        "  \\label{tab:amino-acid-concordance}\n"
        "  \\begin{tabular}{@{}llrrrrrr@{}}\n    \\hline\n"
        "    Cooper peak & M\\\"ulleder & strains & Spearman & log Pearson & top 5\\% & "
        "M\\\"ulleder replicate & Cooper replicate \\\\\n    \\hline\n"
        + "\n".join(rows)
        + "\n    \\hline\n  \\end{tabular}\n\\end{table}\n"
    )
    return write("amino_acids", "amino_acid_concordance", body, "results/amino_acid_dataset_concordance.json")


def mulleder_retest() -> str | None:
    """Mulleder 2016's 194 strains measured twice, per amino acid, and the ceiling it sets
    on a model: the square root of the between-strain share of a measurement's variance."""
    src = osp.join(
        EXPERIMENT_ROOT, "027-betaxanthin-metabolic", "results", "mulleder_retest_reliability.json"
    )
    if not osp.isfile(src):
        return None
    with open(src) as fh:
        d = json.load(fh)
    rows = []
    for r in d["per_amino_acid"]:
        rows.append(
            f"    {r['amino_acid']} & {r['n_pairs']} & {r['pearson_retest_log10']:.2f} & "
            f"{r['spearman_retest_log10']:.2f} & {r['qc_sd_log10']:.2f} & "
            f"{r['sd_single_measurement_log10']:.2f} & {r['sd_across_strains_log10']:.2f} & "
            f"{r['reliability_estimate']:.2f} & {r['pearson_ceiling']:.2f} \\\\"
        )
    rows.append("    \\hline")
    rows.append(
        f"    mean & & {d['mean_pearson_retest']:.2f} & {d['mean_spearman_retest']:.2f} & & & & "
        f"{d['mean_reliability']:.2f} & {d['mean_pearson_ceiling']:.2f} \\\\"
    )
    body = (
        "\\begin{table}[H]\n  \\centering\n  \\footnotesize\n"
        "  \\caption[M\\\"ulleder 2016 retest and the model ceiling]{M\\\"ulleder 2016's "
        f"retest, the {d['n_orfs_measured_twice']} strains measured twice, per amino acid. "
        "Pearson and Spearman between the two $\\log_{10}$ measurements; the "
        f"quality-control sample's sd over its {d['n_qc_injections']} injections (the "
        "instrument); the single-measurement sd from the pairs and the sd across strains "
        "(both $\\log_{10}$); the reliability, the between-strain share of a measurement's "
        "variance; and its square root, the Pearson a perfect model of the true value "
        "would reach against one measurement. The retest correlation bounds a second "
        "screen; the square root of the reliability bounds a model. Written by "
        "\\texttt{target\\_notes\\_tex\\_tables.py} from the 027 read "
        "\\texttt{results/mulleder\\_retest\\_reliability.json}.}\n"
        "  \\label{tab:mulleder-retest}\n"
        "  \\begin{tabular}{@{}lrrrrrrrr@{}}\n    \\hline\n"
        "    amino acid & pairs & Pearson & Spearman & QC sd & single sd & across sd & "
        "reliability & ceiling \\\\\n    \\hline\n"
        + "\n".join(rows)
        + "\n    \\hline\n  \\end{tabular}\n\\end{table}\n"
    )
    return write(
        "amino_acids", "mulleder_retest", body,
        "experiments/027-betaxanthin-metabolic/results/mulleder_retest_reliability.json",
    )


def betaxanthin_amino_acid_correlation() -> str | None:
    """Cachera's betaxanthin score against each amino-acid quantity of the two screens,
    and the pool ridge, from betaxanthin_amino_acid_correlation.py.
    """
    src = results("amino_acids", "betaxanthin_amino_acid_correlation.json")
    if not osp.isfile(src):
        return None
    with open(src) as fh:
        d = json.load(fh)
    screen_label = {"mulleder2016": "M\\\"ulleder 2016 (mM)", "cooper2010": "Cooper 2010 (ratio)"}
    tables = []
    for screen in ("mulleder2016", "cooper2010"):
        rows = []
        for s in d["features"]:
            if s["screen"] != screen:
                continue
            ceiling = "" if s["ceiling"] is None else f"{s['ceiling']:.2f}"
            rows.append(
                f"    {s['key'].replace('_', ' ')} & {s['n']:,} & ${s['spearman']:+.3f}$ & "
                f"$[{s['ci_low']:+.3f}, {s['ci_high']:+.3f}]$ & "
                f"{s['top5_overlap']} / {s['top5_expected']:.1f} & {ceiling} \\\\"
            )
        inputs_label = {"pool": "ridge, pool", "go": "ridge, GO", "go+pool": "ridge, GO with pool"}
        for p in (x for x in d["pool"] if x["screen"] == screen):
            perm = p["permuted_spearman_oof"]
            rows.append(
                f"    {inputs_label[p['inputs']]} ({p['n_features']:,}) & "
                f"{p['n']:,} & ${p['spearman_oof']:+.3f}$ & "
                f"$[{min(p['spearman_by_fold']):+.3f}, {max(p['spearman_by_fold']):+.3f}]$ & "
                f"${np.mean(perm):+.3f}$ ({np.std(perm):.3f}) & \\\\"
            )
        if screen == "mulleder2016":
            caption = (
                "  \\caption[Betaxanthin against the amino-acid pool]{Cachera 2023's "
                "betaxanthin score (corrected 24 h colony fluorescence, population-centered) "
                "against each of M\\\"ulleder 2016's amino-acid concentrations, over the "
                "strains both screens hold, matched on the systematic ORF: the Spearman with "
                "a strain-bootstrap 95 percent interval (1,000 draws), the overlap of the top "
                "5 percent of strains on the two axes against the count expected by chance, "
                "and the ceiling a correlation could reach through both endpoints' noise, the "
                "geometric mean of the betaxanthin reliability "
                f"({d['betaxanthin_reliability']:.2f}, the 027 variance-components read) and "
                "the amino acid's log10 retest Spearman over 194 strains. The ridge rows "
                "predict the betaxanthin score over five strain folds, the alpha chosen on an "
                "inner split, scored out of fold, with the same fit against a shuffled target: "
                "from the standardized log profile (the pool), from the deleted gene's "
                "propagated GO multi-hot (a zero row outside the store), and from both, the "
                "GO block scaled to the pool block's total variance; for these rows the "
                "interval column holds the lowest and highest fold and the top-5 column the "
                "shuffled-target fit's mean (sd), with the column count in parentheses. "
                "Written by "
                "\\texttt{target\\_notes\\_tex\\_tables.py} from "
                "\\texttt{results/betaxanthin\\_amino\\_acid\\_correlation.json} "
                "(\\texttt{betaxanthin\\_amino\\_acid\\_correlation.py}).}\n"
                "  \\label{tab:betaxanthin-amino-acid-correlation}\n"
            )
        else:
            caption = (
                "  \\caption[Betaxanthin against the Cooper peaks]{"
                "Table~\\ref{tab:betaxanthin-amino-acid-correlation} for Cooper 2010's "
                "peaks (a linear ratio to the plate mean), the ceiling from the peak's "
                "duplicate-strain Spearman, blank where no duplicate pairs were measured.}\n"
                "  \\label{tab:betaxanthin-amino-acid-correlation-cooper}\n"
            )
        tables.append(
            "\\begin{table}[H]\n  \\centering\n  \\footnotesize\n" + caption
            + "  \\begin{tabular}{@{}lrrlrr@{}}\n    \\hline\n"
            "    " + screen_label[screen] + " & strains & Spearman & 95\\% interval & "
            "top 5\\% & ceiling \\\\\n    \\hline\n"
            + "\n".join(rows)
            + "\n    \\hline\n  \\end{tabular}\n\\end{table}\n\n"
        )
    body = "".join(tables)
    return write(
        "amino_acids", "betaxanthin_amino_acid_correlation", body,
        "results/betaxanthin_amino_acid_correlation.json",
    )


