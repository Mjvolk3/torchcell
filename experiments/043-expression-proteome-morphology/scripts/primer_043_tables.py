def _short(name: str, temperature: float | None) -> str:
    base = name.split(" (")[0].split(",")[0].strip()
    return (
        f"{base}, {temperature:g} C"
        if temperature is not None
        else f"{base}, temperature a typed gap"
    )


def media_names(data_root: str) -> dict[str, str]:
    """Distinct media of each dataset, from up to 3,000 dev-LMDB records each."""
    out = {}
    for cls, d in DEV_DIRS.items():
        seen: dict[str, None] = {}
        path = osp.join(data_root, "data/torchcell", d, "processed/lmdb")
        for record in islice(_iter_dev(path), 3000):
            env = record["experiment"]["environment"]
            t = env.get("temperature")
            seen.setdefault(
                _short(env["media"]["name"], t["value"] if t else None), None
            )
        out[cls] = "; ".join(seen)
    return out


def _load(path: str) -> tuple[dict[str, Any], str]:
    with open(path, "rb") as f:
        raw = f.read()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def _n(x: float | int) -> str:
    return f"{int(round(x)):,}".replace(",", "{,}")


def _f(x: float, d: int = 2) -> str:
    return f"{x:.{d}f}".replace("-", "$-$")


def _tex(cell: str) -> str:
    """Escape a bare percent sign and write a pair's x as a times sign."""
    cell = re.sub(r"(?<!\\)%", r"\\%", cell)
    return cell.replace(" x ", " $\\times$ ")


def _tab(spec: str, header: list[str], rows: list[list[str]]) -> str:
    out = [
        HEADER,
        f"\\begin{{tabular}}{{{spec}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
    ]
    out += [" & ".join(_tex(c) for c in r) + " \\\\" for r in rows]
    out += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(out)


