def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", default=RESULTS_DIR)
    args = parser.parse_args()
    with open(osp.join(args.results, "store_against_plan_provenance.json")) as fh:
        print(json.dumps(json.load(fh), indent=2))
    for table in (
        t0_scorecard,
        t1_axes,
        t2_genotype_dose,
        t3_physical,
        t4_units,
        t5_label_policy,
        t6_reliability,
        t7_target,
        t8_ploidy,
        t9_folds,
        t10_embedding,
        t11_cross,
        t12_vocabulary,
    ):
        table(args.results)


if __name__ == "__main__":
    main()
