# Raw mirror (the loader reads the mirror, never the live Zenodo URL)
# --------------------------------------------------------------------------- #
def _data_root() -> str:
    """``DATA_ROOT`` from the environment (the mirror + build tree live under it)."""
    return os.environ["DATA_ROOT"]


def raw_mirror_dir(data_root: str | None = None) -> Path:
    """``$DATA_ROOT/torchcell-raw/lamoureuxMultiscaleExpressionRegulation2023``."""
    return Path(data_root or _data_root()) / RAW_DIR_REL


def _sha256(path: str | Path) -> str:
    """Streaming sha256 of a file."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def retrieval_record(
    raw: RawFile, retrieved_at: str = DATA_RETRIEVED_AT
) -> RetrievalRecord:
    """The versioned retrieval of one member: ``zip_member`` over the Zenodo archive."""
    return RetrievalRecord(
        method=RetrievalMethod.zenodo,
        source_url=ARCHIVE_URL,
        retriever="torchcell.literature.retrieve.zip_member",
        params={
            "url": ARCHIVE_URL,
            "member": raw.member,
            "container_sha256": ARCHIVE_SHA256,
        },
        sha256=raw.sha256,
        retrieved_at=retrieved_at,
    )


def deposit_raw_mirror(
    *,
    archive_path: str | Path,
    retrieved_at: str = DATA_RETRIEVED_AT,
    data_root: str | None = None,
) -> Path:
    """Write the four consumed members of an already-retrieved archive + ``manifest.json``.

    The archive must carry ``ARCHIVE_SHA256`` and each member its pinned sha256.
    Idempotent by sha256: an existing mirror file with the recorded hash is left alone
    and a differing one raises rather than being overwritten. The recorded retrieval
    (``zip_member`` with the archive hash) re-runs as-is.
    """
    got = _sha256(archive_path)
    if got != ARCHIVE_SHA256:
        raise RuntimeError(
            f"{archive_path} sha256 mismatch: got {got}, expected {ARCHIVE_SHA256}"
        )
    root = raw_mirror_dir(data_root)
    files: list[ArtifactRecord] = []
    with zipfile.ZipFile(archive_path) as archive:
        for raw in RAW_FILES:
            data = archive.read(raw.member)
            member_sha = hashlib.sha256(data).hexdigest()
            if member_sha != raw.sha256:
                raise RuntimeError(
                    f"{raw.member} sha256 mismatch: got {member_sha}, expected "
                    f"{raw.sha256}"
                )
            dest = root / raw.relpath
            dest.parent.mkdir(parents=True, exist_ok=True)
            if dest.exists():
                if _sha256(dest) != raw.sha256:
                    raise RuntimeError(
                        f"{dest} exists with a different sha256; refusing"
                    )
            else:
                tmp = dest.with_suffix(dest.suffix + ".partial")
                tmp.write_bytes(data)
                shutil.move(str(tmp), str(dest))
            files.append(
                ArtifactRecord(
                    path=raw.relpath,
                    role=ROLE_RAW_DATA,
                    bytes=dest.stat().st_size,
                    sha256=raw.sha256,
                    source=f"{ARCHIVE_URL}#{raw.member}",
                    retrieval=retrieval_record(raw, retrieved_at),
                )
            )
    manifest = Manifest(
        citation_key=CITATION_KEY,
        doi=PAPER_DOI,
        title=PAPER_TITLE,
        files=files,
        si_data_sources=[
            f"https://doi.org/{ZENODO_DOI}",
            ZENODO_RECORD_URL,
            GITHUB_RELEASE_URL,
            ARCHIVE_URL,
        ],
        si_expected=[
            "Zenodo 10.5281/zenodo.8284223 (SBRG/precise1k v1.0): the four consumed "
            "members of data/precise1k/ are mirrored; the rest of the archive (iModulon "
            "matrices, Public K-12 data, notebooks) is not consumed and not mirrored"
        ],
        provenance_complete=True,
        created_at=datetime.now(UTC).isoformat(),
    )
    (root / "manifest.json").write_text(manifest.model_dump_json(indent=2))
    return root


def load_manifest(data_root: str | None = None) -> Manifest:
    """Read the raw mirror's ``manifest.json``."""
    path = raw_mirror_dir(data_root) / "manifest.json"
    return Manifest.model_validate_json(path.read_text())


def manifest_sha256(manifest: Manifest, relpath: str) -> str:
    """The recorded sha256 of one mirror file."""
    for record in manifest.files:
        if record.path == relpath:
            return record.sha256
    raise KeyError(f"{relpath} is not in the raw-mirror manifest")


