def t2_method_landscape() -> str:
    out = [
        "## Table 2. Published single-cell RNA-seq runs, yeast and microbial",
        "",
        "| Study | Platform | Isolation | Cells | mRNA UMIs/cell | Genes/cell | Perturbation readout |",
        "| --- | --- | --- | ---: | ---: | ---: | :---: |",
    ]
    for m in MD.METHODS:
        umi = "--"
        if m.mrna_umis_per_cell is not None:
            umi = f"{m.mrna_umis_per_cell:,.0f}"
            if m.mrna_umis_low and m.mrna_umis_high:
                umi = f"{m.mrna_umis_low:,.0f}--{m.mrna_umis_high:,.0f}"
        gene = "--"
        if m.genes_per_cell is not None:
            gene = f"{m.genes_per_cell:,.0f}"
            if m.genes_low and m.genes_high:
                gene = f"{m.genes_low:,.0f}--{m.genes_high:,.0f}"
        out.append(
            f"| {m.label} | {m.platform} | {m.isolation.replace('_','-')} | "
            f"{m.cells_profiled:,} | {umi} | {gene} | "
            f"{'yes' if m.has_perturbation_readout else '--'} |"
        )
    out.append("")
    return "\n".join(out)


def t3_cost_per_cell() -> str:
    df = library_prep_table()
    out = [
        "## Table 3. Cost per cell, library preparation only",
        "",
        "**Quoted** = the source states a per-cell rate. **Derived** = a total "
        "divided by a cell count the same source supplies.",
        "",
        "| Method | Organism | Isolation | $ / cell | Basis | Source |",
        "| --- | --- | --- | ---: | --- | --- |",
    ]
    for _, r in df.iterrows():
        u = r["usd_per_cell"]
        s = f"${u:,.2f}" if u >= 1 else (f"${u:.4f}" if u >= 0.01 else f"${u:.5f}")
        out.append(
            f"| {r['method']} | *{r['organism']}* | {r['isolation']} | {s} | "
            f"{r['sourced_or_derived']} | {r['citation']} |"
        )
    out += [
        "",
        f"> Spread, cheapest to dearest: **~{CD.PER_CELL_SPREAD:,.0f}x**. Every "
        "row excludes sequencing -- see Table 4.",
        "",
    ]
    return "\n".join(out)


