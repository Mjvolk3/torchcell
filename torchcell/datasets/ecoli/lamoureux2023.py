def _paper(
    value: Any, quote: str, *, page: str, note: str | None = None
) -> SourcedValue:
    """Bind a value to a verbatim quote in the sha256-pinned paper OCR mirror."""
    return SourcedValue(
        value=value,
        quote=quote,
        note=note,
        provenance=Provenance(
            source_uri=PAPER_MD,
            citation_key=CITATION_KEY,
            sha256=PAPER_MD_SHA256,
            method="MinerU OCR of the publisher PDF (torchcell-library mirror)",
            page=page,
        ),
    )


def _si(value: Any, quote: str, *, page: str) -> SourcedValue:
    """Bind a value to a verbatim quote in the sha256-pinned SI OCR mirror."""
    return SourcedValue(
        value=value,
        quote=quote,
        provenance=Provenance(
            source_uri=SI_MD,
            citation_key=CITATION_KEY,
            sha256=SI_MD_SHA256,
            method="MinerU OCR of the supplementary PDF (torchcell-library mirror)",
            page=page,
        ),
    )


def metadata_provenance(column: str) -> Provenance:
    """A column of the release's sample metadata table, in the raw mirror."""
    return Provenance(
        source_uri=METADATA.relpath,
        citation_key=CITATION_KEY,
        sha256=METADATA.sha256,
        method=f"cell of the release's sample metadata (raw mirror {RAW_DIR_REL})",
        page=f"column {column!r}",
    )


def _metadata_cell(value: Any, cell: str, column: str) -> SourcedValue:
    """Bind a value to a verbatim cell of one metadata column."""
    return SourcedValue(value=value, quote=cell, provenance=metadata_provenance(column))


