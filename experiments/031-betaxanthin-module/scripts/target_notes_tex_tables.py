def results(target: str, name: str) -> str:
    return osp.join(EXPERIMENT_ROOT, STUDY[target]["dir"], "results", name)


def write(target: str, name: str, body: str, source: str) -> str:
    tables = osp.join(NOTES_TEX, STUDY[target]["dir"], "tables")
    os.makedirs(tables, exist_ok=True)
    path = osp.join(tables, f"{name}.tex")
    with open(path, "w") as fh:
        fh.write(
            f"%% notes-tex/{STUDY[target]['dir']}/tables/{name}.tex\n"
            f"%% GENERATED by {SCRIPT}\n"
            f"%% SOURCE: {source}\n" + fit_columns(body)
        )
    return path


def target_transfer(target: str) -> str | None:
    """The transformer rounds on one target, arm against control, paired by seed."""
    src = results(target, "transfer_readout.json")
    if not osp.isfile(src):
        return None
    with open(src) as fh:
        report = json.load(fh)
    rows = []
    for p in report["pairs"]:
        a, c = p["arm"], p["control"]
        enrich = (
            f"{a['mean_top50_enrichment']:.2f} / {c['mean_top50_enrichment']:.2f}"
            if a.get("mean_top50_enrichment") is not None
            and c.get("mean_top50_enrichment") is not None
            else "--"
        )
        name = p["name"].split(": ", 1)[1] if ": " in p["name"] else p["name"]
        rows.append(
            f"    {name} & {p['n']} & {a['mean_spearman']:.4f} ({a['sd_spearman']:.4f}) & "
            f"{c['mean_spearman']:.4f} ({c['sd_spearman']:.4f}) & "
            f"${p['mean_difference']:+.4f}$ ({p['sd_difference']:.4f}) & "
            f"{p['n_positive']}/{p['n']} & {enrich} \\\\"
        )
    comp_rows = []
    for head, items in report["comparators"].items():
        comp_rows.append(f"    \\multicolumn{{2}}{{@{{}}l}}{{\\textit{{{head}}}}} \\\\")
        comp_rows.extend(f"    {name} & {value:.4f} \\\\" for name, value in items.items())
    label = STUDY[target]["label"]
    statistic = (
        "the pinned-test Spearman at the epoch selected on validation Pearson (centered "
        "five-epoch moving average)"
        if target == "betaxanthin"
        else "the mean per-amino-acid pinned-test Spearman over the 19 columns at the "
        "epoch selected on validation Pearson (centered five-epoch moving average)"
    )
    top50 = (
        ", and the top-50 enrichment of high producers (arm / control)"
        if target == "betaxanthin"
        else ""
    )
    # The pairs fill more than a page once the rounds pass twenty, so they are split
    # into tables of at most PAIRS_PER_TABLE rows, the first carrying the label the
    # prose refers to and the rest continuing it.
    header = (
        "  \\begin{tabular}{@{}p{58mm}rrrrrr@{}}\n    \\hline\n"
        "    arm against control & seeds & arm (sd) & control (sd) & difference (sd) & "
        "higher & top-50 \\\\\n    \\hline\n"
    )
    chunks = [rows[i : i + PAIRS_PER_TABLE] for i in range(0, len(rows), PAIRS_PER_TABLE)]
    pair_tables = []
    for k, chunk in enumerate(chunks):
        if k == 0:
            caption = (
                f"  \\caption[The rounds on {label}: arm against control]{{Every arm paired by "
                "seed against its control on the same split (Merzbacher's 639 genes pinned to "
                f"test, the 027 protocol). The statistic is {statistic}. Columns: seeds paired, "
                "the arm and control means with their standard deviations over seeds, the mean "
                "paired difference with its standard deviation, the seeds on which the arm scored "
                f"higher{top50}. Written by \\texttt{{target\\_notes\\_tex\\_tables.py}} from "
                "\\texttt{results/transfer\\_readout.json} "
                "(\\texttt{target\\_transfer\\_readout.py}).}\n"
                "  \\label{tab:target-transfer}\n"
            )
        else:
            caption = (
                f"  \\caption[The rounds on {label}: arm against control, continued]{{"
                f"Table~\\ref{{tab:target-transfer}}, continued (part {k + 1} of {len(chunks)}).}}\n"
                f"  \\label{{tab:target-transfer-{k + 1}}}\n"
            )
        pair_tables.append(
            "\\begin{table}[H]\n  \\centering\n  \\footnotesize\n" + caption + header
            + "\n".join(chunk) + "\n    \\hline\n  \\end{tabular}\n\\end{table}\n\n"
        )
    body = (
        "".join(pair_tables)
        + "\\begin{table}[H]\n  \\centering\n  \\footnotesize\n"
        "  \\caption[The 027 comparators]{The pinned-test Spearman of the 027 rounds "
        "on the same split and statistic, read by "
        "\\texttt{target\\_transfer\\_readout.py} from 027's result files: the mean over "
        "three seeds for a trained arm, the validation-selected cell for the linear "
        "ladder, and the Merzbacher comparison's RandomForest.}\n"
        "  \\label{tab:target-transfer-comparators}\n"
        "  \\begin{tabular}{@{}p{90mm}r@{}}\n    \\hline\n"
        "    comparator & Spearman \\\\\n    \\hline\n"
        + "\n".join(comp_rows)
        + "\n    \\hline\n  \\end{tabular}\n\\end{table}\n"
    )
    return write(target, "target_transfer", body, "results/transfer_readout.json")


