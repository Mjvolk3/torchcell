class EnvironmentRule(StrEnum):
    """Why a genotype-kept sample's environment could not be written."""

    medium_not_in_library = "medium_not_in_library"
    culture_not_batch = "culture_not_batch"
    oxygen_regime_not_stated = "oxygen_regime_not_stated"
    supplement_label_ambiguous = "supplement_label_ambiguous"


ENVIRONMENT_RULE_REASONS: dict[EnvironmentRule, str] = {
    EnvironmentRule.medium_not_in_library: (
        "the 'Base Media' label has no MEDIA_LIBRARY key and neither the paper nor the "
        "release states its recipe, so the medium would be free text that joins nothing"
    ),
    EnvironmentRule.culture_not_batch: (
        "a chemostat or fed-batch culture: Environment has no culture-type slot (the "
        "CultureEnvironment fields do not survive the bacterial experiment's "
        "Environment-typed slot), so the record would merge with batch records of the "
        "same medium"
    ),
    EnvironmentRule.oxygen_regime_not_stated: (
        "the 'Electron Acceptor' cell is blank and the condition does not say "
        "anaerobic, so Environment.aerobicity (which cannot be a typed gap) would be a "
        "guess"
    ),
    EnvironmentRule.supplement_label_ambiguous: (
        "the supplement label 'Acetoacetate/LiCl(10mM)' names two compounds and one "
        "dose, so neither compound's dose is stated"
    ),
}

#: ``Base Media`` label -> (the MEDIA_LIBRARY key it derives from, is_synthetic).
LIBRARY_BASES: dict[str, tuple[str, bool]] = {"M9": ("M9", True), "LB": ("LB", False)}
BATCH = "Batch"
AEROBIC_ACCEPTOR = "O2"
ANAEROBIC_CONDITION_TOKEN = "anaero"

#: Chemical formulas the metadata writes, as the name the compound table resolves. A
#: formula names exactly one compound, so this is a spelling, not an interpretation;
#: abbreviations (PQ, DPD) and unstereo amino-acid names are left as written.
FORMULA_NAMES: dict[str, str] = {
    "NH4Cl": "ammonium chloride",
    "KNO3": "potassium nitrate",
    "FeCl2": "iron(II) chloride",
    "FeCl3": "iron(III) chloride",
    "HCl": "hydrochloric acid",
}

_AMOUNT_CELL = re.compile(r"^(?P<name>[^()]+?)\s*(?:\((?P<amount>[^()]*)\))?$")
_AMOUNT = re.compile(r"^(?P<value>\d*\.?\d+)\s*(?P<unit>[A-Za-z%/]+)?$")

#: Unit token -> (typed unit, factor to that unit). mg/mL and mg/L are restated in ug/mL
#: (x1000 and x1), the enum's mass-per-volume unit, in decimal arithmetic so the restated
#: number is exact. A bare "%" is recorded as w/v, the media library's convention.
UNIT_TOKENS: dict[str, tuple[ConcentrationUnit, float]] = {
    "uM": (ConcentrationUnit.micromolar, 1),
    "mM": (ConcentrationUnit.millimolar, 1),
    "M": (ConcentrationUnit.molar, 1),
    "ug/mL": (ConcentrationUnit.ug_per_ml, 1),
    "mg/mL": (ConcentrationUnit.ug_per_ml, 1000),
    "mg/L": (ConcentrationUnit.ug_per_ml, 1),
    "%w/v": (ConcentrationUnit.percent_w_v, 1),
    "%": (ConcentrationUnit.percent_w_v, 1),
}


class Amount(BaseModel):
    """One compound named in a metadata cell, with its dose as stated."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    label: str
    name: str
    value: float | None = None
    unit: ConcentrationUnit | None = None
    unitless_value: str | None = None


def parse_amount(
    cell: str,
    *,
    default_unit: ConcentrationUnit | None,
    extra_units: Mapping[str, tuple[ConcentrationUnit, float]] | None = None,
) -> Amount:
    """Parse ``name(amount)`` (or a bare ``name``) from one metadata cell part.

    ``default_unit`` is the column's unit (``g/L`` for the carbon and nitrogen columns,
    whose headers say so); a number with no unit in a column without one is kept as
    ``unitless_value`` and never given a unit. ``extra_units`` adds unit tokens for a
    sibling release arm whose cells use spellings PRECISE-1K's own cells never do
    (measured: no PRECISE-1K cell of a parsed column carries one), each as
    ``(typed unit, factor to that unit)``.
    """
    units = {**UNIT_TOKENS, **(extra_units or {})}
    match = _AMOUNT_CELL.match(cell.strip())
    if match is None:
        raise ValueError(f"unparseable amount cell {cell!r}")
    label = match.group("name").strip()
    name = FORMULA_NAMES.get(label, label)
    amount = match.group("amount")
    if amount is None or not amount.strip():
        return Amount(label=cell.strip(), name=name)
    quantity = _AMOUNT.match(amount.strip().replace(" ", ""))
    if quantity is None:
        raise ValueError(f"unparseable amount {amount!r} in {cell!r}")
    number = Decimal(quantity.group("value"))
    token = quantity.group("unit")
    if token is None:
        if default_unit is None:
            return Amount(label=cell.strip(), name=name, unitless_value=amount.strip())
        return Amount(
            label=cell.strip(), name=name, value=float(number), unit=default_unit
        )
    if token not in units:
        raise ValueError(f"unknown unit {token!r} in {cell!r}")
    unit, factor = units[token]
    return Amount(
        label=cell.strip(),
        name=name,
        value=float(number * Decimal(str(factor))),
        unit=unit,
    )


def parse_supplements(cell: str) -> tuple[Amount, ...]:
    """Every compound of a ``Supplement`` cell; ``a + b`` names two."""
    if not cell:
        return ()
    return tuple(parse_amount(part, default_unit=None) for part in cell.split(" + "))


class ConditionSpec(BaseModel):
    """The environment-defining cells of one sample, parsed."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    base_media: str
    temperature_c: float
    ph: float
    carbon: Amount | None
    nitrogen: Amount | None
    aerobicity: Literal["aerobic", "anaerobic"]
    electron_acceptor: Amount | None
    trace: str | None
    supplements: tuple[Amount, ...]
    antibiotic: Amount | None


class EnvironmentVerdict(BaseModel):
    """A parsed condition, or the rule that dropped the sample."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    rule: EnvironmentRule | None = None
    spec: ConditionSpec | None = None


def settle_environment(row: Mapping[str, str]) -> EnvironmentVerdict:
    """Parse one metadata row's environment, or name the rule that drops it."""
    media = row[COL_MEDIA]
    if media not in LIBRARY_BASES:
        return EnvironmentVerdict(rule=EnvironmentRule.medium_not_in_library)
    if row[COL_CULTURE] != BATCH:
        return EnvironmentVerdict(rule=EnvironmentRule.culture_not_batch)
    acceptor = row[COL_ACCEPTOR]
    if acceptor == AEROBIC_ACCEPTOR:
        aerobicity: Literal["aerobic", "anaerobic"] = "aerobic"
        electron_acceptor = None
    elif ANAEROBIC_CONDITION_TOKEN in row[COL_CONDITION]:
        aerobicity = "anaerobic"
        electron_acceptor = (
            parse_amount(acceptor, default_unit=None) if acceptor else None
        )
    else:
        return EnvironmentVerdict(rule=EnvironmentRule.oxygen_regime_not_stated)
    supplement = row[COL_SUPPLEMENT]
    supplements = parse_supplements(supplement)
    if any("/" in amount.name for amount in supplements):
        return EnvironmentVerdict(rule=EnvironmentRule.supplement_label_ambiguous)
    carbon = row[COL_CARBON]
    nitrogen = row[COL_NITROGEN]
    if media == "M9" and not (carbon and nitrogen):
        raise ValueError(
            f"sample {row[COL_SAMPLE]}: an M9 row with no carbon or nitrogen source "
            f"({carbon!r}, {nitrogen!r})"
        )
    antibiotic = row[COL_ANTIBIOTIC]
    return EnvironmentVerdict(
        spec=ConditionSpec(
            base_media=media,
            temperature_c=float(row[COL_TEMPERATURE]),
            ph=float(row[COL_PH]),
            carbon=parse_amount(carbon, default_unit=ConcentrationUnit.g_per_l)
            if carbon
            else None,
            nitrogen=parse_amount(nitrogen, default_unit=ConcentrationUnit.g_per_l)
            if nitrogen
            else None,
            aerobicity=aerobicity,
            electron_acceptor=electron_acceptor,
            trace=row[COL_TRACE] or None,
            supplements=supplements,
            antibiotic=parse_amount(antibiotic, default_unit=None)
            if antibiotic
            else None,
        )
    )


def _concentration(amount: Amount) -> Concentration:
    """The dose of an amount; an unstated or unit-less dose is a fixed basis.

    ``DoseBasis.fixed`` is the schema's mechanism for a dose that was set but whose
    numeric value is not released in a usable form (``Concentration`` cannot be
    ``None``); the verbatim cell is kept in ``preprocess/replicate_groups.json``.
    """
    if amount.value is None:
        return Concentration(basis=DoseBasis.fixed)
    return Concentration(value=amount.value, unit=amount.unit)


def _magnitude_gap(column: str, cell: str) -> ProvenanceGap:
    return ProvenanceGap(
        field="magnitude",
        reason=ProvenanceGapReason.not_reported_by_primary,
        looked_in=metadata_provenance(column),
        note=f"the cell {cell!r} names the compound with no amount",
    )


def _source_perturbation(
    factor: PhysicalFactor, amount: Amount, column: str
) -> EnvironmentPhysicalPerturbation:
    """A carbon or nitrogen source as the varied physical factor it is here."""
    if amount.value is None:
        return EnvironmentPhysicalPerturbation(
            factor=factor,
            agent=resolved_compound(amount.name),
            provenance_gaps=[_magnitude_gap(column, amount.label)],
        )
    return EnvironmentPhysicalPerturbation(
        factor=factor,
        magnitude=Concentration(value=amount.value, unit=amount.unit),
        agent=resolved_compound(amount.name),
    )


def _medium_name(spec: ConditionSpec) -> str:
    parts = [f"{spec.base_media} (PRECISE-1K; recipe not stated)"]
    if spec.trace is not None:
        parts.append(spec.trace)
    if spec.antibiotic is not None:
        parts.append(spec.antibiotic.label)
    return " + ".join(parts)


def build_media(spec: ConditionSpec) -> Media:
    """The loader-local medium of one condition, derived from its library base key.

    The base composition is a ``composition_deferred`` component: the metadata names
    the medium and the paper prints no recipe. A trace-element mixture the metadata
    names is a deferred component too; a selection antibiotic is a defined
    ``selection_agent`` component (its compound through the resolver).
    """
    key, synthetic = LIBRARY_BASES[spec.base_media]
    components = [
        MediaComponent(
            compound=Compound(name=f"{spec.base_media} base, PRECISE-1K formulation"),
            role=MediaComponentRole.other,
            definition=ComponentDefinition.composition_deferred,
            provenance=[_metadata_cell(spec.base_media, spec.base_media, COL_MEDIA)],
            note="the release names the base medium per sample and neither it nor the "
            "paper states the recipe; the paper defers growth details to the sample "
            "metadata file, which carries labels, not compositions",
        )
    ]
    if spec.trace is not None:
        components.append(
            MediaComponent(
                compound=Compound(name=spec.trace),
                role=MediaComponentRole.trace_element,
                definition=ComponentDefinition.composition_deferred,
                provenance=[_metadata_cell(spec.trace, spec.trace, COL_TRACE)],
                note="a named trace-element stock; its composition and dose are not "
                "stated",
            )
        )
    if spec.antibiotic is not None:
        components.append(
            MediaComponent(
                compound=resolved_compound(spec.antibiotic.name),
                role=MediaComponentRole.selection_agent,
                concentration=None
                if spec.antibiotic.value is None
                else Concentration(
                    value=spec.antibiotic.value, unit=spec.antibiotic.unit
                ),
                provenance=[
                    _metadata_cell(
                        spec.antibiotic.label, spec.antibiotic.label, COL_ANTIBIOTIC
                    )
                ],
            )
        )
    return Media(
        name=_medium_name(spec),
        state="liquid",
        is_synthetic=synthetic,
        base_medium=key,
        components=components,
        provenance=[CONDITION_SPACE, COMPENDIUM],
    )


def build_environment(spec: ConditionSpec) -> Environment:
    """The ``Environment`` of one condition (identical cells give an identical object)."""
    perturbations: list[EnvironmentPerturbationType] = []
    if spec.carbon is not None:
        perturbations.append(
            _source_perturbation(PhysicalFactor.carbon_source, spec.carbon, COL_CARBON)
        )
    if spec.nitrogen is not None:
        perturbations.append(
            _source_perturbation(
                PhysicalFactor.nitrogen_source, spec.nitrogen, COL_NITROGEN
            )
        )
    perturbations.append(
        EnvironmentPhysicalPerturbation(
            factor=PhysicalFactor.ph,
            magnitude=Concentration(value=spec.ph, unit=ConcentrationUnit.ph),
            provenance_gaps=[PH_AGENT_GAP],
        )
    )
    if spec.electron_acceptor is not None:
        perturbations.append(
            SmallMoleculePerturbation(
                compound=resolved_compound(spec.electron_acceptor.name),
                concentration=_concentration(spec.electron_acceptor),
            )
        )
    for amount in spec.supplements:
        perturbations.append(
            SmallMoleculePerturbation(
                compound=resolved_compound(amount.name),
                concentration=_concentration(amount),
            )
        )
    return Environment(
        media=build_media(spec),
        temperature=Temperature(value=spec.temperature_c),
        perturbations=perturbations,
        aerobicity=spec.aerobicity,
        provenance_gaps=[DURATION_GAP],
    )


