"""Write the Hydra fragment that restricts the morphology head to the MOVING features.

A CalMorph feature MOVES under deletion when its replicate reliability (one minus the
variance across the 122 wild-type replicates over the variance across the 4,718 mutants,
`morphology_noise_ceiling.py`) is at least 0.5, that is, knockout variance at least twice
the replicate variance. On `results/morphology_feature_ceiling.csv` that is 116 of the 278
features the model predicts; the other 162 are mostly replicate noise, and training a
head on them spends capacity on targets no predictor can reach.

The fragment lists the QUIET features as `multitask.drop_features.global`, on top of the
three degenerate ones every morphology config already drops, so a config that includes it
trains and scores the global head on the 116 moving features only.

    python experiments/019-simb-multimodal/scripts/calmorph_moving_features_conf.py

Writes conf/calmorph_moving_features.yaml and results/calmorph_moving_features.json.
"""

from __future__ import annotations

import json
import os.path as osp

import pandas as pd

HERE = osp.dirname(osp.abspath(__file__))
ROOT = osp.dirname(HERE)
CEILING = osp.join(ROOT, "results", "morphology_feature_ceiling.csv")
CONF = osp.join(ROOT, "conf", "calmorph_moving_features.yaml")
OUT = osp.join(ROOT, "results", "calmorph_moving_features.json")
THRESHOLD = 0.5
DEGENERATE = ["A113_A1B", "A113_C", "C123_C"]  # dropped by every morphology config


def main() -> None:
    d = pd.read_csv(CEILING).rename(columns={"Unnamed: 0": "feature"})
    moving = sorted(d.loc[d["reliability"] >= THRESHOLD, "feature"])
    quiet = sorted(d.loc[d["reliability"] < THRESHOLD, "feature"])
    drop = sorted(set(quiet) | set(DEGENERATE))
    lines = [
        "# @package _global_",
        "# experiments/019-simb-multimodal/conf/calmorph_moving_features.yaml",
        "# GENERATED by experiments/019-simb-multimodal/scripts/calmorph_moving_features_conf.py; do not hand-edit.",
        f"# The {len(quiet)} quiet CalMorph features (replicate reliability below {THRESHOLD} in",
        f"# results/morphology_feature_ceiling.csv) plus the {len(DEGENERATE)} degenerate ones, dropped so",
        f"# the global head trains and scores on the {len(moving)} moving features only.",
        "multitask:",
        "  heads:",
        "    global:",
        f"      output_dim: {len(moving)}  # the kept features; the head's width must equal the target's",
        "  drop_features:",
        "    global:",
    ]
    lines += [f"      - {f}" for f in drop]
    with open(CONF, "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(OUT, "w") as f:
        json.dump(
            {
                "generated_by": "experiments/019-simb-multimodal/scripts/calmorph_moving_features_conf.py",
                "source": "results/morphology_feature_ceiling.csv",
                "reliability_threshold": THRESHOLD,
                "n_moving": len(moving),
                "n_quiet": len(quiet),
                "moving": moving,
                "dropped": drop,
            },
            f,
            indent=1,
        )
    print(f"moving {len(moving)}, quiet {len(quiet)}, dropped {len(drop)} -> {CONF}")


if __name__ == "__main__":
    main()
