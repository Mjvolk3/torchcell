#: A name may itself carry balanced parentheses (``(NH4)2SO4(9g/L)``); the trailing
#: parenthesized group, when there is one, is the amount.
_AMOUNT_CELL = re.compile(
    r"^(?P<name>(?:[^()]|\([^()]*\))+?)\s*(?:\((?P<amount>[^()]*)\))?$"
)
#: ``µ`` is the micro sign one public cell writes (``DPTA(250µM)``).
_AMOUNT = re.compile(r"^(?P<value>\d*\.?\d+)\s*(?P<unit>[A-Za-zµ%/]+)?$")

#: Unit token -> (typed unit, factor to that unit). mg/mL and mg/L are restated in ug/mL
#: (x1000 and x1), the enum's mass-per-volume unit, in decimal arithmetic so the restated
#: number is exact. A bare "%" is recorded as w/v, the media library's convention.
UNIT_TOKENS: dict[str, tuple[ConcentrationUnit, float]] = {
    "uM": (ConcentrationUnit.micromolar, 1),
    "mM": (ConcentrationUnit.millimolar, 1),
    "M": (ConcentrationUnit.molar, 1),
    "ug/mL": (ConcentrationUnit.ug_per_ml, 1),
    "mg/mL": (ConcentrationUnit.ug_per_ml, 1000),
    "mg/L": (ConcentrationUnit.ug_per_ml, 1),
    "%w/v": (ConcentrationUnit.percent_w_v, 1),
    "%": (ConcentrationUnit.percent_w_v, 1),
}


class Amount(BaseModel):
    """One compound named in a metadata cell, with its dose as stated."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    label: str
    name: str
    value: float | None = None
    unit: ConcentrationUnit | None = None
    unitless_value: str | None = None


def parse_amount(
    cell: str,
    *,
    default_unit: ConcentrationUnit | None,
    extra_units: Mapping[str, tuple[ConcentrationUnit, float]] | None = None,
    unitless_tokens: frozenset[str] = frozenset(),
) -> Amount:
    """Parse ``name(amount)`` (or a bare ``name``) from one metadata cell part.

    ``default_unit`` is the column's unit (``g/L`` for the carbon and nitrogen columns,
    whose headers say so); a number with no unit in a column without one is kept as
    ``unitless_value`` and never given a unit. ``extra_units`` adds unit tokens for a
    sibling release arm whose cells use spellings PRECISE-1K's own cells never do
    (measured: no PRECISE-1K cell of a parsed column carries one), each as
    ``(typed unit, factor to that unit)``.
    """
    units = {**UNIT_TOKENS, **(extra_units or {})}
    match = _AMOUNT_CELL.match(cell.strip())
    if match is None:
        raise ValueError(f"unparseable amount cell {cell!r}")
    label = match.group("name").strip()
    name = FORMULA_NAMES.get(label, label)
    amount = match.group("amount")
    if amount is None or not amount.strip():
        return Amount(label=cell.strip(), name=name)
    quantity = _AMOUNT.match(amount.strip().replace(" ", ""))
    if quantity is None:
        raise ValueError(f"unparseable amount {amount!r} in {cell!r}")
    number = Decimal(quantity.group("value"))
    token = quantity.group("unit")
    if token is None:
        if default_unit is None:
            return Amount(label=cell.strip(), name=name, unitless_value=amount.strip())
        return Amount(
            label=cell.strip(), name=name, value=float(number), unit=default_unit
        )
    if token in unitless_tokens:
        return Amount(label=cell.strip(), name=name, unitless_value=amount.strip())
    if token not in units:
        raise ValueError(f"unknown unit {token!r} in {cell!r}")
    unit, factor = units[token]
    return Amount(
        label=cell.strip(),
        name=name,
        value=float(number * Decimal(str(factor))),
        unit=unit,
    )


def parse_supplements(cell: str) -> tuple[Amount, ...]:
    """Every compound of a ``Supplement`` cell; ``a + b`` and ``a, b`` name two.

    The comma form is measured on exactly one cell, ``thiamine (1.4mM), FeCl3 (60uM)``,
    on the evolved-isolate rows #1057 stores; no other parsed cell carries ``, ``.
    """
    if not cell:
        return ()
    parts = [piece for part in cell.split(" + ") for piece in part.split(", ")]
    return tuple(parse_amount(part, default_unit=None) for part in parts)


