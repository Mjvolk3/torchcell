def t2_genotype_dose(results: str) -> None:
    axes = pd.read_csv(osp.join(results, "store_axes.csv"))
    rows = []
    for _, r in axes.iterrows():
        dose = dict(item.rsplit(":", 1) for item in r["functional_dose"].split("|"))
        rows.append(
            {
                "dataset": r["dataset"],
                "ploidy": values_only(r["ploidy"]),
                "cells at dose 0": n(int(dose.get("0.0", 0))),
                "cells at dose 1/2": n(int(dose.get("0.5", 0))),
                "dose basis": values_only(r["dose_basis"]),
                "molar dose, percent of cells": pct(r["frac_cells_with_molar"]),
                "plan, percent of records": pct(r["plan_frac_molar"]),
            }
        )
    align = left(2.6) + left(1.3) + right(1.5) * 2 + left(2.3) + right(2.0) * 2
    write("t2-genotype-dose", tex_table(pd.DataFrame(rows), align), "store_axes.csv")


