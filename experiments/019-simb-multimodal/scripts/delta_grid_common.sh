#!/bin/bash
# experiments/019-simb-multimodal/scripts/delta_grid_common.sh
# [[experiments.019-simb-multimodal.scripts.metabolism_grid_runner]]
#
# The body shared by the four Delta metabolism grid jobs. Each experiment's `.slurm` file
# carries only its own `#SBATCH` block and four variables, then sources this and calls
# `run_grid_job`. Four near-identical 150-line launchers is how the Delta env facts (which
# conda base, which DATA_ROOT, why no singularity, why NUM_WORKERS=0) drift apart between
# jobs; there is one copy here instead.
#
# Sourced -- never executed directly. `$PROJECT_ROOT` is resolved from `SLURM_SUBMIT_DIR`
# because slurm copies the submitted script into a spool directory, so `BASH_SOURCE` inside a
# running job does NOT point at the repo.

# --------------------------------------------------------------------------------------
# DELTA ENVIRONMENT -- every value below was validated interactively on Delta, not guessed.
# --------------------------------------------------------------------------------------
PROJECT_ROOT="${SLURM_SUBMIT_DIR:-/projects/bbub/mjvolk3/torchcell}"

# DATA_ROOT is the LARGE space, not /projects (tight quota). This MUST agree with the Delta
# `.env`, because `run_training` resolves the dataset from $DATA_ROOT.
#
# IF THE DATA LIVES SOMEWHERE ELSE, SET IT AT SUBMIT TIME -- do not edit this file:
#   DELTA_DATA_ROOT=/scratch/bbub/mjvolk3/torchcell sbatch --account=... <script>
# The preflight below FAILS FAST when the dataset tree is not under the root in force, which
# is the only way this is discovered before ~20 minutes of a two-day job are spent.
DELTA_DATA_ROOT="${DELTA_DATA_ROOT:-/work/hdd/bbub/mjvolk3/torchcell}"

# THE WORKING ENV, as validated on Delta 2026-07-28: `torchcell` on /work/hdd -- NOT
# `torchcell313` (an earlier name from the July notes) and NOT Delta's stock envs, which are
# Python 3.11 and hit a SyntaxError on the repo's PEP 695 generics.
#   torch 2.8.0+cu128 / PyG 2.7.0 / torch_scatter 2.1.2+pt28cu128
#
# GOTCHA WORTH KEEPING: install into it with the env's EXPLICIT pip
# ($DELTA_CONDA_BASE/envs/$DELTA_CONDA_ENV/bin/pip). A bare `pip` on the Delta login node is
# system python3.9 and silently drops packages into ~/.local, where this env never sees them
# -- which is how a "successful" install still leaves a ModuleNotFoundError at run time.
DELTA_CONDA_BASE="${DELTA_CONDA_BASE:-/work/hdd/bbub/miniconda3}"
DELTA_CONDA_ENV="${DELTA_CONDA_ENV:-torchcell}"
DELTA_PY="$DELTA_CONDA_BASE/envs/$DELTA_CONDA_ENV/bin/python"

# NO SINGULARITY. An earlier draft wrapped every call in `singularity exec --nv
# rockylinux_9.sif`, inherited from the 019 launchers. The env actually validated on Delta
# runs NATIVELY on the host -- its torch is built against the host CUDA (2.8.0+cu128) and the
# interactive smoke test that got through the whole import chain called `$DELTA_PY` directly.
# Running a host-built CUDA wheel inside a container carrying its own driver stack is an
# untested second variable with nothing to gain here.

# DATALOADER WORKERS: 0 BY DEFAULT ON DELTA, and this is a measurement.
#
# The datamodule uses multiprocessing_context="spawn" (required: CUDA is already initialized
# in the parent, so fork would corrupt the context). Under spawn every worker is a FRESH
# interpreter that re-imports torch + PyG + torchcell from the parallel filesystem. On
# GilaHyper's local NVMe that costs seconds; on Delta the 2026-07-28 interactive smoke test
# sat in `Sanity Checking` for 38 MINUTES without reaching a single val batch. Same code,
# same dataset, 20x the startup cost -- the variable is the filesystem, not the model.
#
# 0 removes the mechanism entirely (no spawn, load in the main process), and the dataset is
# small enough that this is a real option rather than a crippled fallback: ~3.5k train rows
# at batch 128 is ~28 batches per epoch. Note this needs the `prefetch_factor` guard from
# commit 2cca6d83 -- without it num_workers=0 is not merely slow, it is UNCONSTRUCTIBLE, and
# that is what killed all 119 trials of Delta job 20556837 in ~15s apiece while the job still
# exited COMPLETED 0:0.
export NUM_WORKERS="${NUM_WORKERS:-0}"

# Seed rounds to enqueue. 12 x 8 settings = 96 runs, comfortably more than 48 h buys at the
# ~20-45 min/run measured on GilaHyper -- deliberately so, because the deadline is what stops
# the job and an under-sized queue would idle the node instead.
export GRID_ROUNDS="${GRID_ROUNDS:-12}"
# Reserve for one in-flight trial: a worker stops CLAIMING work this far before the wall
# clock, so slurm never kills a run that was nearly finished. 90 min covers the longest
# metabolism run ever recorded (91 min) with the epoch cap now at 400.
export GRID_TRIAL_MARGIN_S="${GRID_TRIAL_MARGIN_S:-5400}"

run_grid_job() {
  local exp="$1" arms="$2" base_config="$3" job_seconds="$4"

  local exp_dir="$PROJECT_ROOT/experiments/$exp"
  local optuna_dir="$exp_dir/optuna"
  # slurm does not create the --output directory; a missing one makes the job die in 0s with
  # no log at all, the single most common way a Delta submission fails silently. This mkdir
  # is a backstop for the OTHER directories -- see the header of each .slurm for the one you
  # must create by hand before submitting.
  mkdir -p "$optuna_dir" "$exp_dir/slurm/output" "$exp_dir/results"

  export DATA_ROOT="$DELTA_DATA_ROOT"
  export EXPERIMENT_ROOT="$PROJECT_ROOT/experiments"
  export PYTHONPATH="$PROJECT_ROOT:${PYTHONPATH:-}"
  export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
  export PYTHONUNBUFFERED=1
  export PYTHONWARNINGS=ignore
  # Delta compute nodes HAVE internet, so W&B is ONLINE -- no offline/sync dance.
  export WANDB__SERVICE_WAIT=600
  export GRID_CONF_DIR="$exp_dir/conf"
  export GRID_BASE_CONFIG="$base_config"
  export GRID_MANIFEST_DIR="$exp_dir/results"
  export GRID_DEADLINE_EPOCH=$(($(date +%s) + job_seconds))

  local runner="$PROJECT_ROOT/experiments/019-simb-multimodal/scripts/metabolism_grid_runner.py"
  local dataset_dir="$DATA_ROOT/data/torchcell/experiments/019-simb-multimodal/fig6_pigment_transfer"

  echo "=========================================================="
  echo "host        : $(hostname)"
  echo "job         : ${SLURM_JOB_ID:-none}   exp=$exp   arms=$arms"
  echo "project     : $PROJECT_ROOT"
  echo "DATA_ROOT   : $DATA_ROOT"
  echo "python      : $DELTA_PY"
  echo "base config : $base_config   rounds=$GRID_ROUNDS   num_workers=$NUM_WORKERS"
  echo "deadline    : $(date -d "@$GRID_DEADLINE_EPOCH" 2>/dev/null || echo "$GRID_DEADLINE_EPOCH")"
  echo "=========================================================="

  # ---- PREFLIGHT. Every check below has cost a real job. ----
  [[ -x "$DELTA_PY" ]] || {
    echo "ERROR: interpreter not found: $DELTA_PY" >&2
    echo "       set DELTA_CONDA_BASE / DELTA_CONDA_ENV at submit time." >&2
    exit 1
  }
  [[ -d "$dataset_dir" ]] || {
    echo "ERROR: dataset tree missing: $dataset_dir" >&2
    echo "       DATA_ROOT in force is '$DATA_ROOT'. If the data lives elsewhere, resubmit" >&2
    echo "       with DELTA_DATA_ROOT=<root> -- do NOT edit the launcher. Candidates seen" >&2
    echo "       on Delta: /work/hdd/bbub/mjvolk3/torchcell, /scratch/bbub/mjvolk3/torchcell." >&2
    exit 1
  }
  [[ -f "$runner" ]] || { echo "ERROR: grid runner missing: $runner" >&2; exit 1; }
  nvidia-smi --query-gpu=index,name,memory.total --format=csv,noheader
  echo "=========================================================="

  # Serialized pre-create + enqueue, so the four workers never race a fresh SQLite file's DDL
  # -- each spends >15s importing torch before it would reach create_study, and a lost race
  # there is a corrupt study rather than a retry.
  local arm
  for arm in $arms; do
    ARM="$arm" OPTUNA_STORAGE="sqlite:///$optuna_dir/optuna_${exp}_${arm}_grid.db" \
      "$DELTA_PY" "$runner" --create-only
  done

  # One worker per GPU. Four concurrent runs on four A40s, all draining the SAME queue, so a
  # fast setting does not leave its GPU idle waiting for a slow one -- which is exactly what a
  # static setting-per-GPU assignment would do.
  local dev=0
  local wid=0
  while [[ $dev -lt 4 ]]; do
    for arm in $arms; do
      [[ $dev -lt 4 ]] || break
      bash -c "
        export ARM=$arm
        export OPTUNA_STORAGE='sqlite:///$optuna_dir/optuna_${exp}_${arm}_grid.db'
        export OPTUNA_WORKER_ID=$wid
        CUDA_VISIBLE_DEVICES=$dev '$DELTA_PY' '$runner'
      " &
      dev=$((dev + 1))
      wid=$((wid + 1))
    done
  done
  wait

  echo "=========================================================="
  echo "DONE $exp ($arms)"
  echo "=========================================================="
}
